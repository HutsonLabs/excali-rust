use excali_core::restore::{
    bump_element_versions, restore_elements, ElbowArrowRequest, RestoreElementsOptions,
    RestoreEnv, StickyNoteLayout, StickyNoteLayoutRequest, TestEnv, TextDimensionsRequest,
};
use serde_json::{json, Map, Value};

fn obj(v: Value) -> Map<String, Value> {
    match v {
        Value::Object(m) => m,
        _ => panic!("not an object"),
    }
}

fn opts(repair: bool, delete_invisible: bool) -> RestoreElementsOptions {
    RestoreElementsOptions {
        repair_bindings: repair,
        delete_invisible_elements: delete_invisible,
        refresh_dimensions: false,
    }
}

fn restore_with(
    elements: Vec<Value>,
    existing: Option<Vec<Value>>,
    options: RestoreElementsOptions,
    env: &mut dyn RestoreEnv,
) -> Vec<Map<String, Value>> {
    let existing: Option<Vec<Map<String, Value>>> =
        existing.map(|e| e.into_iter().map(obj).collect());
    restore_elements(&elements, existing.as_deref(), options, env).expect("restores")
}

/// `restoreElements(elements, null, opts)` in upstream's test mode.
fn restore(elements: Vec<Value>, options: RestoreElementsOptions) -> Vec<Map<String, Value>> {
    restore_with(elements, None, options, &mut TestEnv::default())
}

fn plain() -> RestoreElementsOptions {
    RestoreElementsOptions::default()
}

fn repair() -> RestoreElementsOptions {
    opts(true, false)
}

fn ids(elements: &[Map<String, Value>]) -> Vec<Value> {
    elements.iter().map(|e| e["id"].clone()).collect()
}

fn by_id<'a>(elements: &'a [Map<String, Value>], id: &str) -> &'a Map<String, Value> {
    elements
        .iter()
        .find(|e| e["id"] == id)
        .unwrap_or_else(|| panic!("no element {id}"))
}

/// What `API.createElement` (`tests/helpers/api.ts:166-436`) builds in
/// upstream's test mode, for the fields every type shares.
fn api(ty: &str, id: &str, fields: Value) -> Value {
    let mut element = obj(json!({
        "id": id,
        "type": ty,
        "x": 0,
        "y": 0,
        "width": 100,
        "height": 100,
        "angle": 0,
        "strokeColor": "#1e1e1e",
        "backgroundColor": "transparent",
        "fillStyle": "solid",
        "strokeWidth": 2,
        "strokeStyle": "solid",
        "roughness": 1,
        "opacity": 100,
        "groupIds": [],
        "frameId": null,
        "index": null,
        "roundness": null,
        "seed": 1,
        "version": 1,
        "versionNonce": 0,
        "isDeleted": false,
        "boundElements": null,
        "updated": 1,
        "created": 1,
        "link": null,
        "locked": false
    }));
    match ty {
        "text" => element.extend(obj(json!({
            "text": "test",
            "fontSize": 20,
            "baseFontSize": null,
            "fontFamily": 5,
            "textAlign": "left",
            "verticalAlign": "top",
            "containerId": null,
            "originalText": "test",
            "autoResize": true,
            "lineHeight": 1.25,
            "labelPosition": null
        }))),
        "arrow" | "line" => {
            element.extend(obj(json!({
                "points": [[0, 0], [100, 100]],
                "startBinding": null,
                "endBinding": null,
                "startArrowhead": null,
                "endArrowhead": null
            })));
            if ty == "arrow" {
                element.insert("elbowed".into(), json!(false));
            } else {
                element.insert("polygon".into(), json!(false));
            }
        }
        "freedraw" => element.extend(obj(json!({
            "strokeWidth": 1,
            "points": [[0, 0], [10, 10]],
            "pressures": [],
            "simulatePressure": true,
            "strokeOptions": { "variability": "variable", "streamline": 0.5 }
        }))),
        "stickynote" => element.extend(obj(json!({
            "width": 250,
            "height": 250,
            "baseHeight": 250,
            "backgroundColor": "#ffdf6b",
            "roundness": { "type": 3 }
        }))),
        _ => {}
    }
    element.extend(obj(fields));
    Value::Object(element)
}

