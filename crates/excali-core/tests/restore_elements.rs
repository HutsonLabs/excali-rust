/// `syncInvalidIndices`: valid indices are kept, the rest filled between
/// their valid neighbours, each change bumping the version.
#[test]
fn invalid_indices_are_repaired() {
    let restored = restore(
        vec![
            api("rectangle", "a", json!({ "index": "a0" })),
            api("rectangle", "b", json!({ "index": null })),
            api("rectangle", "c", json!({ "index": "zzz" })),
            api("rectangle", "d", json!({ "index": "a1" })),
        ],
        plain(),
    );
    let indices: Vec<&Value> = restored.iter().map(|e| &e["index"]).collect();
    assert_eq!(indices, [&json!("a0"), &json!("a0G"), &json!("a0V"), &json!("a1")]);
    let versions: Vec<&Value> = restored.iter().map(|e| &e["version"]).collect();
    assert_eq!(versions, [&json!(1), &json!(2), &json!(2), &json!(1)]);
}

