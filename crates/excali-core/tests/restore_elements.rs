/// Records elbow re-route requests.
#[derive(Default)]
struct ElbowEnv {
    test: TestEnv,
    requests: Vec<(Value, Vec<Value>)>,
    answer: Option<Map<String, Value>>,
}

impl RestoreEnv for ElbowEnv {
    fn now(&mut self) -> f64 {
        self.test.now()
    }
    fn random_id(&mut self) -> String {
        self.test.random_id()
    }
    fn random_integer(&mut self) -> f64 {
        self.test.random_integer()
    }
    fn update_elbow_arrow_points(
        &mut self,
        request: ElbowArrowRequest<'_>,
    ) -> Option<Map<String, Value>> {
        self.requests
            .push((request.arrow["id"].clone(), request.points.to_vec()));
        self.answer.clone()
    }
}

fn elbow(id: &str, points: Value) -> Value {
    api(
        "arrow",
        id,
        json!({
            "elbowed": true,
            "points": points,
            "fixedSegments": null,
            "startIsSpecial": null,
            "endIsSpecial": null,
            "endArrowhead": "arrow"
        }),
    )
}

/// An unbound elbow arrow with a segment that is not axis-aligned is
/// re-routed from `[0, 0]` to its last point by the environment
/// (`updateElbowArrowPoints`), keeping its index; a valid one is not.
#[test]
fn invalid_unbound_elbow_arrow_is_rerouted() {
    let mut env = ElbowEnv {
        answer: Some(obj(json!({
            "points": [[0, 0], [50, 0], [50, 50], [100, 50]],
            "index": "zz"
        }))),
        ..ElbowEnv::default()
    };
    let restored = restore_with(
        vec![
            elbow("bad", json!([[0, 0], [60, 40], [100, 50]])),
            elbow("good", json!([[0, 0], [50, 0], [50, 50], [100, 50]])),
        ],
        None,
        repair(),
        &mut env,
    );
    assert_eq!(env.requests, [(json!("bad"), vec![json!([0, 0]), json!([100, 50])])]);
    assert_eq!(
        restored[0]["points"],
        json!([[0, 0], [50, 0], [50, 50], [100, 50]])
    );
    assert_eq!(restored[0]["index"], "a0");
}

