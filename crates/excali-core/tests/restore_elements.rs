/// `refreshTextDimensions` is asked for every text but a sticky label, with
/// its container.
#[test]
fn refresh_text_dimensions_with_container() {
    #[derive(Default)]
    struct TextEnv {
        test: TestEnv,
        calls: Vec<(Value, Value)>,
    }
    impl RestoreEnv for TextEnv {
        fn now(&mut self) -> f64 {
            self.test.now()
        }
        fn random_id(&mut self) -> String {
            self.test.random_id()
        }
        fn random_integer(&mut self) -> f64 {
            self.test.random_integer()
        }
        fn refresh_text_dimensions(
            &mut self,
            request: TextDimensionsRequest<'_>,
        ) -> Option<Map<String, Value>> {
            let container = request.container.map_or(Value::Null, |c| c["id"].clone());
            self.calls.push((request.text["id"].clone(), container));
            Some(obj(json!({ "width": 42, "height": 7 })))
        }
    }
    let mut env = TextEnv::default();
    let restored = restore_with(
        vec![
            api(
                "rectangle",
                "r",
                json!({ "boundElements": [{ "type": "text", "id": "t" }] }),
            ),
            api("text", "t", json!({ "containerId": "r" })),
            api("text", "free", json!({})),
            api(
                "stickynote",
                "n",
                json!({ "boundElements": [{ "type": "text", "id": "label" }] }),
            ),
            api("text", "label", json!({ "containerId": "n" })),
        ],
        None,
        RestoreElementsOptions {
            repair_bindings: true,
            refresh_dimensions: true,
            delete_invisible_elements: false,
        },
        &mut env,
    );
    assert_eq!(
        env.calls,
        [(json!("t"), json!("r")), (json!("free"), Value::Null)]
    );
    assert_eq!(by_id(&restored, "t")["width"], 42);
    assert_eq!(by_id(&restored, "label")["width"], 100);
}

/// Inputs upstream throws on fail the whole restore with V8's message.
#[test]
fn errors() {
    let err = |elements: Vec<Value>, options| {
        restore_elements(&elements, None, options, &mut TestEnv::default())
            .expect_err("throws")
            .to_string()
    };
    assert_eq!(
        err(vec![api("rectangle", "r", json!({})), Value::Null], plain()),
        "Cannot read properties of null (reading 'id')"
    );
    assert_eq!(
        err(
            vec![api("rectangle", "r", json!({ "boundElements": 5 }))],
            repair()
        ),
        "container.boundElements.slice is not a function"
    );
    let mut line = obj(api("line", "l", json!({})));
    line.remove("points");
    assert_eq!(
        err(vec![Value::Object(line)], opts(false, true)),
        "Cannot read properties of undefined (reading 'length')"
    );
}
