/// Answers `getStickyNoteLayout` with a fixed layout and records the calls.
#[derive(Default)]
struct LayoutEnv {
    test: TestEnv,
    calls: Vec<(Value, Value)>,
}

impl RestoreEnv for LayoutEnv {
    fn now(&mut self) -> f64 {
        self.test.now()
    }
    fn random_id(&mut self) -> String {
        self.test.random_id()
    }
    fn random_integer(&mut self) -> f64 {
        self.test.random_integer()
    }
    fn sticky_note_layout(
        &mut self,
        request: StickyNoteLayoutRequest<'_>,
    ) -> Option<StickyNoteLayout> {
        let text = request.text.map_or(Value::Null, |t| t["id"].clone());
        self.calls.push((request.note["id"].clone(), text));
        Some(StickyNoteLayout {
            container: obj(json!({ "height": 480, "baseHeight": 250 })),
            text: Some(obj(json!({ "fontSize": 16, "baseFontSize": 28 }))),
        })
    }
}

/// "should refit a sticky note together with its label when refreshing
/// dimensions" (restore.test.ts:342-379): the note and its label are
/// refitted together by `getStickyNoteLayout`, whose measuring the
/// environment supplies; the label is not refreshed on its own.
#[test]
fn sticky_note_refit_with_its_label() {
    let mut env = LayoutEnv::default();
    let restored = restore_with(
        vec![
            api(
                "stickynote",
                "sticky",
                json!({ "boundElements": [{ "type": "text", "id": "label" }] }),
            ),
            api(
                "text",
                "label",
                json!({ "containerId": "sticky", "fontSize": 28 }),
            ),
        ],
        None,
        RestoreElementsOptions {
            repair_bindings: true,
            refresh_dimensions: true,
            delete_invisible_elements: false,
        },
        &mut env,
    );
    assert_eq!(env.calls, [(json!("sticky"), json!("label"))]);
    let note = by_id(&restored, "sticky");
    let text = by_id(&restored, "label");
    assert_eq!(note["baseHeight"], 250);
    assert_eq!(note["height"], 480);
    assert_eq!(text["fontSize"], 16);
    assert_eq!(text["baseFontSize"], 28);
}

