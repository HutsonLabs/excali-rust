/// "bump versions of local duplicate elements when supplied"
/// (restore.test.ts:909-933).
#[test]
fn bump_versions_of_local_duplicates() {
    let mut env = TestEnv::default();
    let restored = restore_with(
        vec![api("rectangle", "rect", json!({})), api("ellipse", "ellipse", json!({}))],
        None,
        plain(),
        &mut env,
    );
    let modified = obj(api(
        "rectangle",
        "rect",
        json!({ "isDeleted": true, "version": 2, "versionNonce": 5 }),
    ));
    let before = restored[0]["versionNonce"].clone();
    let bumped = bump_element_versions(restored, Some(&[modified]), &mut env).expect("bumps");
    assert_eq!(bumped[0]["id"], "rect");
    assert_ne!(bumped[0]["versionNonce"], before);
    assert_eq!(bumped[0]["version"], 3);
    // the ellipse was re-indexed on restore: 1 + 1
    assert_eq!(bumped[1]["version"], 2);
}

/// "bump versions of local duplicate elements when supplied even if both
/// have same version" (restore.test.ts:935-970).
#[test]
fn bump_versions_on_same_version_other_nonce() {
    let once = restore(vec![api("rectangle", "rect", json!({}))], plain());
    // restored once: +1 for the index
    assert_eq!(once[0]["version"], 2);
    let twice = restore(vec![Value::Object(once[0].clone())], plain());
    // restoring it again does not re-index
    assert_eq!(twice[0]["version"], 2);
    assert_eq!(twice[0]["versionNonce"], once[0]["versionNonce"]);

    let mut modified_1 = once[0].clone();
    modified_1.insert("width".into(), json!(500));
    modified_1.insert("versionNonce".into(), json!(11));
    let mut modified_2 = twice[0].clone();
    modified_2.insert("width".into(), json!(600));
    modified_2.insert("versionNonce".into(), json!(22));
    let mut env = TestEnv::default();
    let restored = restore_with(vec![Value::Object(modified_1)], None, plain(), &mut env);
    let bumped = bump_element_versions(restored, Some(&[modified_2]), &mut env).expect("bumps");
    assert_eq!(bumped[0]["id"], "rect");
    assert_ne!(bumped[0]["versionNonce"], 11);
    assert_eq!(bumped[0]["version"], 3);
}

