// -- restoreElements' index pass, for the snapshots ------------------------------

struct Stamp;

impl ChangeStamp for Stamp {
    fn version_nonce(&mut self) -> f64 {
        0.0
    }
    fn updated(&mut self) -> f64 {
        1.0
    }
}

/// `restoreElements(elements, null)` for inputs whose only scene-level
/// change is `syncInvalidIndices`: each element restored, then indexed.
fn restore_scene(elements: Vec<Value>, opts: RestoreOptions) -> Vec<Map<String, Value>> {
    let maps: Vec<Map<String, Value>> = elements.into_iter().map(obj).collect();
    let targets = ElementsMap::new(&maps);
    let mut env = TestEnv::default();
    let mut typed: Vec<Element> = maps
        .iter()
        .filter_map(|e| restore_element(e, &targets, None, opts, &mut env).expect("restores"))
        .map(|m| Element::from_map(m).expect("the typed model reads the restored element"))
        .collect();
    sync_invalid_indices(&mut typed, &mut Stamp).expect("indices sync");
    typed.iter().map(Element::to_map).collect()
}

/// A vitest snapshot: keys in any order, `Any<Number>` fields (`seed`,
/// `versionNonce`) and `customData: undefined` left out.
fn assert_snapshot(got: &Map<String, Value>, snapshot: Value) {
    let mut got = got.clone();
    assert!(got.remove("seed").is_some_and(|s| s.is_number()));
    assert!(got.remove("versionNonce").is_some_and(|s| s.is_number()));
    assert!(!got.contains_key("customData"));
    assert_eq!(as_floats(Value::Object(got)), as_floats(snapshot));
}

/// Every number as an f64, so `2` and `2.0` (the typed model's) compare
/// equal, as they do in JS.
fn as_floats(value: Value) -> Value {
    match value {
        Value::Number(n) => n
            .as_f64()
            .and_then(serde_json::Number::from_f64)
            .map_or(Value::Null, Value::Number),
        Value::Array(items) => Value::Array(items.into_iter().map(as_floats).collect()),
        Value::Object(map) => {
            Value::Object(map.into_iter().map(|(k, v)| (k, as_floats(v))).collect())
        }
        other => other,
    }
}

