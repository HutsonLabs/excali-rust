/// The legacy `font: "<size>px <Family>"` (`restore.ts:538-544`): size by
/// `parseFloat` of the first word, family by exact name of the second (so
/// two-word names never match), unknown names Excalifont; a non-finite
/// size is 20.
#[test]
fn legacy_font_string() {
    let table: &[(&str, Value, Value)] = &[
        ("20px Virgil", json!(20), json!(1)),
        ("16px Helvetica", json!(16), json!(2)),
        ("36px Cascadia", json!(36), json!(3)),
        ("12.5px Nunito", json!(12.5), json!(6)),
        ("1e2px Assistant", json!(100), json!(10)),
        ("20px Lilita One", json!(20), json!(5)),
        ("20px virgil", json!(20), json!(5)),
        ("20px", json!(20), json!(5)),
        ("abc Virgil", json!(20), json!(1)),
        ("Infinity Virgil", json!(20), json!(1)),
        ("20px  Virgil", json!(20), json!(5)),
        ("", json!(20), json!(5)),
    ];
    for (font, size, family) in table {
        let mut element = obj(api_text("t", json!({ "font": font })));
        element.remove("fontSize");
        element.remove("fontFamily");
        let r = restore(Value::Object(element));
        assert_eq!(
            (&r["fontSize"], &r["fontFamily"]),
            (size, family),
            "{font:?}"
        );
        // The legacy key stays (upstream spreads the element back).
        assert_eq!(r["font"], json!(font));
    }
    let null_font = api_text("t", json!({ "font": null }));
    assert_eq!(
        restore_opts(null_font, RestoreOptions::default()).map(|_| ()),
        Err(RestoreError::FontNull)
    );
    let number_font = api_text("t", json!({ "font": 20 }));
    assert_eq!(
        restore_opts(number_font, RestoreOptions::default()).map(|_| ()),
        Err(RestoreError::FontNotString)
    );
}

