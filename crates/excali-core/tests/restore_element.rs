//! Per-type restore: `restoreElement` (`packages/excalidraw/data/restore.ts:517-752`
//! at the pinned commit 438d89861f53d8a90ad566113ecac1b83761098f; research
//! page `site/content/research/data-model.md`, section 3.4).
//!
//! The first part ports the per-element cases of upstream's
//! `packages/excalidraw/tests/data/restore.test.ts` (copied under
//! `fixtures/upstream/`), snapshots included: upstream runs them through
//! `restoreElements`, whose only per-element effect on these inputs is
//! `syncInvalidIndices` (index `a0`, `a1`, ... and the version bump that
//! comes with it), so the snapshot tests apply the crate's
//! `sync_invalid_indices` to the restored elements the same way. Scene-level
//! passes (duplicate ids, invisibly small elements, binding repair) are
//! `restoreElements`' and not ported here.
//!
//! The second part is the rules as readable tables. The exhaustive check
//! against upstream's own output is `restore::element_tests::upstream_fixture`
//! inside the crate (`fixtures/restore-element.json`, generated by
//! `tools/goldens/restore-fixtures.mjs`).

use excali_core::element::Element;
use excali_core::fractional_index::{sync_invalid_indices, ChangeStamp};
use excali_core::restore::{
    restore_element, BindingEnd, ElementsMap, LegacyBinding, LegacyBindingRequest, RestoreEnv,
    RestoreError, RestoreOptions, TestEnv, MAX_LINEAR_PX,
};
use serde_json::{json, Map, Value};

fn obj(v: Value) -> Map<String, Value> {
    match v {
        Value::Object(m) => m,
        _ => panic!("not an object"),
    }
}

/// `restoreElement(element, arrayToMap([element]), null, opts)`.
fn restore_opts(
    element: Value,
    opts: RestoreOptions,
) -> Result<Option<Map<String, Value>>, RestoreError> {
    let element = obj(element);
    let targets = ElementsMap::new(std::slice::from_ref(&element));
    restore_element(&element, &targets, None, opts, &mut TestEnv::default())
}

fn restore(element: Value) -> Map<String, Value> {
    restore_opts(element, RestoreOptions::default())
        .expect("restores")
        .expect("a restorable type")
}

fn delete_invisible() -> RestoreOptions {
    RestoreOptions {
        delete_invisible_elements: true,
    }
}

