/// "restores created=%s without substituting load or last-update time"
/// (restore.test.ts:61-92); undefined is a missing key in a file.
#[test]
fn created_is_kept() {
    for created in [json!(123), json!(0), Value::Null, json!("absent")] {
        let mut element = obj(api(
            "rectangle",
            "r",
            json!({ "index": "a0", "updated": 456 }),
        ));
        if created == "absent" {
            element.remove("created");
        } else {
            element.insert("created".into(), created.clone());
        }
        let r = restore(Value::Object(element));
        let want = if created == "absent" {
            Value::Null
        } else {
            created
        };
        assert_eq!(r["created"], want);
        assert_eq!(r["updated"], json!(456));
        assert_eq!(r["id"], json!("r"));
        // A restored element restores to itself.
        assert_eq!(restore(Value::Object(r.clone())), r);
    }
}

