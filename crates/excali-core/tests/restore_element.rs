fn oversized_linear_elements() {
    let huge_line = restore(api_linear(
        "line",
        "l",
        json!({
            "x": 419048829414166_i64, "y": 8484,
            "points": [[0, 0], [-302985021938436_i64, 0], [-838097658820234_i64, 30]]
        }),
    ));
    let huge_arrow = restore(api_linear(
        "arrow",
        "a",
        json!({ "points": [[0, 0], [900000, 0]] }),
    ));
    let normal = restore(api_linear(
        "line",
        "n",
        json!({ "points": [[0, 0], [100, 200]] }),
    ));
    for r in [&huge_line, &huge_arrow] {
        assert_eq!(r["isDeleted"], json!(true));
        assert_eq!((&r["width"], &r["height"]), (&json!(100), &json!(100)));
        assert_eq!((&r["x"], &r["y"]), (&json!(0), &json!(0)));
        assert_eq!(r["points"], json!([[0, 0], [100, 100]]));
    }
    assert_eq!(normal["isDeleted"], json!(false));
    assert_eq!(
        (&normal["width"], &normal["height"]),
        (&json!(100), &json!(200))
    );
}

