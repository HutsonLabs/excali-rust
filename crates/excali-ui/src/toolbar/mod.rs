/// A dropdown entry.
struct MenuItem {
    icon: &'static str,
    label: String,
    shortcut: Option<String>,
    test_id: &'static str,
    selected: bool,
    disabled: bool,
    badge: Option<&'static str>,
    event: ToolbarEvent,
}

/// `ExtraToolsDropdown` (`Toolbar.tsx:54-222`).
fn extra_tools_dropdown(props: &ToolbarProps<'_>) -> Element {
    let tools = props.tools;
    let active = active_type(tools);
    let is = |ty| active == Some(ty);
    let image = is(ToolType::Image);
    let frame = is(ToolType::Frame);
    let autoshape = is(ToolType::Autoshape);
    let laser = is(ToolType::Laser);
    let bucketfill = is(ToolType::Bucketfill);
    let lasso = is(ToolType::Lasso) && tools.preferred_selection_tool.tool != SelectionTool::Lasso;
    let embeddable = is(ToolType::Embeddable);
    let laser_shown = laser && !props.collaborating;
    let selected = image || frame || embeddable || autoshape || lasso || bucketfill || laser_shown;
    let trigger_icon = if image {
        "ImageIcon"
    } else if frame {
        "frameToolIcon"
    } else if embeddable {
        "EmbedIcon"
    } else if autoshape {
        "drawShapeToolIcon"
    } else if laser_shown {
        "laserPointerToolIcon"
    } else if lasso {
        "LassoIcon"
    } else if bucketfill {
        "bucketFillIcon"
    } else {
        "DotsIcon"
    };
    let labels = ShortcutLabels::EN;
    let disabled = |ty: &str| tools.is_tool_button_disabled(ty);
    let tool_item = |ty: ToolType, shortcut: Option<String>, selected: bool| MenuItem {
        icon: tool_config(ty).map_or("", |c| c.icon),
        label: toolbar_text(&format!("toolBar.{}", ty.as_str())).to_owned(),
        shortcut,
        test_id: match ty {
            ToolType::Image => "toolbar-image",
            ToolType::Frame => "toolbar-frame",
            ToolType::Embeddable => "toolbar-embeddable",
            ToolType::Autoshape => "toolbar-autoshape",
            ToolType::Laser => "toolbar-laser",
            ToolType::Bucketfill => "toolbar-bucketfill",
            _ => "toolbar-lasso",
        },
        selected,
        disabled: disabled(ty.as_str()),
        badge: None,
        event: ToolbarEvent::ExtraTool(ty),
    };
    let mut items: Vec<Option<MenuItem>> = Vec::new();
    if tools.options.image_tool {
        items.push(Some(tool_item(ToolType::Image, Some("9".into()), image)));
    }
    items.push(Some(tool_item(ToolType::Frame, Some("F".into()), frame)));
    items.push(Some(tool_item(ToolType::Embeddable, None, embeddable)));
    items.push(Some(tool_item(
        ToolType::Autoshape,
        Some(get_tool_shortcut(ToolType::Autoshape, &labels)),
        autoshape,
    )));
    items.push(Some(tool_item(ToolType::Laser, Some("K".into()), laser)));
    items.push(Some(tool_item(
        ToolType::Bucketfill,
        Some("B".into()),
        bucketfill,
    )));
    items.push(Some(tool_item(ToolType::Lasso, None, lasso)));
    // None: the "Generate" heading and the text-to-diagram slot
    items.push(None);
    items.push(Some(MenuItem {
        icon: "mermaidLogoIcon",
        label: toolbar_text("toolBar.mermaidToExcalidraw").to_owned(),
        shortcut: None,
        // upstream's test id for this entry (Toolbar.tsx:196-202)
        test_id: "toolbar-embeddable",
        selected: false,
        disabled: false,
        badge: None,
        event: ToolbarEvent::MermaidToExcalidraw,
    }));
    if props.ai_enabled && props.diagram_to_code {
        items.push(Some(MenuItem {
            icon: "MagicIcon",
            label: toolbar_text("toolBar.magicframe").to_owned(),
            shortcut: None,
            test_id: "toolbar-magicframe",
            selected: false,
            disabled: disabled("magicframe"),
            badge: Some("AI"),
            event: ToolbarEvent::MagicFrame,
        }));
    }

    let open = props.extra_tools_open;
    let trigger_id = format!("{}-extra-tools-trigger", props.id_prefix);
    let content_id = format!("{}-extra-tools-content", props.id_prefix);
    let trigger_class = class_names([
        ("App-toolbar__extra-tools-trigger", true),
        ("App-toolbar__extra-tools-trigger--selected", selected),
    ]);
    let on_toggle = props.on_event.clone();
    let trigger = Element::new("button")
        .attr("type", "button")
        .attr("id", trigger_id.clone())
        .attr("aria-haspopup", "menu")
        .attr("aria-expanded", open.to_string())
        .attr_opt("aria-controls", open.then(|| content_id.clone()))
        .attr("data-state", if open { "open" } else { "closed" })
        .attr(
            "class",
            format!("dropdown-menu-button {trigger_class} zen-mode-transition"),
        )
        .attr("data-testid", "dropdown-menu-button")
        .attr("title", toolbar_text("toolBar.extraTools"))
        // radix's trigger (react-dropdown-menu 2.1.16): a primary press
        // toggles its (here controlled) state and, while closed, keeps
        // focus off the trigger
        .on("pointerdown", move |e| {
            let Some(m) = e.dyn_ref::<MouseEvent>() else {
                return;
            };
            if m.button() == 0 && !m.ctrl_key() && !open {
                e.prevent_default();
            }
        })
        .on("keydown", |e| {
            if let Some(k) = e.dyn_ref::<KeyboardEvent>() {
                if matches!(k.key().as_str(), "Enter" | " " | "ArrowDown") {
                    e.prevent_default();
                }
            }
        })
        .on("click", move |_| {
            emit(&on_toggle, ToolbarEvent::ExtraToolsToggle)
        })
        .child(icon_node(trigger_icon));
    let mut wrapper = Element::new("div")
        .attr("class", DROPDOWN_MENU_EVENT_WRAPPER)
        .style("display", "contents")
        .child(trigger);
    if open {
        wrapper = wrapper.child(menu(props, items, &trigger_id, &content_id));
    }
    wrapper
}

/// `DropdownMenuItem` (`DropdownMenuItem.tsx`) in radix's `Menu.Item`.
fn menu_item(item: MenuItem, on_event: &Option<OnToolbarEvent>) -> Node {
    let class = format!(
        "dropdown-menu-item dropdown-menu-item-base  {}",
        if item.selected {
            "dropdown-menu-item--selected"
        } else {
            ""
        }
    );
    let class = format!("radix-menu-item {}", class.trim());
    let on_event = on_event.clone();
    let event = item.event;
    let mut el = Element::new("button")
        .attr("class", class)
        .attr("role", "menuitem")
        .attr("tabindex", "-1")
        .attr("data-orientation", "vertical")
        .attr("data-radix-collection-item", "")
        .attr("data-testid", item.test_id)
        .flag("disabled", item.disabled)
        .child(
            Element::new("div")
                .attr("class", "dropdown-menu-item__icon")
                .child(icon_node(item.icon)),
        )
        .child(
            Element::new("div")
                .attr("class", "dropdown-menu-item__text")
                .child(
                    // Ellipsify (Ellipsify.tsx)
                    Element::new("span")
                        .style("text-overflow", "ellipsis")
                        .style("overflow", "hidden")
                        .style("white-space", "nowrap")
                        .child(item.label),
                ),
        );
    if let Some(badge) = item.badge {
        el = el.child(
            Element::new("div")
                .attr("class", "dropdown-menu-item__badge")
                .child(ai_badge(badge)),
        );
    }
    if let Some(shortcut) = item.shortcut {
        el = el.child(
            Element::new("div")
                .attr("class", "dropdown-menu-item__shortcut")
                .child(shortcut),
        );
    }
    // radix's item selects on click; the content's onSelect then closes
    Node::Element(el.on("click", move |_| {
        emit(&on_event, event.clone());
        emit(&on_event, ToolbarEvent::ExtraToolsClose);
    }))
}

