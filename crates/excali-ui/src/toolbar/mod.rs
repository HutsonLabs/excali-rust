/// The open menu: radix's popper wrapper and `Menu.Content` around
/// `DropdownMenuContent`'s island (`DropdownMenuContent.tsx:92-118`).
fn menu(
    props: &ToolbarProps<'_>,
    items: Vec<Option<MenuItem>>,
    trigger_id: &str,
    content_id: &str,
) -> Element {
    let mut children: Vec<Node> = Vec::new();
    for item in items {
        match item {
            Some(item) => children.push(menu_item(item, &props.on_event)),
            None => {
                children.push(Node::Element(
                    Element::new("div")
                        .style("margin", "6px 0px")
                        .style("font-size", "14px")
                        .style("font-weight", "600")
                        .child("Generate"),
                ));
                if props.ai_enabled {
                    children.extend(props.ttd_trigger.clone());
                }
            }
        }
    }
    let container = island(
        IslandProps {
            padding: Some(2.0),
            class_name: Some("dropdown-menu-container".into()),
            ..IslandProps::default()
        },
        children,
    );
    let on_event = props.on_event.clone();
    radix_menu_content(
        "dropdown-menu App-toolbar__extra-tools-dropdown",
        trigger_id,
        content_id,
        container,
        Rc::new(move || emit(&on_event, ToolbarEvent::ExtraToolsClose)),
    )
}

/// radix's popper wrapper and `Menu.Content` (react-dropdown-menu 2.1.16)
/// around a `DropdownMenuContent`'s `container`, of class `class`: placed
/// by its trigger and focused once mounted; Escape and a press outside the
/// dropdown's wrapper ask `close`.
pub(crate) fn radix_menu_content(
    class: &str,
    trigger_id: &str,
    content_id: &str,
    container: Element,
    close: Rc<dyn Fn()>,
) -> Element {
    let on_key = close.clone();
    let trigger = trigger_id.to_owned();
    let content = Element::new("div")
        .attr("id", content_id)
        .attr("aria-labelledby", trigger_id)
        .attr("role", "menu")
        .attr("aria-orientation", "vertical")
        .attr("data-state", "open")
        .attr("data-radix-menu-content", "")
        .attr("dir", "ltr")
        .attr("data-side", "bottom")
        .attr("data-align", "end")
        .attr("class", class)
        .attr("data-testid", "dropdown-menu")
        .attr("tabindex", "-1")
        .attr("data-orientation", "vertical")
        .style("outline", "none")
        .style(
            "--radix-dropdown-menu-content-transform-origin",
            "var(--radix-popper-transform-origin)",
        )
        .style(
            "--radix-dropdown-menu-content-available-width",
            "var(--radix-popper-available-width)",
        )
        .style(
            "--radix-dropdown-menu-content-available-height",
            "var(--radix-popper-available-height)",
        )
        .style(
            "--radix-dropdown-menu-trigger-width",
            "var(--radix-popper-anchor-width)",
        )
        .style(
            "--radix-dropdown-menu-trigger-height",
            "var(--radix-popper-anchor-height)",
        )
        .on("keydown", move |e| {
            if let Some(k) = e.dyn_ref::<KeyboardEvent>() {
                menu_keydown(k, &*on_key);
            }
        })
        .child(container);
    Element::new("div")
        .attr("data-radix-popper-content-wrapper", "")
        .attr("dir", "ltr")
        .on_mount(move |wrapper| {
            place(wrapper, &trigger);
            close_on_outside_press(wrapper, close.clone());
        })
        .child(content)
}

/// The items of the open menu, in order.
fn menu_items(content: &web_sys::Element) -> Vec<web_sys::HtmlElement> {
    let Ok(list) = content.query_selector_all("[role=menuitem]:not([disabled])") else {
        return Vec::new();
    };
    (0..list.length())
        .filter_map(|i| list.item(i))
        .filter_map(|n| n.dyn_into::<web_sys::HtmlElement>().ok())
        .collect()
}

/// Keys in the menu: Escape closes (`DropdownMenuContent.tsx:63-83`), Tab
/// stays, the arrows, Home and End move focus among the items (radix's
/// `Menu.Content` and roving focus group).
fn menu_keydown(e: &KeyboardEvent, close: &dyn Fn()) {
    let key = e.key();
    if key == "Escape" {
        e.prevent_default();
        e.stop_immediate_propagation();
        close();
        return;
    }
    if key == "Tab" {
        e.prevent_default();
        return;
    }
    let Some(content) = e
        .current_target()
        .and_then(|t| t.dyn_into::<web_sys::Element>().ok())
    else {
        return;
    };
    let items = menu_items(&content);
    if items.is_empty() {
        return;
    }
    let focused = content
        .owner_document()
        .and_then(|d| d.active_element())
        .and_then(|a| {
            items
                .iter()
                .position(|i| AsRef::<web_sys::Element>::as_ref(i) == &a)
        });
    let last = items.len() - 1;
    let next = match (key.as_str(), focused) {
        ("ArrowDown", Some(i)) => (i + 1).min(last),
        ("ArrowDown", None) | ("Home", _) | ("PageUp", _) => 0,
        ("ArrowUp", Some(i)) => i.saturating_sub(1),
        ("ArrowUp", None) | ("End", _) | ("PageDown", _) => last,
        _ => return,
    };
    e.prevent_default();
    let _ = items[next].focus();
}

/// Places the popper wrapper by its trigger and focuses the menu (radix
/// focuses the content when it opens).
fn place(wrapper: &web_sys::Element, trigger_id: &str) {
    let Some(document) = wrapper.owner_document() else {
        return;
    };
    let Some(trigger) = document.get_element_by_id(trigger_id) else {
        return;
    };
    let Some(html) = wrapper.dyn_ref::<web_sys::HtmlElement>() else {
        return;
    };
    let style = html.style();
    let _ = style.set_property("position", "fixed");
    let _ = style.set_property("left", "0px");
    let _ = style.set_property("top", "0px");
    let _ = style.set_property("min-width", "max-content");
    let content = wrapper.first_element_child();
    if let Some(z) = content
        .as_ref()
        .and_then(|c| web_sys::window()?.get_computed_style(c).ok().flatten())
        .and_then(|s| s.get_property_value("z-index").ok())
    {
        let _ = style.set_property("z-index", &z);
    }
    let t = trigger.get_bounding_client_rect();
    let c = wrapper.get_bounding_client_rect();
    let (vw, vh) = web_sys::window()
        .map(|w| {
            let n = |v: Result<wasm_bindgen::JsValue, _>| v.ok().and_then(|v| v.as_f64());
            (
                n(w.inner_width()).unwrap_or(0.0),
                n(w.inner_height()).unwrap_or(0.0),
            )
        })
        .unwrap_or((0.0, 0.0));
    let placed = dropdown_position(
        Rect {
            left: t.left(),
            top: t.top(),
            width: t.width(),
            height: t.height(),
        },
        (c.width(), c.height()),
        (vw, vh),
    );
    let _ = style.set_property(
        "transform",
        &format!("translate({}px, {}px)", placed.x, placed.y),
    );
    if let Some(content) = content {
        let side = match placed.side {
            DropdownSide::Bottom => "bottom",
            DropdownSide::Top => "top",
        };
        let _ = content.set_attribute("data-side", side);
        if let Some(c) = content.dyn_ref::<web_sys::HtmlElement>() {
            let opts = web_sys::FocusOptions::new();
            opts.set_prevent_scroll(true);
            let _ = c.focus_with_options(&opts);
        }
    }
}

/// Asks to close on a press outside the dropdown's wrapper (the trigger
/// toggles itself) while the menu is in the document (`useOutsideClick`,
/// `DropdownMenuContent.tsx:48-61`).
fn close_on_outside_press(wrapper: &web_sys::Element, close: Rc<dyn Fn()>) {
    let Some(document) = wrapper.owner_document() else {
        return;
    };
    let slot: Rc<RefCell<Option<js_sys::Function>>> = Rc::default();
    let own = slot.clone();
    let menu = wrapper.clone();
    let target = document.clone();
    let closure = Closure::<dyn FnMut(Event)>::new(move |e: Event| {
        if !menu.is_connected() {
            if let Some(f) = own.borrow_mut().take() {
                let _ = target.remove_event_listener_with_callback("pointerdown", &f);
                let _ = target.remove_event_listener_with_callback("touchstart", &f);
            }
            return;
        }
        let node = e.target().and_then(|t| t.dyn_into::<web_sys::Node>().ok());
        let Some(node) = node else {
            return;
        };
        if menu.contains(Some(&node))
            || !target
                .document_element()
                .is_some_and(|d| d.contains(Some(&node)))
        {
            return;
        }
        let in_wrapper = menu
            .closest(&format!(".{DROPDOWN_MENU_EVENT_WRAPPER}"))
            .ok()
            .flatten()
            .is_some_and(|w| w.contains(Some(&node)));
        if !in_wrapper {
            close();
        }
    });
    let f: js_sys::Function = closure.into_js_value().unchecked_into();
    let _ = document.add_event_listener_with_callback("pointerdown", &f);
    let _ = document.add_event_listener_with_callback("touchstart", &f);
    *slot.borrow_mut() = Some(f);
}

// -- placement ----------------------------------------------------------------

/// The side of the trigger the menu opened on.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DropdownSide {
    Bottom,
    Top,
}

/// Where the menu goes: its top-left corner in the viewport and its side.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct DropdownPlacement {
    pub x: f64,
    pub y: f64,
    pub side: DropdownSide,
}

/// The menu's placement for a trigger rect, the menu's size and the
/// viewport, as radix's Popper places `DropdownMenuContent` (side bottom,
/// `align="end"`, `sideOffset={8}`, collisions avoided with no padding)
/// through floating-ui: below the trigger with the right edges aligned,
/// flipped above when it overflows below and fits there (else on the side
/// that overflows less, below on a tie), then shifted horizontally into
/// the viewport.
pub fn dropdown_position(
    trigger: Rect,
    content: (f64, f64),
    viewport: (f64, f64),
) -> DropdownPlacement {
    let (width, height) = content;
    let below = trigger.top + trigger.height + DROPDOWN_SIDE_OFFSET;
    let above = trigger.top - DROPDOWN_SIDE_OFFSET - height;
    let overflow_below = (below + height - viewport.1).max(0.0);
    let overflow_above = (-above).max(0.0);
    let side = if overflow_below > 0.0 && overflow_above < overflow_below {
        DropdownSide::Top
    } else {
        DropdownSide::Bottom
    };
    let y = match side {
        DropdownSide::Bottom => below,
        DropdownSide::Top => above,
    };
    let x = trigger.left + trigger.width - width;
    let x = x.min(viewport.0 - width).max(0.0);
    DropdownPlacement { x, y, side }
}

// -- activation ---------------------------------------------------------------

fn set_tool(tools: &mut ToolState, ty: ToolType) -> Result<ToolSwitch, ToolRefusal> {
    tools.set_active_tool(
        ToolRequest::new(Tool::Builtin(ty)),
        SetActiveToolOptions::default(),
    )
}

/// A tool button's `onSelect` (`Tools.tsx:300-316`, the selection button's
/// :340-352): the first pen press turns pen mode on; pointer-clicking the
/// active selection tool switches to the lasso; any other button activates
/// its tool unless it is already active (`None` when nothing is asked of
/// `setActiveTool`).
pub fn activate_tool_button(
    tools: &mut ToolState,
    ty: ToolType,
    pointer: Option<PointerType>,
) -> Option<Result<ToolSwitch, ToolRefusal>> {
    if !tools.pen_detected && pointer == Some(PointerType::Pen) {
        tools.toggle_pen_mode(Some(true));
    }
    let active = active_type(tools);
    if ty == ToolType::Selection && active == Some(ToolType::Selection) && pointer.is_some() {
        return Some(set_tool(tools, ToolType::Lasso));
    }
    if active == Some(ty) {
        return None;
    }
    Some(set_tool(tools, ty))
}

/// A dropdown tool item's `onSelect` (`Toolbar.tsx:124-189`): activates its
/// tool.
pub fn activate_extra_tool(tools: &mut ToolState, ty: ToolType) -> Result<ToolSwitch, ToolRefusal> {
    set_tool(tools, ty)
}
