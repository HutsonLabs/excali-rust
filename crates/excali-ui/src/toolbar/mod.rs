//! The shapes toolbar: the desktop `Toolbar` island and its
//! `ExtraToolsDropdown` (`components/Toolbar.tsx`), with the tool buttons
//! of `components/Tools.tsx` (`createToolButton`, `LockButton.tsx`,
//! `PenModeButton.tsx`) and the dropdown menu they open
//! (`components/dropdownMenu/*` over radix-ui's `DropdownMenu`).
//!
//! Order and grouping (`Toolbar.tsx:262-323`, research
//! `ui-design-system.md` §3.1): pen mode (once a pen is detected), lock,
//! divider, hand, selection (or lasso when preferred), rectangle, diamond,
//! ellipse, arrow, line, freedraw, text, sticky note, eraser, divider, the
//! "More tools" dropdown: image, frame, embeddable, autoshape, laser,
//! bucket fill, lasso, then "Generate" (the host's text-to-diagram
//! trigger, Mermaid to Excalidraw, Wireframe to code). Tooltips read
//! "Label — R or 2" (`getToolShortcut`).
//!
//! [`toolbar`] builds the DOM upstream leaves (`tests/toolbar.rs` holds
//! every case of `tests/fixtures/toolbar.json` to it), radix's attributes
//! included; its listeners report [`ToolbarEvent`]s, which the host applies
//! with [`activate_tool_button`], [`activate_extra_tool`] and the tool
//! state's `toggle_lock` / `toggle_pen_mode`, re-rendering with
//! [`ToolbarProps::extra_tools_open`] as the dropdown's state. The styles
//! are upstream's `Toolbar.scss` and `DropdownMenu.scss` compiled
//! ([`TOOLBAR_CSS`]).
//!
//! Not ported here: the compact (tablet) toolbar's selection and freedraw
//! popovers (`ToolPopover`), the HintViewer (ex-528) and the
//! text-to-diagram trigger, which the host passes in as slots, and the
//! collaboration laser island (`LayerUI.tsx:374-393`). Of radix's menu
//! behaviour the port keeps the trigger's press handling, focus on open,
//! arrow-key focus among the items and its placement ([`dropdown_position`]).

