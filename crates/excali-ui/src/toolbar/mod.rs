/// The desktop toolbar island (`Toolbar`, `Toolbar.tsx:226-326`) in full
/// styles-panel mode.
pub fn toolbar(props: ToolbarProps<'_>) -> Element {
    let tools = props.tools;
    let forced = tools.options.forced_tool.is_some();
    let mut row: Vec<Node> = Vec::new();
    row.extend(pen_mode_button(&props));
    if !forced {
        row.push(lock_button(&props));
        row.push(divider("margin-right"));
    }
    row.push(tool_button(&props, ToolType::Hand, ToolType::Hand, true));
    if tools.preferred_selection_tool.tool == SelectionTool::Lasso {
        row.push(tool_button(
            &props,
            ToolType::Lasso,
            ToolType::Selection,
            false,
        ));
    } else {
        row.push(tool_button(
            &props,
            ToolType::Selection,
            ToolType::Selection,
            false,
        ));
    }
    for ty in [
        ToolType::Rectangle,
        ToolType::Diamond,
        ToolType::Ellipse,
        ToolType::Arrow,
        ToolType::Line,
        ToolType::Freedraw,
        ToolType::Text,
        ToolType::Stickynote,
        ToolType::Eraser,
    ] {
        row.push(tool_button(&props, ty, ty, false));
    }
    row.push(divider("margin-left"));
    row.push(Node::Element(extra_tools_dropdown(&props)));
    let mut children: Vec<Node> = Vec::new();
    children.extend(props.hint_viewer.clone());
    children.push(Node::Element(stack_row(
        StackProps {
            gap: Some(1.0),
            ..StackProps::default()
        },
        row,
    )));
    island(
        IslandProps {
            padding: Some(1.0),
            class_name: Some(class_names([
                ("App-toolbar", true),
                ("zen-mode", props.zen_mode),
            ])),
            viewport_ui: Some("top".into()),
            ..IslandProps::default()
        },
        children,
    )
}

