//! The chrome's building blocks, as upstream's hand-rolled UI kit has them
//! (`site/content/research/ui-design-system.md` §9): [`island`],
//! [`stack_row`] / [`stack_col`], [`button`], [`icon_button`] (the
//! `ToolIcon` button every toolbar uses), [`radio_group`], [`range`],
//! [`text_field`], [`popover`], [`modal`] and [`dialog`], and [`tooltip`].
//!
//! Upstream counterpart: `packages/excalidraw/components/Island.tsx`,
//! `Stack.tsx`, `Button.tsx`, `IconButton.tsx`, `RadioGroup.tsx`,
//! `Range.tsx`, `TextField.tsx`, `Popover.tsx`, `Modal.tsx`, `Dialog.tsx`
//! and `Tooltip.tsx`, and their stylesheets.
//!
//! Each primitive is a function from props to an [`Element`](crate::dom::Element)
//! with upstream's class names, attributes and inline style
//! (`tests/ui_primitives.rs` holds every one to the DOM React leaves for
//! upstream's component); behaviour that needs the document (focus, the
//! tooltip div, the modal portal) runs from the element's listeners and
//! mount hooks. The styles are upstream's SCSS compiled
//! ([`PRIMITIVES_CSS`]), sized by the design system's tokens
//! ([`SIZE_TOKENS`]): 2rem buttons, 1rem icons, a 0.25rem space factor,
//! radii of 0.375rem and 0.5rem. They apply inside an element with the
//! class `excalidraw` (the editor container; a modal's portal container
//! carries it too).

