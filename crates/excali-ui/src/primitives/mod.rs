/// Upstream's `css/theme.scss` and the primitives' stylesheets, compiled
/// (generated by `tools/goldens/ui-primitives.mjs`).
pub const PRIMITIVES_CSS: &str = include_str!("primitives.css");

/// The `data-excali-ui` value of the `<style>` holding [`PRIMITIVES_CSS`].
const STYLESHEET_ID: &str = "primitives";

/// Adds [`PRIMITIVES_CSS`] to `document`'s head once.
pub fn install_stylesheet(document: &Document) -> Result<(), JsValue> {
    let selector = format!("style[data-excali-ui=\"{STYLESHEET_ID}\"]");
    if document.query_selector(&selector)?.is_some() {
        return Ok(());
    }
    let style = document.create_element("style")?;
    style.set_attribute("data-excali-ui", STYLESHEET_ID)?;
    style.set_text_content(Some(PRIMITIVES_CSS));
    let head = document
        .head()
        .ok_or_else(|| JsValue::from_str("the document has no head"))?;
    head.append_child(&style)?;
    Ok(())
}

/// `${n}px`, as React writes a number into a pixel style.
pub(crate) fn px(n: f64) -> String {
    format!("{}px", excali_core::json::number_to_string(n))
}

/// A number as React writes it into an attribute or a custom property
/// (`String(n)`).
pub(crate) fn number(n: f64) -> String {
    excali_core::json::number_to_string(n)
}

/// `queryFocusableElements` (`packages/common/src/utils.ts:715-726`): the
/// buttons, links, inputs, selects, textareas and tabindexed divs and
/// labels in `container`, without negative tab indices or disabled form
/// controls (`element.disabled`, which only form controls have).
pub(crate) fn focusable_elements(container: &web_sys::Element) -> Vec<web_sys::HtmlElement> {
    use wasm_bindgen::JsCast;
    let Ok(list) = container
        .query_selector_all("button, a, input, select, textarea, div[tabindex], label[tabindex]")
    else {
        return Vec::new();
    };
    (0..list.length())
        .filter_map(|i| list.item(i))
        .filter_map(|n| n.dyn_into::<web_sys::HtmlElement>().ok())
        .filter(|el| {
            let control = matches!(
                el.local_name().as_str(),
                "button" | "input" | "select" | "textarea"
            );
            el.tab_index() > -1 && !(control && el.has_attribute("disabled"))
        })
        .collect()
}
