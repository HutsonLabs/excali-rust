/// The toolbar's popovers (`ToolPopover`).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum ToolPopover {
    /// Selection and lasso (`SelectionToolPopover`, `Tools.tsx:373-420`).
    Selection,
    /// Freedraw and draw to shape (`FreedrawToolPopover`, `Tools.tsx:426-476`).
    Freedraw,
    /// Rectangle, diamond and ellipse (`MobileToolbar.tsx:184-205`).
    Shapes,
    /// Arrow and line (`MobileToolbar.tsx:208-230`).
    Linear,
}

impl ToolPopover {
    pub const ALL: [ToolPopover; 4] = [
        ToolPopover::Selection,
        ToolPopover::Freedraw,
        ToolPopover::Shapes,
        ToolPopover::Linear,
    ];

    /// The popover's options, in order.
    pub fn options(self) -> &'static [ToolType] {
        match self {
            ToolPopover::Selection => &[ToolType::Selection, ToolType::Lasso],
            ToolPopover::Freedraw => &[ToolType::Freedraw, ToolType::Autoshape],
            ToolPopover::Shapes => &[ToolType::Rectangle, ToolType::Diamond, ToolType::Ellipse],
            ToolPopover::Linear => &[ToolType::Arrow, ToolType::Line],
        }
    }

    /// The trigger's `data-testid`.
    pub fn test_id(self) -> &'static str {
        match self {
            ToolPopover::Selection => "toolbar-selection",
            ToolPopover::Freedraw => "toolbar-freedraw",
            ToolPopover::Shapes => "toolbar-rectangle",
            ToolPopover::Linear => "toolbar-arrow",
        }
    }

    fn id(self) -> &'static str {
        match self {
            ToolPopover::Selection => "selection",
            ToolPopover::Freedraw => "freedraw",
            ToolPopover::Shapes => "shapes",
            ToolPopover::Linear => "linear",
        }
    }
}

/// What the toolbar keeps between renders (React state upstream).
#[derive(Clone, Debug, PartialEq)]
pub struct MobileToolbarState {
    /// Its measured width (`toolbarWidth`; 0 until measured).
    pub width: f64,
    /// "…" is open (`isOtherShapesMenuOpen`).
    pub extra_tools_open: bool,
    /// The open popover (each `ToolPopover`'s `isPopupOpen`).
    pub open_popover: Option<ToolPopover>,
    /// The shapes popover's remembered option (`lastActiveGenericShape`).
    pub last_shape: ToolType,
    /// The arrow/line popover's (`lastActiveLinearElement`).
    pub last_linear: ToolType,
    /// The freedraw popover's (`lastDrawingTool`).
    pub last_drawing: ToolType,
}

impl MobileToolbarState {
    /// The state after the first render with `tools`.
    pub fn new(tools: &ToolState) -> MobileToolbarState {
        let mut state = MobileToolbarState {
            width: 0.0,
            extra_tools_open: false,
            open_popover: None,
            last_shape: ToolType::Rectangle,
            last_linear: ToolType::Arrow,
            last_drawing: ToolType::Freedraw,
        };
        state.sync(tools);
        state
    }

    /// Follows the active tool, however it changed: each popover
    /// remembers it when it is one of its options (the toolbar's and
    /// `FreedrawToolPopover`'s effects), and an open popover whose options
    /// do not hold it closes (`ToolPopover.tsx:52-55`).
    pub fn sync(&mut self, tools: &ToolState) {
        let Some(active) = tools.active_tool.tool.builtin() else {
            self.open_popover = None;
            return;
        };
        match active {
            ToolType::Rectangle | ToolType::Diamond | ToolType::Ellipse => self.last_shape = active,
            ToolType::Arrow | ToolType::Line => self.last_linear = active,
            ToolType::Freedraw | ToolType::Autoshape => self.last_drawing = active,
            _ => {}
        }
        if let Some(open) = self.open_popover {
            if !open.options().contains(&active) {
                self.open_popover = None;
            }
        }
    }

    /// Closes the popovers (a press on the canvas).
    pub fn close_popovers(&mut self) {
        self.open_popover = None;
    }

    /// The option a popover's trigger shows and activates.
    pub fn displayed(&self, popover: ToolPopover, tools: &ToolState) -> ToolType {
        match popover {
            ToolPopover::Selection => tools.preferred_selection_tool.tool.tool_type(),
            ToolPopover::Freedraw => self.last_drawing,
            ToolPopover::Shapes => self.last_shape,
            ToolPopover::Linear => self.last_linear,
        }
    }
}

/// A popover's `onToolChange(type)`: the selection popover makes its
/// option the preferred selection tool (`Tools.tsx:406-414`); the others
/// remember it (`MobileToolbar.tsx:192-201, 216-224`, `Tools.tsx:465-470`);
/// all activate it.
fn tool_change(
    state: &mut MobileToolbarState,
    tools: &mut ToolState,
    popover: ToolPopover,
    ty: ToolType,
) -> Result<ToolSwitch, ToolRefusal> {
    match popover {
        ToolPopover::Selection => {
            let result = set_tool(tools, ty);
            tools.preferred_selection_tool.tool = if ty == ToolType::Lasso {
                SelectionTool::Lasso
            } else {
                SelectionTool::Selection
            };
            tools.preferred_selection_tool.initialized = true;
            result
        }
        ToolPopover::Freedraw => {
            state.last_drawing = ty;
            set_tool(tools, ty)
        }
        ToolPopover::Shapes => {
            state.last_shape = ty;
            set_tool(tools, ty)
        }
        ToolPopover::Linear => {
            state.last_linear = ty;
            set_tool(tools, ty)
        }
    }
}

/// Applies a toolbar event to the toolbar's state and the tool state, as
/// upstream's handlers do, and syncs the state to the tool it leaves
/// active. Returns what `setActiveTool` answered, when it was asked.
/// `ExtraToolsToggle` also asks the host to close its menus and popups
/// (`setAppState({ openMenu: null, openPopup: null })`); `MermaidToExcalidraw`
/// and `MagicFrame` are the host's; `PenMode`, `Lock` and
/// `ToolButtonPointerDown` are not the phone toolbar's.
pub fn apply_toolbar_event(
    state: &mut MobileToolbarState,
    tools: &mut ToolState,
    event: &ToolbarEvent,
) -> Option<Result<ToolSwitch, ToolRefusal>> {
    let result = match event {
        ToolbarEvent::ToolButton { tool, pointer_type } => {
            activate_tool_button(tools, *tool, *pointer_type)
        }
        ToolbarEvent::ExtraToolsToggle => {
            state.extra_tools_open = !state.extra_tools_open;
            None
        }
        ToolbarEvent::ExtraToolsClose => {
            state.extra_tools_open = false;
            None
        }
        ToolbarEvent::ExtraTool(ty) => Some(activate_extra_tool(tools, *ty)),
        ToolbarEvent::ToolPopoverTrigger(popover) => {
            state.open_popover = if state.open_popover == Some(*popover) {
                None
            } else {
                Some(*popover)
            };
            let ty = state.displayed(*popover, tools);
            Some(tool_change(state, tools, *popover, ty))
        }
        ToolbarEvent::ToolPopoverOption(popover, ty) => {
            if tools.active_tool.tool.builtin() == Some(*ty) {
                None
            } else {
                // setActiveTool, then onToolChange (ToolPopover.tsx:94-101)
                let _ = set_tool(tools, *ty);
                Some(tool_change(state, tools, *popover, *ty))
            }
        }
        ToolbarEvent::MobileToolbarWidth(width) => {
            state.width = *width;
            None
        }
        ToolbarEvent::ToolButtonPointerDown { .. }
        | ToolbarEvent::PenMode
        | ToolbarEvent::Lock
        | ToolbarEvent::MermaidToExcalidraw
        | ToolbarEvent::MagicFrame => None,
    };
    state.sync(tools);
    result
}

/// App.tsx:3660-3683 on load: an uninitialized preferred selection tool
/// becomes the lasso on a phone and the selection elsewhere, and a
/// restored selection, lasso or image tool becomes the preferred one.
pub fn init_selection_tool(tools: &mut ToolState, form_factor: FormFactor) {
    let preferred = &mut tools.preferred_selection_tool;
    if !preferred.initialized {
        preferred.tool = if form_factor == FormFactor::Phone {
            SelectionTool::Lasso
        } else {
            SelectionTool::Selection
        };
        preferred.initialized = true;
    }
    let tool = preferred.tool.tool_type();
    if matches!(
        tools.active_tool.tool.builtin(),
        Some(ToolType::Image | ToolType::Lasso | ToolType::Selection)
    ) {
        tools.active_tool.tool = Tool::Builtin(tool);
    }
}

