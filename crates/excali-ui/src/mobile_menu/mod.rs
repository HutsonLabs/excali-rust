/// A popover option's label: the trigger's is the tool's
/// (`capitalizeString(t("toolBar.<type>"))`), an option's its type
/// (`capitalizeString(type)`, `ToolPopover.tsx:90-91`).
fn trigger_title(ty: ToolType) -> String {
    capitalize(toolbar_text(&format!("toolBar.{}", ty.as_str())))
}

fn fillable(ty: ToolType) -> &'static str {
    if tool_config(ty).is_some_and(|c| c.is_fillable()) {
        "fillable"
    } else {
        ""
    }
}

/// `ToolPopover` (`ToolPopover.tsx:39-113`): the trigger showing the
/// remembered option and, while open, radix's popper wrapper around the
/// options.
fn tool_popover(props: &MobileToolbarProps<'_>, popover: ToolPopover, out: &mut Vec<Node>) {
    let tools = props.tools;
    let active = tools.active_tool.tool.builtin();
    let displayed = props.state.displayed(popover, tools);
    let title = trigger_title(displayed);
    let on_trigger = props.on_event.clone();
    out.push(Node::Element(icon_button(IconButtonProps {
        kind: IconButtonKind::Toggle {
            checked: active == Some(displayed),
        },
        class_name: fillable(displayed).into(),
        icon: Some(tool_icon(displayed)),
        disabled: popover
            .options()
            .iter()
            .all(|o| tools.is_tool_button_disabled(o.as_str())),
        title: Some(title.clone()),
        aria_label: title,
        test_id: Some(popover.test_id().into()),
        on_select: Some(Rc::new(move |_| {
            emit(&on_trigger, ToolbarEvent::ToolPopoverTrigger(popover))
        })),
        ..IconButtonProps::default()
    })));
    if props.state.open_popover != Some(popover) {
        return;
    }
    let options = popover.options().iter().map(|&ty| {
        let label = capitalize(ty.as_str());
        let on_option = props.on_event.clone();
        Node::Element(icon_button(IconButtonProps {
            kind: IconButtonKind::Toggle {
                checked: active == Some(ty),
            },
            class_name: fillable(ty).into(),
            icon: Some(tool_icon(ty)),
            disabled: tools.is_tool_button_disabled(ty.as_str()),
            title: Some(label.clone()),
            aria_label: label,
            test_id: Some(format!("toolbar-{}", ty.as_str())),
            on_select: Some(Rc::new(move |_| {
                emit(&on_option, ToolbarEvent::ToolPopoverOption(popover, ty))
            })),
            ..IconButtonProps::default()
        }))
    });
    let content = Element::new("div")
        .attr("class", "tool-popover-content")
        .attr(
            "id",
            format!("{}-tool-popover-{}", props.id_prefix, popover.id()),
        )
        .attr("role", "dialog")
        .attr("tabindex", "-1")
        .attr("data-state", "open")
        .attr("data-side", "bottom")
        .attr("data-align", "center")
        .style(
            "--radix-popover-content-transform-origin",
            "var(--radix-popper-transform-origin)",
        )
        .style(
            "--radix-popover-content-available-width",
            "var(--radix-popper-available-width)",
        )
        .style(
            "--radix-popover-content-available-height",
            "var(--radix-popper-available-height)",
        )
        .style(
            "--radix-popover-trigger-width",
            "var(--radix-popper-anchor-width)",
        )
        .style(
            "--radix-popover-trigger-height",
            "var(--radix-popper-anchor-height)",
        )
        .children_from(options);
    out.push(Node::Element(
        Element::new("div")
            .attr("data-radix-popper-content-wrapper", "")
            .on_mount(place_tool_popover)
            .child(content),
    ));
}

/// `sideOffset` of the tool popovers (`ToolPopover.tsx:47`).
pub const TOOL_POPOVER_SIDE_OFFSET: f64 = 16.0;

/// A tool popover's placement for its trigger rect and size within the
/// editor container (`boundary`), as radix's Popper places
/// `Popover.Content` (side bottom, align center, `sideOffset={16}`,
/// `collisionBoundary` the container) through floating-ui: below the
/// trigger and centred on it, flipped above when it overflows the
/// container below and less so above (on a phone's bottom bar, always),
/// then shifted horizontally into the container.
pub fn tool_popover_position(
    trigger: Rect,
    content: (f64, f64),
    boundary: Rect,
) -> DropdownPlacement {
    let (width, height) = content;
    let below = trigger.top + trigger.height + TOOL_POPOVER_SIDE_OFFSET;
    let above = trigger.top - TOOL_POPOVER_SIDE_OFFSET - height;
    let bottom = boundary.top + boundary.height;
    let overflow_below = (below + height - bottom).max(0.0);
    let overflow_above = (boundary.top - above).max(0.0);
    let side = if overflow_below > 0.0 && overflow_above < overflow_below {
        DropdownSide::Top
    } else {
        DropdownSide::Bottom
    };
    let y = match side {
        DropdownSide::Bottom => below,
        DropdownSide::Top => above,
    };
    let x = trigger.left + trigger.width / 2.0 - width / 2.0;
    let x = x
        .min(boundary.left + boundary.width - width)
        .max(boundary.left);
    DropdownPlacement { x, y, side }
}

fn rect_of(el: &web_sys::Element) -> Rect {
    let r = el.get_bounding_client_rect();
    Rect {
        left: r.left(),
        top: r.top(),
        width: r.width(),
        height: r.height(),
    }
}

/// Places a mounted popover's wrapper by its trigger (the button before
/// it) within the editor container.
fn place_tool_popover(wrapper: &web_sys::Element) {
    use wasm_bindgen::JsCast;
    let Some(trigger) = wrapper.previous_element_sibling() else {
        return;
    };
    let Some(html) = wrapper.dyn_ref::<web_sys::HtmlElement>() else {
        return;
    };
    let style = html.style();
    let _ = style.set_property("position", "fixed");
    let _ = style.set_property("left", "0px");
    let _ = style.set_property("top", "0px");
    let _ = style.set_property("min-width", "max-content");
    let boundary = wrapper
        .closest(".excalidraw")
        .ok()
        .flatten()
        .map(|c| rect_of(&c))
        .unwrap_or_else(|| {
            let n = |v: Result<wasm_bindgen::JsValue, _>| v.ok().and_then(|v| v.as_f64());
            let (w, h) = web_sys::window()
                .map(|w| {
                    (
                        n(w.inner_width()).unwrap_or(0.0),
                        n(w.inner_height()).unwrap_or(0.0),
                    )
                })
                .unwrap_or((0.0, 0.0));
            Rect {
                left: 0.0,
                top: 0.0,
                width: w,
                height: h,
            }
        });
    let c = wrapper.get_bounding_client_rect();
    let placed = tool_popover_position(rect_of(&trigger), (c.width(), c.height()), boundary);
    let _ = style.set_property(
        "transform",
        &format!("translate({}px, {}px)", placed.x, placed.y),
    );
    if let Some(content) = wrapper.first_element_child() {
        let side = match placed.side {
            DropdownSide::Bottom => "bottom",
            DropdownSide::Top => "top",
        };
        let _ = content.set_attribute("data-side", side);
    }
}

/// The "…" trigger's icon: the active tool's when it is in "…"
/// (`MobileToolbar.tsx:116-159`).
fn extra_icon(active: Option<ToolType>, in_menu: bool) -> &'static str {
    if !in_menu {
        return "DotsIcon";
    }
    match active {
        Some(ToolType::Text) => "TextIcon",
        Some(ToolType::Image) => "ImageIcon",
        Some(ToolType::Frame) => "frameToolIcon",
        Some(ToolType::Stickynote) => "stickyNoteToolIcon",
        Some(ToolType::Embeddable) => "EmbedIcon",
        Some(ToolType::Laser) => "laserPointerToolIcon",
        Some(ToolType::Bucketfill) => "bucketFillIcon",
        Some(ToolType::Magicframe) => "MagicIcon",
        _ => "DotsIcon",
    }
}

/// "…" (`MobileToolbar.tsx:243-373`): the trigger and, while open, the
/// menu of the tools not shown as buttons and "Generate".
fn extra_tools(props: &MobileToolbarProps<'_>, outside: ToolsOutside) -> Element {
    let tools = props.tools;
    let active = tools.active_tool.tool.builtin();
    let in_menu = active.is_some_and(|a| {
        matches!(
            a,
            ToolType::Stickynote
                | ToolType::Embeddable
                | ToolType::Laser
                | ToolType::Bucketfill
                | ToolType::Magicframe
        ) || (a == ToolType::Text && !outside.text)
            || (a == ToolType::Frame && !outside.frame)
    });
    let open = props.state.extra_tools_open;
    let trigger_id = format!("{}-extra-tools-trigger", props.id_prefix);
    let content_id = format!("{}-extra-tools-content", props.id_prefix);
    let class = class_names([
        ("dropdown-menu-button", true),
        ("App-toolbar__extra-tools-trigger", true),
        ("App-toolbar__extra-tools-trigger--mobile", true),
        (
            "App-toolbar__extra-tools-trigger--selected",
            in_menu || open,
        ),
        ("zen-mode-transition", true),
        ("dropdown-menu-button--mobile", true),
    ]);
    let size = format!("{TOOL_SIZE}px");
    let trigger = extra_tools_trigger(
        &trigger_id,
        &content_id,
        open,
        class,
        extra_icon(active, in_menu),
        &props.on_event,
    )
    .style("width", size.clone())
    .style("height", size)
    .style("display", "flex")
    .style("align-items", "center")
    .style("justify-content", "center");
    let mut wrapper = Element::new("div")
        .attr("class", DROPDOWN_MENU_EVENT_WRAPPER)
        .style("display", "contents")
        .child(trigger);
    if open {
        wrapper = wrapper.child(extra_tools_menu(props, outside, &trigger_id, &content_id));
    }
    wrapper
}

fn extra_tools_menu(
    props: &MobileToolbarProps<'_>,
    outside: ToolsOutside,
    trigger_id: &str,
    content_id: &str,
) -> Element {
    let tools = props.tools;
    let active = tools.active_tool.tool.builtin();
    // a phone's menu items show no shortcut (DropdownMenuItemContent.tsx:28)
    let item = |ty: ToolType, test_id: &'static str| MenuItem {
        icon: tool_config(ty).map_or("", |c| c.icon),
        label: toolbar_text(&format!("toolBar.{}", ty.as_str())).to_owned(),
        shortcut: None,
        test_id,
        selected: active == Some(ty),
        disabled: tools.is_tool_button_disabled(ty.as_str()),
        badge: None,
        event: ToolbarEvent::ExtraTool(ty),
    };
    let mut items: Vec<MenuItem> = Vec::new();
    if !outside.text {
        items.push(item(ToolType::Text, "toolbar-text"));
    }
    if !outside.image {
        items.push(item(ToolType::Image, "toolbar-image"));
    }
    items.push(item(ToolType::Stickynote, "toolbar-stickynote"));
    if !outside.frame {
        items.push(item(ToolType::Frame, "toolbar-frame"));
    }
    items.push(item(ToolType::Embeddable, "toolbar-embeddable"));
    items.push(item(ToolType::Autoshape, "toolbar-autoshape"));
    items.push(item(ToolType::Laser, "toolbar-laser"));
    items.push(item(ToolType::Bucketfill, "toolbar-bucketfill"));
    let mut children: Vec<Node> = items
        .into_iter()
        .map(|i| menu_item(i, &props.on_event))
        .collect();
    children.push(Node::Element(
        Element::new("div")
            .style("margin", "6px 0px")
            .style("font-size", "14px")
            .style("font-weight", "600")
            .child("Generate"),
    ));
    if props.ai_enabled {
        children.extend(props.ttd_trigger.clone());
    }
    children.push(menu_item(
        MenuItem {
            icon: "mermaidLogoIcon",
            label: toolbar_text("toolBar.mermaidToExcalidraw").to_owned(),
            shortcut: None,
            // upstream's test id for this entry (MobileToolbar.tsx:352-358)
            test_id: "toolbar-embeddable",
            selected: false,
            disabled: false,
            badge: None,
            event: ToolbarEvent::MermaidToExcalidraw,
        },
        &props.on_event,
    ));
    if props.ai_enabled && props.diagram_to_code {
        children.push(menu_item(
            MenuItem {
                icon: "MagicIcon",
                label: toolbar_text("toolBar.magicframe").to_owned(),
                shortcut: None,
                test_id: "toolbar-magicframe",
                selected: false,
                disabled: tools.is_tool_button_disabled("magicframe"),
                badge: Some("AI"),
                event: ToolbarEvent::MagicFrame,
            },
            &props.on_event,
        ));
    }
    // a phone's DropdownMenuContent is a column, not an island
    let container = stack_col(
        StackProps {
            class_name: Some("dropdown-menu-container".into()),
            ..StackProps::default()
        },
        children,
    );
    let on_close = props.on_event.clone();
    radix_menu_content_aligned(
        "dropdown-menu App-toolbar__extra-tools-dropdown dropdown-menu--mobile",
        DropdownAlign::Start,
        trigger_id,
        content_id,
        container,
        Rc::new(move || emit(&on_close, ToolbarEvent::ExtraToolsClose)),
    )
}

/// `MobileToolbar` (`MobileToolbar.tsx:50-376`) at the state's measured
/// width; once mounted it reports its width when that differs
/// ([`ToolbarEvent::MobileToolbarWidth`]).
pub fn mobile_toolbar(props: MobileToolbarProps<'_>) -> Element {
    let tools = props.tools;
    let on_event = &props.on_event;
    let outside = tools_outside(props.state.width);
    let mut row: Vec<Node> = Vec::new();
    row.push(tool_button_for(
        tools,
        on_event,
        ToolType::Hand,
        ToolType::Hand,
        ShortcutDisplay::NoKeyBinding,
    ));
    tool_popover(&props, ToolPopover::Selection, &mut row);
    tool_popover(&props, ToolPopover::Freedraw, &mut row);
    row.push(tool_button_for(
        tools,
        on_event,
        ToolType::Eraser,
        ToolType::Eraser,
        ShortcutDisplay::Hidden,
    ));
    tool_popover(&props, ToolPopover::Shapes, &mut row);
    tool_popover(&props, ToolPopover::Linear, &mut row);
    for (shown, ty) in [
        (outside.text, ToolType::Text),
        (outside.image, ToolType::Image),
        (outside.frame, ToolType::Frame),
    ] {
        if shown {
            row.push(tool_button_for(
                tools,
                on_event,
                ty,
                ty,
                ShortcutDisplay::Hidden,
            ));
        }
    }
    row.push(Node::Element(extra_tools(&props, outside)));
    let measured = props.state.width;
    let on_width = props.on_event.clone();
    Element::new("div")
        .attr("class", "mobile-toolbar")
        .on_mount(move |el| {
            let width = el.get_bounding_client_rect().width();
            if width != measured {
                emit(&on_width, ToolbarEvent::MobileToolbarWidth(width));
            }
        })
        .children_from(row)
}

