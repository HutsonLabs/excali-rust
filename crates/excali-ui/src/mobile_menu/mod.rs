/// A toolbar button's size (`WIDTH`, `MobileToolbar.tsx:104`).
pub const TOOL_SIZE: f64 = 36.0;

/// The gap between the toolbar's buttons (`GAP`, `MobileToolbar.tsx:105`).
pub const TOOL_GAP: f64 = 4.0;

/// The buttons always shown: hand, selection, freedraw, eraser,
/// rectangle, arrow and "…" (`MIN_TOOLS`, `MobileToolbar.tsx:108`).
pub const MIN_TOOLS: f64 = 7.0;

/// Their width with their gaps (`MIN_WIDTH`, `MobileToolbar.tsx:109`).
pub const MIN_WIDTH: f64 = MIN_TOOLS * TOOL_SIZE + (MIN_TOOLS - 1.0) * TOOL_GAP;

/// What each further button needs (`ADDITIONAL_WIDTH`,
/// `MobileToolbar.tsx:110`).
pub const ADDITIONAL_WIDTH: f64 = TOOL_SIZE + TOOL_GAP;

/// `.App-bottom-bar`'s `max-width` (`styles.scss:322-346`).
pub const BOTTOM_BAR_MAX_WIDTH: f64 = 450.0;

/// What `.App-bottom-bar` leaves of the editor's width (`calc(100% -
/// 28px)`).
pub const BOTTOM_BAR_INSET: f64 = 28.0;

/// The padding of the bottom bar's islands (`.App-bottom-bar > .Island`).
pub const BOTTOM_BAR_PADDING: f64 = 4.0;

/// `SCROLLBAR_WIDTH` and `SCROLLBAR_MARGIN` (`scene/scrollbars.ts`): the
/// bottom bar's margin below.
pub const SCROLLBAR_WIDTH: f64 = 6.0;
pub const SCROLLBAR_MARGIN: f64 = 4.0;

/// The toolbar's width in the bottom bar of an editor `editor_width` wide,
/// as the compiled CSS lays it out: what upstream's toolbar measures.
pub fn toolbar_width(editor_width: f64) -> f64 {
    ((editor_width - BOTTOM_BAR_INSET).min(BOTTOM_BAR_MAX_WIDTH) - 2.0 * BOTTOM_BAR_PADDING)
        .max(0.0)
}

/// Which of text, image and frame the toolbar shows as buttons rather
/// than in "…".
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ToolsOutside {
    pub text: bool,
    pub image: bool,
    pub frame: bool,
}

/// `showTextToolOutside`, `showImageToolOutside` and
/// `showFrameToolOutside` for a toolbar `width` wide
/// (`MobileToolbar.tsx:112-114`).
pub fn tools_outside(width: f64) -> ToolsOutside {
    ToolsOutside {
        text: width >= MIN_WIDTH + ADDITIONAL_WIDTH,
        image: width >= MIN_WIDTH + 2.0 * ADDITIONAL_WIDTH,
        frame: width >= MIN_WIDTH + 3.0 * ADDITIONAL_WIDTH,
    }
}

