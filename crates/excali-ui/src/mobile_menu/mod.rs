/// `FixedSideContainer.scss` and the phone layout's rules of `styles.scss`,
/// compiled (generated by `tools/goldens/mobile-menu.mjs`).
pub const MOBILE_MENU_CSS: &str = include_str!("mobile_menu.css");

/// The `data-excali-ui` value of the `<style>` holding [`MOBILE_MENU_CSS`].
const STYLESHEET_ID: &str = "mobile-menu";

/// Adds [`MOBILE_MENU_CSS`] to `document`'s head once, after the
/// toolbar's stylesheet ([`crate::toolbar::install_stylesheet`], which it
/// installs first).
pub fn install_stylesheet(document: &web_sys::Document) -> Result<(), wasm_bindgen::JsValue> {
    crate::toolbar::install_stylesheet(document)?;
    let selector = format!("style[data-excali-ui=\"{STYLESHEET_ID}\"]");
    if document.query_selector(&selector)?.is_some() {
        return Ok(());
    }
    let style = document.create_element("style")?;
    style.set_attribute("data-excali-ui", STYLESHEET_ID)?;
    style.set_text_content(Some(MOBILE_MENU_CSS));
    let head = document
        .head()
        .ok_or_else(|| wasm_bindgen::JsValue::from_str("the document has no head"))?;
    let toolbar = document.query_selector("style[data-excali-ui=\"toolbar\"]")?;
    let next = toolbar.and_then(|p| p.next_sibling());
    head.insert_before(&style, next.as_ref())?;
    Ok(())
}

/// The English strings of the phone layout (`locales/en.json`); the key
