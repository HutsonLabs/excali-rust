/// What the phone layout's own buttons report.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MobileMenuEvent {
    /// The pen mode button (`onPenModeToggle(null)`).
    PenMode,
    /// The exit view mode button (`actionToggleViewMode`).
    ExitViewMode,
    /// "Scroll back to content" (`getScrollToContentState`).
    ScrollBackToContent,
}

/// Receives the menu's [`MobileMenuEvent`]s.
pub type OnMobileMenuEvent = Rc<dyn Fn(MobileMenuEvent)>;

/// `MobileMenu`'s props: the app state it reads, the host's settings and
/// its slots.
#[derive(Clone, Default)]
pub struct MobileMenuProps {
    /// `appState.viewModeEnabled`.
    pub view_mode: bool,
    /// `appState.penMode`.
    pub pen_mode: bool,
    /// `appState.penDetected`.
    pub pen_detected: bool,
    /// `appState.scrolledOutside`.
    pub scrolled_outside: bool,
    /// `appState.openMenu` is set.
    pub menu_open: bool,
    /// `appState.openSidebar` is set.
    pub sidebar_open: bool,
    /// `appState.openDialog` is the element link selector.
    pub element_link_selector: bool,
    /// `app.isInteractionEnabled()`.
    pub interaction_enabled: bool,
    /// LayerUI's `defaultUIEnabled`.
    pub default_ui: bool,
    /// LayerUI's `scrollBackToContentUIEnabled`.
    pub scroll_back_ui: bool,
    /// LayerUI's `renderWelcomeScreen`.
    pub render_welcome_screen: bool,
    /// `renderSidebars()`.
    pub sidebars: Option<Node>,
    /// `WelcomeScreenCenterTunnel.Out`.
    pub welcome_screen: Option<Node>,
    /// `MainMenuTunnel.Out`.
    pub main_menu: Option<Node>,
    /// `DefaultSidebarTriggerTunnel.Out`.
    pub sidebar_trigger: Option<Node>,
    /// `renderTopLeftUI(true, appState)`.
    pub top_left_ui: Option<Node>,
    /// `renderTopRightUI(true, appState)`: replaces pen mode and the
    /// sidebar trigger when given.
    pub top_right_ui: Option<Node>,
    /// The styles row ([`crate::styles_panel::mobile_shape_actions`]).
    pub shape_actions: Option<Node>,
    /// The toolbar ([`mobile_toolbar`]).
    pub toolbar: Option<Node>,
    pub on_event: Option<OnMobileMenuEvent>,
}

fn menu_emit(on_event: &Option<OnMobileMenuEvent>, event: MobileMenuEvent) {
    if let Some(f) = on_event {
        f(event);
    }
}

/// `MobileMenu` (`MobileMenu.tsx:47-204`): the sidebars, the welcome
/// screen, the bottom bar (the styles row and the toolbar island, unless
/// in view mode) and the top bar, in that order (the top bar last, so on
/// top).
pub fn mobile_menu(props: MobileMenuProps) -> Vec<Node> {
    let mut out: Vec<Node> = Vec::new();
    out.extend(props.sidebars.clone());
    let mut welcome = Element::new("div").attr("class", "App-welcome-screen");
    if props.render_welcome_screen {
        welcome = welcome.children_from(props.welcome_screen.clone());
    }
    out.push(Node::Element(welcome));

    let scroll_back =
        (props.scroll_back_ui && props.scrolled_outside && !props.menu_open && !props.sidebar_open)
            .then(|| {
                let on_event = props.on_event.clone();
                Node::Element(
                    Element::new("button")
                        .attr("type", "button")
                        .attr("class", "scroll-back-to-content")
                        .on("click", move |_| {
                            menu_emit(&on_event, MobileMenuEvent::ScrollBackToContent)
                        })
                        .child(mobile_text("buttons.scrollBackToContent")),
                )
            });
    let status_stack = |button: Node| {
        Node::Element(
            Element::new("div")
                .attr("class", "floating-status-stack")
                .child(button),
        )
    };
    let bottom_bar = props.default_ui && !props.view_mode;
    if bottom_bar {
        let mut children: Vec<Node> = Vec::new();
        children.extend(scroll_back.clone().map(status_stack));
        children.extend(props.shape_actions.clone());
        let toolbar = if props.element_link_selector {
            Vec::new()
        } else {
            props.toolbar.clone().into_iter().collect()
        };
        children.push(Node::Element(island(
            IslandProps {
                class_name: Some("App-toolbar".into()),
                ..IslandProps::default()
            },
            toolbar,
        )));
        out.push(Node::Element(
            Element::new("div")
                .attr("class", "App-bottom-bar")
                .attr("data-viewport-ui", "bottom")
                .style(
                    "margin-bottom",
                    format!("{}px", SCROLLBAR_WIDTH + SCROLLBAR_MARGIN),
                )
                .children_from(children),
        ));
    } else if let Some(button) = scroll_back {
        out.push(status_stack(button));
    }

    let mut top = Element::new("div").attr(
        "class",
        "FixedSideContainer FixedSideContainer_side_top App-top-bar",
    );
    if !props.element_link_selector {
        top = top.child(top_bar(&props));
    }
    out.push(Node::Element(top));
    out
}

/// `renderAppTopBar` (`MobileMenu.tsx:66-116`).
fn top_bar(props: &MobileMenuProps) -> Element {
    let mut right: Vec<Node> = Vec::new();
    match &props.top_right_ui {
        Some(ui) => right.push(ui.clone()),
        None if !props.view_mode => {
            if props.default_ui && props.pen_detected {
                let title = toolbar_text("toolBar.penMode");
                let on_event = props.on_event.clone();
                right.push(Node::Element(icon_button(IconButtonProps {
                    kind: IconButtonKind::Toggle {
                        checked: props.pen_mode,
                    },
                    class_name: "ToolIcon__penMode is-mobile".into(),
                    icon: Some(icon_node("PenModeIcon")),
                    title: Some(title.into()),
                    aria_label: title.into(),
                    on_select: Some(Rc::new(move |_| {
                        menu_emit(&on_event, MobileMenuEvent::PenMode)
                    })),
                    ..IconButtonProps::default()
                })));
            }
            right.extend(props.sidebar_trigger.clone());
        }
        None => {}
    }
    if props.default_ui && props.view_mode && props.interaction_enabled {
        let on_event = props.on_event.clone();
        right.push(Node::Element(
            Element::new("button")
                .attr("type", "button")
                .attr("class", "disable-view-mode")
                .on("click", move |_| {
                    menu_emit(&on_event, MobileMenuEvent::ExitViewMode)
                })
                .child(icon_node("pencilIcon")),
        ));
    }
    let mut left: Vec<Node> = Vec::new();
    left.extend(props.top_left_ui.clone());
    left.extend(props.main_menu.clone());
    Element::new("div")
        .attr("class", "App-toolbar-content")
        .style("display", "flex")
        .style("flex-direction", "row")
        .style("justify-content", "space-between")
        .child(
            Element::new("div")
                .attr("class", "excalidraw-ui-top-left")
                .children_from(left),
        )
        .child(
            Element::new("div")
                .attr("class", "excalidraw-ui-top-right")
                .children_from(right),
        )
}
