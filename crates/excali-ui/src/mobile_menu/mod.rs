//! The phone layout: `MobileMenu` (`components/MobileMenu.tsx`), the top
//! bar and the bottom bar LayerUI renders on a phone instead of the
//! desktop's top menu (`LayerUI.tsx:612-629`), and its `MobileToolbar`
//! (`components/MobileToolbar.tsx`) with the tool popovers of
//! `components/ToolPopover.tsx` and `Tools.tsx` (`SelectionToolPopover`,
//! `FreedrawToolPopover`).
//!
//! A phone is an editor at most 599 px wide, or less than 500 px high and
//! 1000 px wide ([`crate::editor_interface::is_mobile_breakpoint`]); it
//! starts with the lasso as its selection tool ([`init_selection_tool`]).
//! Research `ui-design-system.md` §3.7, mockup 06:
//!
//! - the top bar: the host's main menu (and top-left UI) on the left; pen
//!   mode (once a pen is detected) and the library trigger, or the exit
//!   view mode button, on the right;
//! - the bottom bar, at most 450 px wide and centred: the styles row
//!   ([`crate::styles_panel::mobile_shape_actions`]) above the toolbar;
//! - the toolbar's 36 px buttons: hand, selection/lasso, freedraw/draw to
//!   shape, eraser, rectangle/diamond/ellipse, arrow/line, then text,
//!   image and frame while the toolbar is wide enough ([`tools_outside`]),
//!   then "…" with the other tools and "Generate".
//!
//! [`mobile_toolbar`] and [`mobile_menu`] build the DOM upstream leaves
//! (`tests/mobile_menu.rs` holds every case of
//! `tests/fixtures/mobile-menu.json` to it). The toolbar's listeners
//! report [`ToolbarEvent`]s, which the host applies with
//! [`apply_toolbar_event`] to its [`MobileToolbarState`] (the popovers,
//! the remembered options and the measured width upstream keeps in React
//! state) and its tool state, then re-renders; a press on the canvas
//! closes the popovers ([`MobileToolbarState::close_popovers`], upstream's
//! `onPointerDownEmitter`). The menu's own buttons report
//! [`MobileMenuEvent`]s. The styles are upstream's `MobileToolbar.scss`,
//! `ToolPopover.scss`, `FixedSideContainer.scss` and the phone layout's
//! rules of `styles.scss`, compiled ([`MOBILE_MENU_CSS`]).
//!
//! Not ported here: the viewport status badge (`props.viewportStatusFrame`,
//! a host feature the port has no counterpart of yet).

