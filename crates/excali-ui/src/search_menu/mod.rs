/// A match's preview (`getMatchPreview`): the words around the match, the
/// query's position in it, and whether words were left out on either side.
#[derive(Debug, Clone, PartialEq)]
pub struct MatchPreview {
    /// In UTF-16 code units.
    pub index_in_search_query: usize,
    pub preview_text: String,
    pub more_before: bool,
    pub more_after: bool,
}

/// `getMatchPreview(text, index, searchQuery)` (`SearchMenu.tsx:537-590`):
/// two words before the match (at most 20 code units) and five after.
pub fn get_match_preview(text: &str, index: usize, search_query: &str) -> MatchPreview {
    const WORDS_BEFORE: i64 = 2;
    const WORDS_AFTER: usize = 5;
    const MAX_ALLOWED_CHARS: usize = 20;
    let text = units(text);
    let query = units(search_query);

    let substr_before_query = slice(&text, 0, index);
    let words_before_query = split_whitespace(substr_before_query);
    let is_query_complete_before = substr_before_query.last() == Some(&0x20);
    let start_word_index = words_before_query.len() as i64
        - WORDS_BEFORE
        - 1
        - if is_query_complete_before { 0 } else { 1 };
    let from = if start_word_index <= 0 {
        0
    } else {
        start_word_index as usize
    };
    let mut words_before = join(
        &words_before_query[from.min(words_before_query.len())..],
        0x20,
    );
    if is_query_complete_before {
        words_before.push(0x20);
    }
    if words_before.len() > MAX_ALLOWED_CHARS {
        words_before = words_before[words_before.len() - MAX_ALLOWED_CHARS..].to_vec();
    }

    let substr_after_query = slice(&text, index + query.len(), text.len());
    let words_after = split_whitespace(substr_after_query);
    let is_query_complete_after = substr_after_query.first() != Some(&0x20);
    let take = if is_query_complete_after {
        WORDS_AFTER + 1
    } else {
        WORDS_AFTER
    };
    let mut words_after_string = Vec::new();
    if !is_query_complete_after {
        words_after_string.push(0x20);
    }
    words_after_string.extend(join(&words_after[..take.min(words_after.len())], 0x20));

    let mut preview = words_before.clone();
    preview.extend_from_slice(&query);
    preview.extend(words_after_string);
    MatchPreview {
        index_in_search_query: words_before.len(),
        preview_text: string(&preview),
        more_before: start_word_index > 0,
        more_after: words_after.len() > take,
    }
}

/// `indexOf(search, from)` on code units.
fn index_of(haystack: &[u16], needle: &[u16], from: usize) -> Option<usize> {
    if needle.is_empty() {
        return Some(from.min(haystack.len()));
    }
    (from..=haystack.len().saturating_sub(needle.len()))
        .find(|&i| i + needle.len() <= haystack.len() && haystack[i..i + needle.len()] == *needle)
}

/// `normalizeWrappedText(wrappedText, originalText)`
/// (`SearchMenu.tsx:592-625`): each wrapped line padded with the spaces
/// wrapping dropped before the next line, so positions in the original
/// text fall on the same lines.
pub fn normalize_wrapped_text(wrapped_text: &str, original_text: &str) -> String {
    let wrapped = units(wrapped_text);
    let original = units(original_text);
    let lines: Vec<&[u16]> = wrapped.split(|&u| u == 0x0a).collect();
    let mut normalized: Vec<Vec<u16>> = Vec::new();
    let mut original_index = 0usize;
    for (i, line) in lines.iter().enumerate() {
        let mut current = line.to_vec();
        if let Some(next) = lines.get(i + 1).filter(|l| !l.is_empty()) {
            // indexOf returns -1 when absent, never more than the current end
            if let Some(at) = index_of(&original, next, original_index) {
                let end = current.len() + original_index;
                if at > end {
                    current.extend(std::iter::repeat_n(0x20, at - end));
                }
            }
        }
        original_index += current.len();
        normalized.push(current);
    }
    string(&join(
        &normalized.iter().map(Vec::as_slice).collect::<Vec<_>>(),
        0x0a,
    ))
}

/// Where a match shows on the canvas (`SearchMatch["matchedLines"]`): per
/// line it spans, the offset from the element's position and the size.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct MatchedLine {
    pub offset_x: f64,
    pub offset_y: f64,
    pub width: f64,
    pub height: f64,
    pub show_on_canvas: bool,
}

impl MatchedLine {
    /// As the app state holds it.
    pub fn to_json(&self) -> Value {
        json!({
            "offsetX": self.offset_x,
            "offsetY": self.offset_y,
            "width": self.width,
            "height": self.height,
            "showOnCanvas": self.show_on_canvas,
        })
    }
}

/// `getMatchedLines(textElement, searchQuery, index)`
/// (`SearchMenu.tsx:627-728`): the lines of the rendered (wrapped) text the
/// match at `index` of the original text spans, measured in the element's
/// font. Not a text element: none.
pub fn get_matched_lines(
    element: &SceneElement,
    search_query: &str,
    index: usize,
    metrics: &dyn TextMetricsProvider,
) -> Vec<MatchedLine> {
    let ElementKind::Text(text) = &element.kind else {
        return Vec::new();
    };
    let normalized = units(&normalize_wrapped_text(&text.text, &text.original_text));
    let font = get_font_string(text.font_size, text.font_family);
    let measure = |s: &[u16]| measure_text(&string(s), &font, text.line_height, metrics);

    struct Range<'a> {
        line: &'a [u16],
        start: i64,
        end: i64,
        number: usize,
    }
    let mut ranges = Vec::new();
    let mut current = 0i64;
    for (number, line) in normalized.split(|&u| u == 0x0a).enumerate() {
        let start = current;
        let end = start + line.len() as i64 - 1;
        ranges.push(Range {
            line,
            start,
            end,
            number,
        });
        current = end + 1;
    }

    let original = units(&text.original_text);
    let query_len = units(search_query).len();
    let mut start_index = index as i64;
    let mut remaining = slice(&original, index, index + query_len).to_vec();
    let mut out = Vec::new();
    for range in &ranges {
        if remaining.is_empty() {
            break;
        }
        if start_index >= range.start && start_index <= range.end {
            let capacity = (range.end + 1 - start_index) as usize;
            let text_to_start = slice(range.line, 0, (start_index - range.start) as usize);
            let matched_word = slice(&remaining, 0, capacity).to_vec();
            remaining = slice(&remaining, capacity, remaining.len()).to_vec();

            let mut offset = measure(text_to_start);
            // measureText measures "" as a space
            if text_to_start.is_empty() {
                offset.width = 0.0;
            }
            if text.text_align != TextAlign::Left && !range.line.is_empty() {
                let line_width = measure(range.line).width;
                let space_to_start = if text.text_align == TextAlign::Center {
                    (element.base.width - line_width) / 2.0
                } else {
                    element.base.width - line_width
                };
                offset.width += space_to_start;
            }
            let size = measure(&matched_word);
            out.push(MatchedLine {
                offset_x: offset.width,
                offset_y: range.number as f64 * offset.height,
                width: size.width,
                height: size.height,
                show_on_canvas: true,
            });
            start_index += capacity as i64;
        }
    }
    out
}

/// `getMatchInFrame(frame, searchQuery, index, zoomValue)`
/// (`SearchMenu.tsx:730-770`): the match in the frame's name, drawn above
/// the frame in Assistant at the name's font size; shown on the canvas
/// when it ends within the frame's zoomed width. Not a frame: none.
pub fn get_match_in_frame(
    frame: &SceneElement,
    search_query: &str,
    index: usize,
    zoom: f64,
    metrics: &dyn TextMetricsProvider,
) -> Vec<MatchedLine> {
    let Some(name) = get_frame_like_title(frame) else {
        return Vec::new();
    };
    let text = units(name);
    let query_len = units(search_query).len();
    let matched = slice(&text, index, index + query_len);
    let prefix = slice(&text, 0, index);
    let font = get_font_string(FRAME_NAME_FONT_SIZE, FontFamily::ASSISTANT);
    let line_height = get_line_height(FontFamily::ASSISTANT);
    let mut offset = measure_text(&string(prefix), &font, line_height, metrics);
    if prefix.is_empty() {
        offset.width = 0.0;
    }
    let size = measure_text(&string(matched), &font, line_height, metrics);
    vec![MatchedLine {
        offset_x: offset.width,
        offset_y: -offset.height - FRAME_STROKE_WIDTH,
        width: size.width,
        height: size.height,
        show_on_canvas: offset.width + size.width <= frame.base.width * zoom,
    }]
}

/// Which group a match is in.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MatchKind {
    /// A frame's (or AI frame's) name.
    Frame,
    Text,
}

/// A match (`SearchMatchItem`): the element, what was searched, where.
#[derive(Debug, Clone, PartialEq)]
pub struct SearchMatchItem {
    pub element_id: String,
    pub kind: MatchKind,
    /// The element's position and font when searched (a frame's name is
    /// drawn in Assistant at the name's size).
    pub x: f64,
    pub y: f64,
    pub font_size: f64,
    pub font_family: FontFamily,
    /// The trimmed query.
    pub search_query: String,
    /// In UTF-16 code units of the searched text.
    pub index: usize,
    pub preview: MatchPreview,
    pub matched_lines: Vec<MatchedLine>,
}

/// What a search reads: the scene, the visible elements, the view and the
/// text measurement.
pub struct SearchContext<'a> {
    /// The scene's elements; deleted ones are skipped.
    pub elements: &'a [SceneElement],
    /// `app.scene.getSceneNonce()`: a search is redone when it changes.
    pub scene_nonce: u64,
    /// The ids of `app.visibleElements`.
    pub visible_ids: &'a [String],
    /// The viewport: scroll, zoom, the canvas's CSS size and offset.
    pub view: ViewportState,
    /// `app.viewport.getOffsets()`: the UI covering the canvas plus the
    /// padding, in viewport px.
    pub padding: Offsets,
    pub metrics: &'a dyn TextMetricsProvider,
}

/// `handleSearch`'s search (`SearchMenu.tsx:776-866`), undebounced: the
/// matches of `search_query` (trimmed, case-insensitive) in the texts'
/// original text and the frames' names, each sorted by `y`, frames first;
/// and the index of the first match whose element is visible (`-1` for
/// none; `None` for an empty query).
pub fn handle_search(
    search_query: &str,
    cx: &SearchContext<'_>,
) -> (Vec<SearchMatchItem>, Option<i64>) {
    if search_query.is_empty() {
        return (Vec::new(), None);
    }
    let live: Vec<&SceneElement> = cx.elements.iter().filter(|e| !e.base.is_deleted).collect();
    let mut texts: Vec<&SceneElement> = live
        .iter()
        .copied()
        .filter(|e| matches!(e.kind, ElementKind::Text(_)))
        .collect();
    let mut frames: Vec<&SceneElement> = live
        .iter()
        .copied()
        .filter(|e| matches!(e.kind, ElementKind::Frame(_) | ElementKind::MagicFrame(_)))
        .collect();
    texts.sort_by(|a, b| a.base.y.total_cmp(&b.base.y));
    frames.sort_by(|a, b| a.base.y.total_cmp(&b.base.y));
    let query = units(search_query);

    let mut text_matches = Vec::new();
    for el in texts {
        let ElementKind::Text(t) = &el.kind else {
            continue;
        };
        for index in find_matches(&units(&t.original_text), &query) {
            let preview = get_match_preview(&t.original_text, index, search_query);
            let matched_lines = get_matched_lines(el, search_query, index, cx.metrics);
            if !matched_lines.is_empty() {
                text_matches.push(SearchMatchItem {
                    element_id: el.base.id.clone(),
                    kind: MatchKind::Text,
                    x: el.base.x,
                    y: el.base.y,
                    font_size: t.font_size,
                    font_family: t.font_family,
                    search_query: search_query.to_owned(),
                    index,
                    preview,
                    matched_lines,
                });
            }
        }
    }

    let mut frame_matches = Vec::new();
    for el in frames {
        let Some(name) = get_frame_like_title(el) else {
            continue;
        };
        for index in find_matches(&units(name), &query) {
            let preview = get_match_preview(name, index, search_query);
            let matched_lines =
                get_match_in_frame(el, search_query, index, cx.view.zoom, cx.metrics);
            frame_matches.push(SearchMatchItem {
                element_id: el.base.id.clone(),
                kind: MatchKind::Frame,
                x: el.base.x,
                y: el.base.y,
                font_size: FRAME_NAME_FONT_SIZE,
                font_family: FontFamily::ASSISTANT,
                search_query: search_query.to_owned(),
                index,
                preview,
                matched_lines,
            });
        }
    }

    let mut items = frame_matches;
    items.extend(text_matches);
    let focus = items
        .iter()
        .position(|m| cx.visible_ids.contains(&m.element_id))
        .map_or(-1, |i| i as i64);
    (items, Some(focus))
}

/// `appState.searchMatches` for a search's matches: `null` for none, else
/// no match focused.
pub fn search_matches_value(items: &[SearchMatchItem]) -> Value {
    if items.is_empty() {
        return Value::Null;
    }
    json!({
        "focusedId": null,
        "matches": items.iter().map(|m| json!({
            "id": m.element_id,
            "focus": false,
            "matchedLines": m.matched_lines.iter().map(MatchedLine::to_json).collect::<Vec<_>>(),
        })).collect::<Vec<_>>(),
    })
}

/// The focus effect's functional update (`SearchMenu.tsx:174-197`) of the
/// current `searchMatches`: the match at `focus` focused and its id
/// `focusedId`; `None` (no update) while there are no matches.
pub fn focus_search_matches(current: &Value, focus: Option<i64>) -> Option<Value> {
    let matches = current.get("matches")?.as_array()?;
    let at = focus.and_then(|i| usize::try_from(i).ok());
    let focused_id = at
        .and_then(|i| matches.get(i))
        .and_then(|m| m.get("id"))
        .filter(|id| id.as_str().is_some_and(|s| !s.is_empty()))
        .cloned()
        .unwrap_or(Value::Null);
    let matches = matches
        .iter()
        .enumerate()
        .map(|(i, m)| {
            let mut m = m.as_object().cloned().unwrap_or_default();
            m.insert("focus".into(), json!(Some(i) == at));
            Value::Object(m)
        })
        .collect::<Vec<_>>();
    Some(json!({ "focusedId": focused_id, "matches": matches }))
}

