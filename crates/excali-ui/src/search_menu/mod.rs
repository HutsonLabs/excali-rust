//! The search menu: upstream's `SearchMenu` (`components/SearchMenu.tsx`),
//! the content of the default sidebar's search tab
//! ([`crate::library_sidebar::LibrarySidebarProps::search_menu`]), and
//! `actionToggleSearchMenu` (`actions/actionToggleSearchMenu.ts`), which
//! Ctrl/Cmd+F runs.
//!
//! Layout (research `ui-design-system.md` §3.6, `SearchMenu.tsx:340-519`):
//! the search field, the match count with the next and previous buttons
//! (or "No matches found..."), then the matches in two groups, "Frames"
//! (frame names) before "Texts", each under its title; the focused match
//! is highlighted and scrolls itself into view.
//!
//! [`search_menu`] builds the DOM for a [`SearchMenuState`] (the menu's
//! atoms, `searchQueryAtom` and `searchItemInFocusAtom`, and its React
//! state); what the user does comes back as [`SearchMenuEvent`]s, which
//! the host runs through [`update`], and window keys through
//! [`key_down`]. Each returns the [`SearchEffect`]s upstream's handlers and
//! effects have, in their order: app state patches (`searchMatches`,
//! `openSidebar`), the focused match's functional update
//! ([`focus_search_matches`]), the viewport navigation to the focused match
//! ([`SearchEffect::SetViewport`], `app.viewport.setViewport` with a 300 ms
//! animation and the UI's offsets), focusing the search field, and
//! [`SearchEffect::ScheduleSearch`]: `handleSearch` is debounced by
//! [`SEARCH_DEBOUNCE_MS`], so the host (re)starts a timer that calls
//! [`run_pending`]. [`mount`] and [`unmount`] are the component's mount and
//! cleanup effects; [`sync`] its search effect when the scene changes.
//!
//! Positions in texts are UTF-16 code units, as JavaScript counts them.
//! Text is measured through a [`TextMetricsProvider`].
//!
//! Not here: drawing the matches on the interactive canvas
//! (`renderer/interactiveScene.ts`, `renderSearchMatches`).

