/// A debounced search waiting for its timer.
#[derive(Debug, Clone, PartialEq)]
pub struct PendingSearch {
    /// The trimmed query.
    pub query: String,
    /// From the field's `onChange` (sets the focus and ends `isSearching`),
    /// or from the search effect.
    pub from_input: bool,
}

/// The menu's state: `searchQueryAtom` (kept while the menu is closed),
/// `searchItemInFocusAtom`, and the component's state and refs.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct SearchMenuState {
    /// `searchQueryAtom`: the field's value.
    pub input: String,
    /// `searchItemInFocusAtom`: the focused match; `-1` when a search found
    /// no visible match.
    pub focus_index: Option<i64>,
    pub is_searching: bool,
    /// `searchMatches.items`.
    pub matches: Vec<SearchMatchItem>,
    /// `searchedQueryRef`.
    pub searched_query: Option<String>,
    /// `lastSceneNonceRef`.
    pub last_scene_nonce: Option<u64>,
    /// The debounced `handleSearch` call waiting.
    pub pending: Option<PendingSearch>,
}

impl SearchMenuState {
    /// `searchQuery`: the field's value trimmed.
    pub fn search_query(&self) -> &str {
        excali_core::color::js_trim(&self.input)
    }
}

/// What the menu's handlers and effects do, in order.
#[derive(Debug, Clone, PartialEq)]
pub enum SearchEffect {
    /// `setAppState` with these keys.
    SetAppState(Map<String, Value>),
    /// `setAppState` with [`focus_search_matches`] of the current
    /// `searchMatches` (nothing when it returns `None`).
    FocusMatches(Option<i64>),
    /// `app.viewport.setViewport({target, fit, animation: {duration: 300},
    /// offsets: {ui: true}})`: `target` is the focused match's bounds.
    SetViewport { target: [f64; 4], fit: Fit },
    /// Focus and select the search field.
    FocusInput,
    /// (Re)start the [`SEARCH_DEBOUNCE_MS`] timer that calls
    /// [`run_pending`].
    ScheduleSearch,
}

/// What the user does in the menu.
#[derive(Debug, Clone, PartialEq)]
pub enum SearchMenuEvent {
    /// The field's value.
    Input(String),
    /// The next button (`collapseDownIcon`), Enter or ArrowDown.
    Next,
    /// The previous button (`upIcon`) or ArrowUp.
    Previous,
    /// A match clicked, by its index among all matches.
    Select(usize),
}

fn search_matches_patch(items: &[SearchMatchItem]) -> SearchEffect {
    let mut patch = Map::new();
    patch.insert("searchMatches".into(), search_matches_value(items));
    SearchEffect::SetAppState(patch)
}

/// The search effect (`SearchMenu.tsx:103-138`): unless a search from the
/// field is under way, a query or scene the matches are not for schedules
/// a search.
fn search_effect(state: &mut SearchMenuState, scene_nonce: u64) -> Vec<SearchEffect> {
    if state.is_searching {
        return Vec::new();
    }
    let query = state.search_query().to_owned();
    let stale = state.searched_query.as_deref() != Some(query.as_str())
        || state.last_scene_nonce != Some(scene_nonce);
    let scheduled = state
        .pending
        .as_ref()
        .is_some_and(|p| p.query == query && !p.from_input);
    if !stale || scheduled {
        return Vec::new();
    }
    state.searched_query = None;
    state.pending = Some(PendingSearch {
        query,
        from_input: false,
    });
    vec![SearchEffect::ScheduleSearch]
}

/// The menu mounted (in the search tab): its search effect runs.
pub fn mount(state: &mut SearchMenuState, scene_nonce: u64) -> Vec<SearchEffect> {
    search_effect(state, scene_nonce)
}

/// The scene changed while the menu is open: its search effect runs again.
pub fn sync(state: &mut SearchMenuState, scene_nonce: u64) -> Vec<SearchEffect> {
    search_effect(state, scene_nonce)
}

/// The cleanup when the menu unmounts (`SearchMenu.tsx:260-271`): no
/// focus, the refs reset, no matches in the app state. The query stays.
pub fn unmount(state: &mut SearchMenuState) -> Vec<SearchEffect> {
    state.focus_index = None;
    state.searched_query = None;
    state.last_scene_nonce = None;
    state.is_searching = false;
    state.pending = None;
    let mut patch = Map::new();
    patch.insert("searchMatches".into(), Value::Null);
    vec![SearchEffect::SetAppState(patch)]
}

/// The debounce timer fired: `handleSearch` runs with the last call's
/// query, then its callback and the effects of what it changed.
pub fn run_pending(state: &mut SearchMenuState, cx: &SearchContext<'_>) -> Vec<SearchEffect> {
    let Some(pending) = state.pending.take() else {
        return Vec::new();
    };
    let (items, focus) = handle_search(&pending.query, cx);
    let mut effects = vec![search_matches_patch(&items)];
    state.matches = items;
    state.searched_query = Some(pending.query);
    state.last_scene_nonce = Some(cx.scene_nonce);
    let before = state.focus_index;
    if pending.from_input {
        state.focus_index = focus;
        state.is_searching = false;
    }
    if state.focus_index != before {
        effects.push(SearchEffect::FocusMatches(state.focus_index));
    }
    // the viewport effect runs for the new matches
    effects.extend(navigate(state, cx));
    effects.extend(search_effect(state, cx.scene_nonce));
    effects
}

/// The viewport effect (`SearchMenu.tsx:199-258`): the focused match,
/// laid out as a text of the query in the match's font, navigated to when
/// it is not wholly in view or too small to read at this zoom.
fn navigate(state: &SearchMenuState, cx: &SearchContext<'_>) -> Vec<SearchEffect> {
    let Some(item) = state
        .focus_index
        .and_then(|i| usize::try_from(i).ok())
        .and_then(|i| state.matches.get(i))
    else {
        return Vec::new();
    };
    let first = item.matched_lines.first();
    let x = item.x + first.map_or(0.0, |l| l.offset_x);
    let y = item.y + first.map_or(0.0, |l| l.offset_y);
    let font = get_font_string(item.font_size, item.font_family);
    let size = measure_text(
        &normalize_text(&item.search_query),
        &font,
        get_line_height(item.font_family),
        cx.metrics,
    );
    let target = [x, y, x + size.width, y + size.height];
    let zoom = cx.view.zoom;
    let is_text_tiny = item.font_size * zoom < FONT_SIZE_LEGIBILITY_THRESHOLD;
    let p = &cx.padding;
    let v = &cx.view;
    let (left, top) =
        viewport_coords_to_scene_coords(v.offset_left + p.left, v.offset_top + p.top, v);
    let (right, bottom) = viewport_coords_to_scene_coords(
        v.offset_left + v.width - p.right,
        v.offset_top + v.height - p.bottom,
        v,
    );
    let in_view =
        target[0] >= left && target[1] >= top && target[2] <= right && target[3] <= bottom;
    if in_view && !is_text_tiny {
        return Vec::new();
    }
    let fit = if is_text_tiny && item.font_size < FONT_SIZE_LEGIBILITY_THRESHOLD {
        Fit::Contain
    } else {
        Fit::ScaleDown
    };
    vec![SearchEffect::SetViewport { target, fit }]
}

/// The focus set: when it changed, the focus effect and the viewport
/// effect run.
fn set_focus(
    state: &mut SearchMenuState,
    focus: Option<i64>,
    cx: &SearchContext<'_>,
) -> Vec<SearchEffect> {
    if state.focus_index == focus {
        return Vec::new();
    }
    state.focus_index = focus;
    let mut effects = vec![SearchEffect::FocusMatches(focus)];
    effects.extend(navigate(state, cx));
    effects
}

/// `goToNextItem` (`SearchMenu.tsx:140-150`).
fn next_index(state: &SearchMenuState) -> Option<Option<i64>> {
    let n = state.matches.len() as i64;
    (n > 0).then(|| Some(state.focus_index.map_or(0, |i| (i + 1) % n)))
}

/// `goToPreviousItem` (`SearchMenu.tsx:152-164`).
fn previous_index(state: &SearchMenuState) -> Option<Option<i64>> {
    let n = state.matches.len() as i64;
    (n > 0).then(|| {
        Some(
            state
                .focus_index
                .map_or(0, |i| if i - 1 < 0 { n - 1 } else { i - 1 }),
        )
    })
}

/// Runs a [`SearchMenuEvent`]: updates the state and returns the effects.
pub fn update(
    state: &mut SearchMenuState,
    event: SearchMenuEvent,
    cx: &SearchContext<'_>,
) -> Vec<SearchEffect> {
    match event {
        SearchMenuEvent::Input(value) => {
            state.input = value;
            state.is_searching = true;
            state.pending = Some(PendingSearch {
                query: state.search_query().to_owned(),
                from_input: true,
            });
            vec![SearchEffect::ScheduleSearch]
        }
        SearchMenuEvent::Next => match next_index(state) {
            Some(focus) => set_focus(state, focus, cx),
            None => Vec::new(),
        },
        SearchMenuEvent::Previous => match previous_index(state) {
            Some(focus) => set_focus(state, focus, cx),
            None => Vec::new(),
        },
        SearchMenuEvent::Select(index) => set_focus(state, Some(index as i64), cx),
    }
}

/// A window `keydown` as the menu's capture listener reads it.
#[derive(Debug, Clone, Copy)]
pub struct SearchKey<'a> {
    pub key: &'a str,
    /// Cmd on Apple platforms, Ctrl elsewhere.
    pub ctrl_or_cmd: bool,
    /// The target is inside `.layer-ui__search`.
    pub in_search: bool,
    /// The search field has the focus.
    pub input_focused: bool,
    /// `appState.openDialog` / `openPopup` are set.
    pub open_dialog: bool,
    pub open_popup: bool,
}

/// What [`key_down`] did.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct SearchKeyOutcome {
    pub prevent_default: bool,
    pub stop_propagation: bool,
    pub effects: Vec<SearchEffect>,
}

/// The menu's window `keydown` listener (capture phase,
/// `SearchMenu.tsx:279-338`): Escape closes the sidebar (no dialog or
/// popup open); Ctrl/Cmd+F is taken from the browser and focuses the
/// field; in the menu, Enter and ArrowDown go to the next match, ArrowUp
/// to the previous.
pub fn key_down(
    state: &mut SearchMenuState,
    key: &SearchKey<'_>,
    cx: &SearchContext<'_>,
) -> SearchKeyOutcome {
    let mut out = SearchKeyOutcome::default();
    if key.key == "Escape" && !key.open_dialog && !key.open_popup {
        out.prevent_default = true;
        out.stop_propagation = true;
        let mut patch = Map::new();
        patch.insert("openSidebar".into(), Value::Null);
        out.effects.push(SearchEffect::SetAppState(patch));
        return out;
    }
    if key.ctrl_or_cmd && key.key == "f" {
        out.prevent_default = true;
        out.stop_propagation = true;
        if key.open_dialog {
            return out;
        }
        if !key.input_focused {
            out.effects.push(SearchEffect::FocusInput);
        }
    }
    if key.in_search && !state.matches.is_empty() {
        let step = match key.key {
            "Enter" | "ArrowDown" => next_index(state),
            "ArrowUp" => previous_index(state),
            _ => None,
        };
        if let Some(focus) = step {
            out.stop_propagation = true;
            out.effects.extend(set_focus(state, focus, cx));
        }
    }
    out
}

// -- the DOM ------------------------------------------------------------------------

/// How the search field takes the focus when the menu is built.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum InputFocus {
    /// Not at all.
    None,
    /// Focused with its value selected (`selectOnRender`, the first build).
    Select,
    /// Focused with this selection (in UTF-16 code units): a build that
    /// replaces a field that had the focus.
    Restore(u32, u32),
}

/// A handler of the menu's events.
pub type OnSearchMenuEvent = Rc<dyn Fn(SearchMenuEvent)>;

/// [`search_menu`]'s props.
pub struct SearchMenuProps<'a> {
    pub state: &'a SearchMenuState,
    pub focus: InputFocus,
    pub on_event: Option<OnSearchMenuEvent>,
}

fn emit(on_event: &Option<OnSearchMenuEvent>, event: SearchMenuEvent) {
    if let Some(f) = on_event {
        f(event);
    }
}

fn icon(icon: &icons::Icon) -> Node {
    icon.element(Theme::Light)
        .map(Node::Element)
        .unwrap_or_else(|| Node::text(""))
}

/// `<div class="layer-ui__search">` (`SearchMenu.tsx:346-432`): the field,
/// the count and navigation, the matches.
pub fn search_menu(props: SearchMenuProps<'_>) -> Element {
    let state = props.state;
    let on_change = props.on_event.clone();
    let mut field = text_field(TextFieldProps {
        value: TextFieldValue::Controlled(state.input.clone()),
        on_change: Some(Rc::new(move |value| {
            emit(&on_change, SearchMenuEvent::Input(value))
        })),
        class_name: Some(SEARCH_MENU_INPUT_WRAPPER.into()),
        placeholder: Some(search_text("search.placeholder").into()),
        icon: Some(icon(&icons::searchIcon)),
        select_on_render: props.focus == InputFocus::Select,
        ..TextFieldProps::default()
    });
    if let InputFocus::Restore(start, end) = props.focus {
        field = field.on_mount(move |el| {
            let Ok(Some(input)) = el.query_selector("input") else {
                return;
            };
            if let Some(input) = wasm_bindgen::JsCast::dyn_ref::<web_sys::HtmlInputElement>(&input)
            {
                let _ = input.focus();
                let _ = input.set_selection_range(start, end);
            }
        });
    }
    let header = Element::new("div")
        .attr("class", "layer-ui__search-header")
        .child(field);

    let n = state.matches.len();
    let mut count = Element::new("div").attr("class", "layer-ui__search-count");
    if n > 0 {
        let match_count = format!(
            "{n} {}",
            if n == 1 {
                search_text("search.singleResult")
            } else {
                search_text("search.multipleResults")
            }
        );
        let label = match state.focus_index {
            Some(i) if i > -1 => Element::new("div")
                .child(Node::text((i + 1).to_string()))
                .child(Node::text(" / "))
                .child(Node::text(match_count)),
            _ => Element::new("div").child(Node::text(match_count)),
        };
        let nav = |event: SearchMenuEvent, glyph: &icons::Icon| {
            let on_event = props.on_event.clone();
            button(
                ButtonProps {
                    class_name: "result-nav-btn".into(),
                    on_select: Some(Rc::new(move || emit(&on_event, event.clone()))),
                    ..ButtonProps::default()
                },
                vec![icon(glyph)],
            )
        };
        count = count.child(label).child(
            Element::new("div")
                .attr("class", "result-nav")
                .child(nav(SearchMenuEvent::Next, &icons::collapseDownIcon))
                .child(nav(SearchMenuEvent::Previous, &icons::upIcon)),
        );
    } else if !state.search_query().is_empty()
        && state
            .searched_query
            .as_deref()
            .is_some_and(|q| !q.is_empty())
    {
        count = count.child(
            Element::new("div")
                .style("margin", "1rem auto")
                .child(Node::text(search_text("search.noMatch"))),
        );
    }

    Element::new("div")
        .attr("class", "layer-ui__search")
        .child(header)
        .child(count)
        .child(match_list(&props))
}

/// `MatchList` (`SearchMenu.tsx:465-521`): the frames' group, a divider
/// when texts follow, the texts' group.
fn match_list(props: &SearchMenuProps<'_>) -> Element {
    let state = props.state;
    let frames: Vec<&SearchMatchItem> = state
        .matches
        .iter()
        .filter(|m| m.kind == MatchKind::Frame)
        .collect();
    let texts: Vec<&SearchMatchItem> = state
        .matches
        .iter()
        .filter(|m| m.kind == MatchKind::Text)
        .collect();
    let group = |title_icon: &icons::Icon, title: &str| {
        Element::new("div")
            .attr("class", "layer-ui__search-result-container")
            .child(
                Element::new("div")
                    .attr("class", "layer-ui__search-result-title")
                    .child(
                        Element::new("div")
                            .attr("class", "title-icon")
                            .child(icon(title_icon)),
                    )
                    .child(Element::new("div").child(Node::text(title))),
            )
    };
    let mut list = Element::new("div");
    if !frames.is_empty() {
        let mut container = group(&icons::frameToolIcon, search_text("search.frames"));
        for (i, m) in frames.iter().enumerate() {
            container = container.child(list_item(props, m, i));
        }
        if !texts.is_empty() {
            container = container.child(Element::new("div").attr("class", "layer-ui__divider"));
        }
        list = list.child(container);
    }
    if !texts.is_empty() {
        let mut container = group(&icons::TextIcon, search_text("search.texts"));
        for (i, m) in texts.iter().enumerate() {
            container = container.child(list_item(props, m, i + frames.len()));
        }
        list = list.child(container);
    }
    list
}

/// `ListItem` (`SearchMenu.tsx:434-463`): the preview with the query in
/// bold, `...` where words were left out; the focused one is `active` and
/// scrolls itself into view.
fn list_item(props: &SearchMenuProps<'_>, m: &SearchMatchItem, index: usize) -> Element {
    let preview = units(&m.preview.preview_text);
    let at = m.preview.index_in_search_query;
    // MatchList renders again only for new matches or a new focus
    // (`areEqual`), so with the query they were searched with
    let len = units(&m.search_query).len();
    let highlighted = props.state.focus_index == Some(index as i64);
    let before = string(slice(&preview, 0, at));
    let query = string(slice(&preview, at, at + len));
    let after = string(slice(&preview, at + len, preview.len()));
    let mut text = Element::new("div").attr("class", "preview-text");
    for part in [if m.preview.more_before { "..." } else { "" }, &before] {
        if !part.is_empty() {
            text = text.child(Node::text(part));
        }
    }
    let mut bold = Element::new("b");
    if !query.is_empty() {
        bold = bold.child(Node::text(query));
    }
    text = text.child(bold);
    for part in [
        after.as_str(),
        if m.preview.more_after { "..." } else { "" },
    ] {
        if !part.is_empty() {
            text = text.child(Node::text(part));
        }
    }
    let on_event = props.on_event.clone();
    let mut el = Element::new("div")
        .attr("tabindex", "-1")
        .attr(
            "class",
            class_names([("layer-ui__result-item", true), ("active", highlighted)]),
        )
        .child(text)
        .on("click", move |_| {
            emit(&on_event, SearchMenuEvent::Select(index))
        });
    if highlighted {
        el = el.on_mount(scroll_into_view);
    }
    el
}

/// `scrollIntoView({ behavior: "auto", block: "nearest" })`.
fn scroll_into_view(el: &web_sys::Element) {
    let options = web_sys::ScrollIntoViewOptions::new();
    let _ = js_sys::Reflect::set(&options, &"behavior".into(), &"auto".into());
    options.set_block(web_sys::ScrollLogicalPosition::Nearest);
    el.scroll_into_view_with_scroll_into_view_options(&options);
}
