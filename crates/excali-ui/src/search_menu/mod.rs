/// What `actionToggleSearchMenu.perform` does.
#[derive(Debug, Clone, PartialEq)]
pub enum SearchToggle {
    /// A dialog is open: nothing (`false`).
    None,
    /// The search tab is open: its field is focused and selected (`false`).
    FocusInput,
    /// The app state keys to set (`openSidebar` on the search tab,
    /// `openDialog: null`), captured eventually.
    Open(Map<String, Value>),
}

/// `actionToggleSearchMenu.perform` (`actionToggleSearchMenu.ts:26-51`).
pub fn toggle_search_menu(app_state: &Map<String, Value>) -> SearchToggle {
    if app_state.get("openDialog").is_some_and(|d| !d.is_null()) {
        return SearchToggle::None;
    }
    let open = app_state.get("openSidebar");
    let on_search = open.and_then(|o| o.get("name")).and_then(Value::as_str)
        == Some(DEFAULT_SIDEBAR_NAME)
        && open.and_then(|o| o.get("tab")).and_then(Value::as_str) == Some(CANVAS_SEARCH_TAB);
    if on_search {
        return SearchToggle::FocusInput;
    }
    let mut patch = Map::new();
    patch.insert(
        "openSidebar".into(),
        json!({ "name": DEFAULT_SIDEBAR_NAME, "tab": CANVAS_SEARCH_TAB }),
    );
    patch.insert("openDialog".into(), Value::Null);
    SearchToggle::Open(patch)
}

// -- UTF-16 helpers ---------------------------------------------------------------

fn units(s: &str) -> Vec<u16> {
    s.encode_utf16().collect()
}

fn string(units: &[u16]) -> String {
    String::from_utf16_lossy(units)
}

/// `String.prototype.slice(start, end)` on code units, clamped.
fn slice(units: &[u16], start: usize, end: usize) -> &[u16] {
    let end = end.min(units.len());
    let start = start.min(end);
    &units[start..end]
}

/// ECMAScript's `\s`: white space and line terminators.
fn is_js_space(u: u16) -> bool {
    matches!(
        u,
        0x09..=0x0d
            | 0x20
            | 0xa0
            | 0x1680
            | 0x2000..=0x200a
            | 0x2028
            | 0x2029
            | 0x202f
            | 0x205f
            | 0x3000
            | 0xfeff
    )
}

/// `text.split(/\s+/)`.
fn split_whitespace(text: &[u16]) -> Vec<&[u16]> {
    let mut out = Vec::new();
    let mut start = 0;
    let mut i = 0;
    while i < text.len() {
        if is_js_space(text[i]) {
            out.push(&text[start..i]);
            while i < text.len() && is_js_space(text[i]) {
                i += 1;
            }
            start = i;
        } else {
            i += 1;
        }
    }
    out.push(&text[start..]);
    out
}

fn join(words: &[&[u16]], sep: u16) -> Vec<u16> {
    let mut out = Vec::new();
    for (i, w) in words.iter().enumerate() {
        if i > 0 {
            out.push(sep);
        }
        out.extend_from_slice(w);
    }
    out
}

/// `Canonicalize` of a case-insensitive, non-unicode RegExp: the code
/// unit upper-cased when that is one code unit and does not map a
/// non-ASCII unit to ASCII.
fn canonicalize(u: u16) -> u16 {
    let Some(c) = char::from_u32(u32::from(u)) else {
        return u;
    };
    let mut upper = c.to_uppercase();
    let (Some(first), None) = (upper.next(), upper.next()) else {
        return u;
    };
    let mut buf = [0u16; 2];
    let encoded = first.encode_utf16(&mut buf);
    if encoded.len() != 1 {
        return u;
    }
    let cu = encoded[0];
    if u >= 128 && cu < 128 {
        return u;
    }
    cu
}

/// The start of every match of `new RegExp(escape(query), "gi")` in
/// `text`, as `regex.exec` finds them one after another.
fn find_matches(text: &[u16], query: &[u16]) -> Vec<usize> {
    let mut out = Vec::new();
    if query.is_empty() {
        return out;
    }
    let q: Vec<u16> = query.iter().map(|&u| canonicalize(u)).collect();
    let mut i = 0;
    while i + q.len() <= text.len() {
        if text[i..i + q.len()]
            .iter()
            .zip(&q)
            .all(|(&a, &b)| canonicalize(a) == b)
        {
            out.push(i);
            i += q.len();
        } else {
            i += 1;
        }
    }
    out
}

