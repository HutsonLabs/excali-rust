//! The font picker (`components/FontPicker/*`): the three top picks
//! (`FontPicker.tsx`: Excalifont "Hand-drawn", Nunito "Normal", Comic
//! Shanns "Code", or the customised `appState.fontTopPicks` padded with
//! them), the trigger (`FontPickerTrigger.tsx`), and the popup
//! (`FontPickerList.tsx`) with the search box (`QuickSearch.tsx`), the "In
//! this scene" and "Available fonts" groups, the "old" badge of deprecated
//! fonts and the keyboard map ([`font_picker_key_handler`],
//! `keyboardNavHandlers.ts`).
//!
//! [`font_picker`] builds the DOM for the host's state
//! ([`FontPickerProps`]); what the user does comes back as
//! [`FontPickerEvent`]s, which [`FontPickerState::dispatch`] applies the
//! way `actionChangeFontFamily`'s panel and `perform` update the app state
//! (`actions/actionProperties.tsx:1160-1540`), returning the callbacks
//! upstream's picker makes on the way. Previewing the hovered font on the
//! selected elements is that action's element update, not the picker's.
//! Outside compact mode the strip is customisable (`fontTopPicksDnD.ts`
//! over [`crate::top_picks_dnd`]): a list row dragged onto a pick pins its
//! font there (an already pinned one is refused), a pick dragged along the
//! strip reorders it, and the strip's context menu and the tip's reset link
//! clear `appState.fontTopPicks` ([`FontPickerEvent::TopPicksChange`]).
//!
//! See `site/content/research/ui-design-system.md` section 3.13.

