/// `needsGlyphSample` (`FontPicker.tsx:101-113`): a non-default pick whose
/// icon another pick shows too gets an "Aa" in its own font.
fn needs_glyph_sample(family: FontFamily, picks: &[FontFamily]) -> bool {
    if default_font(family).is_some() {
        return false;
    }
    let icon = pick_icon(family).name;
    picks
        .iter()
        .any(|p| *p != family && pick_icon(*p).name == icon)
}

/// `getTopPickFont` (`FontPicker.tsx:90-99`): the default's icon, label
/// and test id, else the family's own.
fn pick_icon(family: FontFamily) -> &'static Icon {
    default_font(family).map_or_else(|| font_family_icon(family), |d| d.icon)
}

fn pick_label(family: FontFamily) -> String {
    default_font(family).map_or_else(
        || font_family_label(family),
        |d| font_picker_text(d.text_key).to_owned(),
    )
}

fn pick_test_id(family: FontFamily) -> String {
    default_font(family).map_or_else(
        || format!("font-family-{}", family.0),
        |d| d.test_id.to_owned(),
    )
}

/// `FontTopPicks` (`FontPicker.tsx:115-187`) in its `TopPicksContextMenu`
/// trigger: the picks, which a drag moves and marks, around the drag's
/// outline.
fn top_picks_strip(props: &FontPickerProps) -> Node {
    let picks = top_picks(props.state.top_picks.as_deref());
    let drag_state = props.dnd.as_ref().and_then(|d| d.drag_state());
    let state = drag_state.as_ref();
    let buttons = picks.iter().enumerate().map(|(index, family)| {
        let family = *family;
        let content = if needs_glyph_sample(family, &picks) {
            Element::new("span")
                .attr("class", "FontPicker__top-pick-sample")
                .style("font-family", font_family_string(family))
                .child("Aa")
                .into()
        } else {
            icon(pick_icon(family))
        };
        let offset = get_top_pick_reorder_offset(state, index);
        let el = Element::new("button")
            .attr("type", "button")
            .attr("title", pick_label(family))
            .attr("data-testid", pick_test_id(family))
            .attr(
                "class",
                class_names([
                    ("top-picks-dnd__pick", true),
                    ("active", props.state.selected == Some(family)),
                    (
                        "is-dnd-source",
                        state.is_some_and(|s| s.origin == DragOrigin::Pick(index)),
                    ),
                    (
                        "is-dnd-target",
                        state.is_some_and(|s| {
                            s.origin == DragOrigin::Source && s.over_index == Some(index)
                        }),
                    ),
                    (
                        "is-dnd-duplicate",
                        state.is_some_and(|s| s.duplicate_index == Some(index)),
                    ),
                ]),
            )
            .style_opt(
                "transform",
                (offset != 0.0).then(|| format!("translateX({offset}px)")),
            )
            .on("click", props.handler(FontPickerEvent::Select(family)))
            .attr("data-top-pick-index", index.to_string())
            .child(content);
        draggable(el, props, family, DragOrigin::Pick(index), &picks).into()
    });
    let mut slots = Element::new("div")
        .attr(
            "class",
            class_names([
                ("FontPicker__top-picks-slots top-picks-dnd", true),
                ("is-dnd-active", drag_state.is_some()),
            ]),
        )
        .child_opt(drag_state.is_some().then(top_picks_dnd_outline))
        .children_from(buttons);
    if let Some(dnd) = props.dnd.clone() {
        slots = slots.on_mount(move |el| dnd.set_strip(Some(el.clone())));
    }
    let on_event = props.on_event.clone();
    let open = props.state.is_open();
    let on_open: Rc<dyn Fn(i32, i32)> = Rc::new(move |x, y| {
        emit(&on_event, FontPickerEvent::TopPicksMenu(Some((x, y))));
        // radix's popover closes as the menu takes the focus
        if open {
            emit(&on_event, FontPickerEvent::PopupChange(false));
        }
    });
    context_menu_trigger(
        Element::new("div")
            .attr("class", "buttonList FontPicker__top-picks")
            .child(slots),
        props.top_picks_menu.is_some(),
        on_open,
    )
    .into()
}

/// `FontPickerTrigger` (`FontPickerTrigger.tsx`): radix's
/// `Popover.Trigger` (asChild) around a toggle IconButton.
fn trigger(props: &FontPickerProps) -> Node {
    let open = props.state.is_open();
    let mut style = vec![("border".to_owned(), "none".to_owned())];
    if props.compact() {
        // MOBILE_ACTION_BUTTON_BG
        style.insert(
            0,
            ("background".into(), "var(--mobile-action-button-bg)".into()),
        );
        style.push(("width".into(), "2rem".into()));
        style.push(("height".into(), "2rem".into()));
    }
    let label = font_picker_text("labels.showFonts");
    let on_event = props.on_event.clone();
    let button = icon_button(IconButtonProps {
        kind: IconButtonKind::Toggle { checked: open },
        icon: Some(icon(&icons::TextIcon)),
        title: Some(label.to_owned()),
        aria_label: label.to_owned(),
        class_name: "standalone properties-trigger".into(),
        test_id: Some("font-family-show-fonts".into()),
        style,
        ..IconButtonProps::default()
    });
    Element::new("div")
        .attr("type", "button")
        .attr("aria-haspopup", "dialog")
        .attr("aria-expanded", open.to_string())
        .attr("aria-controls", props.popup_id.as_str())
        .attr("data-state", if open { "open" } else { "closed" })
        .attr("data-openpopup", "fontFamily")
        .attr("class", "properties-trigger")
        .on("click", move |e: &Event| {
            e.prevent_default();
            e.stop_propagation();
            // the IconButton's onSelect, then radix's toggle
            emit(&on_event, FontPickerEvent::TriggerSelect);
            emit(&on_event, FontPickerEvent::PopupChange(!open));
        })
        .child(button)
        .into()
}

