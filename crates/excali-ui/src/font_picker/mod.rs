/// `FontPickerListItem` (`FontPickerList.tsx:283-345`).
fn list_item(
    props: &FontPickerProps,
    font: &FontDescriptor,
    order: usize,
    hovered: Option<FontFamily>,
) -> Node {
    let is_hovered = hovered == Some(font.value);
    let is_selected = props.state.selected == Some(font.value);
    let value = font.value;
    let on_event = props.on_event.clone();
    let dnd = props.dnd.clone();
    let mut el = Element::new("button")
        .attr("type", "button")
        .attr("value", value.0.to_string())
        .attr("class", item_class(is_selected, is_hovered))
        .attr("title", font.text.as_str())
        .attr("tabindex", if is_selected { "0" } else { "-1" })
        .on("click", props.handler(FontPickerEvent::Select(value)))
        .on("mousemove", move |_| {
            let dragging = dnd.as_ref().is_some_and(|d| d.drag_state().is_some());
            if let Some(e) = hover_event(dragging, hovered, value) {
                emit(&on_event, e);
            }
        })
        .child(
            Element::new("div")
                .attr("class", "dropdown-menu-item__icon")
                .child(icon(font.icon)),
        )
        .child(
            Element::new("div")
                .style("font-family", font_family_string(value))
                .attr("class", "dropdown-menu-item__text")
                .child(
                    // Ellipsify (Ellipsify.tsx)
                    Element::new("span")
                        .style("text-overflow", "ellipsis")
                        .style("overflow", "hidden")
                        .style("white-space", "nowrap")
                        .child(font.text.as_str()),
                ),
        )
        .child_opt(font.deprecated.then(|| {
            Element::new("div")
                .attr("class", "dropdown-menu-item__badge")
                .child(old_badge(props.theme))
        }));
    el = draggable(el, props, value, DragOrigin::Source, &[]);
    if is_hovered {
        // the first item scrolls so its group title shows
        let block = if order == 0 { "end" } else { "nearest" };
        el = el.on_mount(move |dom| scroll_into_view(dom, block));
    }
    el.into()
}

fn scroll_into_view(el: &web_sys::Element, block: &str) {
    let Some(f) = js_sys::Reflect::get(el, &"scrollIntoView".into())
        .ok()
        .and_then(|f| f.dyn_into::<js_sys::Function>().ok())
    else {
        return;
    };
    let options = js_sys::Object::new();
    let _ = js_sys::Reflect::set(&options, &"block".into(), &block.into());
    let _ = f.call1(el, &options);
}

