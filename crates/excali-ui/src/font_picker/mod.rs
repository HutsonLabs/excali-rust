/// What a list row does with the pointer over it (`onMouseMove`,
/// `FontPickerList.tsx:328-333`): previews its font unless it is the
/// hovered one, or a drag is passing over it.
pub fn hover_event(
    dragging: bool,
    hovered: Option<FontFamily>,
    value: FontFamily,
) -> Option<FontPickerEvent> {
    (!dragging && hovered != Some(value)).then_some(FontPickerEvent::Hover(value))
}

/// Where a ghost comes from: a list row, or a pick of the strip showing
/// these picks.
#[derive(Clone, Copy, Debug)]
pub enum FontGhostSource<'a> {
    Row,
    Pick(&'a [FontFamily]),
}

/// The computed style `createFontGhost` samples (`fontTopPicksDnD.ts:30-40,
/// 44-50, 55-63`): the template pick's colours, border and radius, its
/// icon's size, and the source's glyph sample's font size. An empty value
/// is not written.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct FontGhostStyle {
    pub background_color: String,
    pub color: String,
    pub border_width: String,
    pub border_color: String,
    pub border_radius: String,
    pub icon_size: Option<(f64, f64)>,
    pub sample_font_size: String,
}

/// The pick whose look a ghost takes (`fontTopPicksDnD.ts:24-29`): a
/// dragged pick's own, else the first pick that is not the selected font's
/// (`[data-top-pick-index]:not(.active)`), else the first.
pub fn ghost_template_index(picks: &[FontFamily], selected: Option<FontFamily>) -> usize {
    picks.iter().position(|p| Some(*p) != selected).unwrap_or(0)
}

/// The ghost's content (`createFontGhost`, `fontTopPicksDnD.ts:19-66`): a
/// strip-button tile with the font's icon, or a pick's glyph sample,
/// never the whole list row.
pub fn font_ghost(
    family: FontFamily,
    source: FontGhostSource<'_>,
    style: &FontGhostStyle,
) -> Element {
    let set = |el: Element, property: &str, value: &str| {
        if value.is_empty() {
            el
        } else {
            el.style(property.to_owned(), value.to_owned())
        }
    };
    let mut tile = Element::new("div").attr("class", "excalidraw-font-dnd-ghost-tile");
    tile = set(tile, "background-color", &style.background_color);
    tile = set(tile, "color", &style.color);
    tile = tile.style("border-style", "solid");
    tile = set(tile, "border-width", &style.border_width);
    tile = set(tile, "border-color", &style.border_color);
    tile = set(tile, "border-radius", &style.border_radius);
    let icon_of = |i: &Icon| {
        let el = i
            .element(Theme::Light)
            .unwrap_or_else(|| panic!("icons.tsx has no {}", i.name));
        match style.icon_size {
            Some((w, h)) => el
                .style("width", format!("{w}px"))
                .style("height", format!("{h}px")),
            None => el,
        }
    };
    let content = match source {
        FontGhostSource::Row => icon_of(font_family_icon(family)),
        FontGhostSource::Pick(picks) if needs_glyph_sample(family, picks) => {
            let sample = Element::new("span")
                .attr("class", "FontPicker__top-pick-sample")
                .style("font-family", font_family_string(family));
            set(sample, "font-size", &style.sample_font_size)
                .style("line-height", "1")
                .child("Aa")
        }
        FontGhostSource::Pick(_) => icon_of(pick_icon(family)),
    };
    tile.child(content)
}

/// Where the ghost spawns and flies back to (`fontTopPicksDnD.ts:67-82`):
/// a pick's own rect, or the template's size centred on the list row's
/// icon (`anchor`).
pub fn font_ghost_rect(is_pick: bool, template: Rect, anchor: Rect) -> Rect {
    if is_pick {
        return template;
    }
    Rect {
        left: anchor.left + anchor.width / 2.0 - template.width / 2.0,
        top: anchor.top + anchor.height / 2.0 - template.height / 2.0,
        width: template.width,
        height: template.height,
    }
}

/// [`font_ghost`] and [`font_ghost_rect`] from the rendered DOM: the
/// source, the registered strip's template pick and their computed style.
fn browser_ghost(
    source: &web_sys::Element,
    strip: Option<&web_sys::Element>,
    family: FontFamily,
    picks: &[FontFamily],
) -> (web_sys::Element, Rect) {
    let is_pick = source.has_attribute("data-top-pick-index");
    let template = if is_pick {
        Some(source.clone())
    } else {
        strip.and_then(|s| {
            s.query_selector("[data-top-pick-index]:not(.active)")
                .ok()
                .flatten()
                .or_else(|| s.query_selector("[data-top-pick-index]").ok().flatten())
        })
    }
    .unwrap_or_else(|| source.clone());
    let window = web_sys::window();
    let computed = |el: &web_sys::Element, property: &str| {
        window
            .as_ref()
            .and_then(|w| w.get_computed_style(el).ok().flatten())
            .and_then(|s| s.get_property_value(property).ok())
            .unwrap_or_default()
    };
    let icon = source.query_selector("svg").ok().flatten();
    let style = FontGhostStyle {
        background_color: computed(&template, "background-color"),
        color: computed(&template, "color"),
        border_width: computed(&template, "border-top-width"),
        border_color: computed(&template, "border-top-color"),
        border_radius: computed(&template, "border-top-left-radius"),
        icon_size: template.query_selector("svg").ok().flatten().map(|svg| {
            let r = Rect::of(&svg);
            (r.width, r.height)
        }),
        sample_font_size: source
            .query_selector(".FontPicker__top-pick-sample")
            .ok()
            .flatten()
            .map(|s| computed(&s, "font-size"))
            .unwrap_or_default(),
    };
    let ghost_source = if is_pick {
        FontGhostSource::Pick(picks)
    } else {
        FontGhostSource::Row
    };
    let ghost = font_ghost(family, ghost_source, &style);
    let content = source
        .owner_document()
        .and_then(|d| crate::dom::create_detached(&Node::Element(ghost), &d).ok())
        .and_then(|n| n.dyn_into::<web_sys::Element>().ok())
        .unwrap_or_else(|| source.clone());
    let anchor = Rect::of(icon.as_ref().unwrap_or(source));
    (
        content,
        font_ghost_rect(is_pick, Rect::of(&template), anchor),
    )
}

/// Lets `el` start a drag of `family` from `origin` while the strip is
/// customisable (`startSourceDrag`, `startPickDrag`); `picks` are the
/// strip's.
fn draggable(
    el: Element,
    props: &FontPickerProps,
    family: FontFamily,
    origin: DragOrigin,
    picks: &[FontFamily],
) -> Element {
    if !props.customizable() {
        return el;
    }
    let dnd = props.dnd.clone();
    let picks = picks.to_vec();
    el.on("pointerdown", move |e: &Event| {
        let Some(dnd) = &dnd else {
            return;
        };
        let strip = dnd.strip();
        dnd.start_drag(e, Some(family), origin, |source| {
            browser_ghost(source, strip.as_ref(), family, &picks)
        });
    })
}

