/// `FontPickerList` (`FontPickerList.tsx:106-435`) in its
/// `PropertiesPopover`: radix's popper wrapper and the dialog content
/// with the island and the arrow.
fn popup(props: &FontPickerProps) -> Node {
    let filtered = filtered_fonts(&props.list, &props.state.search);
    let hovered = hovered_font(&filtered, &props.state).0;
    let values: Vec<FontFamily> = filtered.all().map(|f| f.value).collect();

    let mut groups = Vec::new();
    if !filtered.scene.is_empty() {
        let items = filtered
            .scene
            .iter()
            .enumerate()
            .map(|(i, f)| list_item(props, f, i, hovered))
            .collect();
        groups.push(menu_group(Some(font_picker_text("fontList.sceneFonts")), "", items).into());
    }
    if !filtered.available.is_empty() {
        let offset = filtered.scene.len();
        let items = filtered
            .available
            .iter()
            .enumerate()
            .map(|(i, f)| list_item(props, f, i + offset, hovered))
            .collect();
        groups
            .push(menu_group(Some(font_picker_text("fontList.availableFonts")), "", items).into());
    }
    let list = Element::new("div")
        .attr(
            "class",
            "ScrollableList__wrapper dropdown-menu fonts manual-hover",
        )
        .attr("role", "menu");
    let list = if groups.is_empty() {
        list.child(
            Element::new("div")
                .attr("class", "empty")
                .child(font_picker_text("fontList.empty")),
        )
    } else {
        list.children_from(groups)
    };
    let mut body = Vec::new();
    if !props.compact() {
        body.push(quick_search(props));
    }
    body.push(list.into());
    // only while the top picks are customisable
    if props.customizable() {
        body.push(tip(props));
    }

    let keydown = {
        let on_event = props.on_event.clone();
        let is_darwin = props.is_darwin;
        move |e: &Event| {
            let Some(k) = e.dyn_ref::<KeyboardEvent>() else {
                return;
            };
            let input = KeyInput {
                key: k.key(),
                code: k.code(),
                shift: k.shift_key(),
                ctrl_or_cmd: if is_darwin {
                    k.meta_key()
                } else {
                    k.ctrl_key()
                },
            };
            let out = font_picker_key_handler(&input, hovered, &values);
            if !out.handled {
                return;
            }
            e.prevent_default();
            e.stop_propagation();
            match out.effect {
                Some(FontPickerKeyEffect::FocusSearch) => focus_search(e),
                Some(FontPickerKeyEffect::Close) => {
                    emit(&on_event, FontPickerEvent::PopupChange(false))
                }
                Some(FontPickerKeyEffect::Select(f)) => emit(&on_event, FontPickerEvent::Select(f)),
                Some(FontPickerKeyEffect::Hover(f)) => emit(&on_event, FontPickerEvent::Hover(f)),
                None => {}
            }
        }
    };

    let arrow = Element::new("span").child(
        Element::svg("svg")
            .attr("width", "20")
            .attr("height", "10")
            .attr("viewBox", "0 0 30 10")
            .attr("preserveAspectRatio", "none")
            .style("fill", "var(--popup-bg-color)")
            .style("filter", "drop-shadow(rgba(0, 0, 0, 0.05) 0px 3px 2px)")
            .style("display", "block")
            .child(Element::svg("polygon").attr("points", "0,0 30,0 15,10")),
    );
    let content = Element::new("div")
        .attr("class", "focus-visible-none properties-content")
        .attr("data-prevent-outside-click", "true")
        .attr("data-state", "open")
        .attr("id", props.popup_id.as_str())
        .attr("role", "dialog")
        .attr("tabindex", "-1")
        .style(
            "--radix-popover-content-transform-origin",
            "var(--radix-popper-transform-origin)",
        )
        .style(
            "--radix-popover-content-available-width",
            "var(--radix-popper-available-width)",
        )
        .style(
            "--radix-popover-content-available-height",
            "var(--radix-popper-available-height)",
        )
        .style(
            "--radix-popover-trigger-width",
            "var(--radix-popper-anchor-width)",
        )
        .style(
            "--radix-popover-trigger-height",
            "var(--radix-popper-anchor-height)",
        )
        .style("z-index", "var(--zIndex-ui-styles-popup)")
        .style_opt("margin-left", props.phone.then_some("0.5rem"))
        // radix's DismissableLayer: a layer under a modal one (the strip's
        // context menu) takes no pointer events
        .style_opt(
            "pointer-events",
            (props.customizable() && props.top_picks_menu.is_some()).then_some("none"),
        )
        .on("keydown", keydown)
        .on("pointerleave", props.handler(FontPickerEvent::Leave))
        .child(island(
            IslandProps {
                padding: Some(3.0),
                style: vec![("width".into(), "15rem".into())],
                ..IslandProps::default()
            },
            body,
        ))
        .child(arrow)
        // radix's FocusScope focuses the first tabbable element as it opens
        .on_mount(|content| {
            let target = content
                .query_selector("input, [tabindex=\"0\"]")
                .ok()
                .flatten()
                .unwrap_or_else(|| content.clone());
            if let Some(h) = target.dyn_ref::<HtmlElement>() {
                let _ = h.focus();
            }
        });
    let trigger_id = props.popup_id.clone();
    let below = props.phone;
    Element::new("div")
        .attr("data-radix-popper-content-wrapper", "")
        .child(content)
        .on_mount(move |wrapper| place_popup(wrapper, &trigger_id, below))
        .into()
}

/// Shift+F inside the popup: back to the search box.
fn focus_search(e: &Event) {
    let content = e
        .current_target()
        .and_then(|t| t.dyn_into::<web_sys::Element>().ok());
    if let Some(input) = content
        .and_then(|c| c.query_selector(".QuickSearch__input").ok().flatten())
        .and_then(|i| i.dyn_into::<HtmlElement>().ok())
    {
        let _ = input.focus();
    }
}

/// Places the popup beside its trigger once mounted, as the colour
/// picker's is (radix's `side="right"`, `align="start"`, below on a
/// phone).
fn place_popup(wrapper: &web_sys::Element, trigger_id: &str, below: bool) {
    let Some(document) = wrapper.owner_document() else {
        return;
    };
    let selector = format!("[aria-controls=\"{trigger_id}\"]");
    if let Ok(Some(trigger)) = document.query_selector(&selector) {
        place_beside(wrapper, &trigger, below);
    }
}

/// `FontPicker` (`FontPicker.tsx:212-303`): the popup when open (portaled
/// into the editor container, which radix does before the picker's own
/// element), then the picker: the top-picks strip and a separator unless
/// compact, and the trigger.
///
/// While customisable, the strip's context menu follows when open
/// (portaled into the container, and radix hides the rest from assistive
/// technology meanwhile), and the drag and drop is told the picks and
/// whom to tell of a drop.
pub fn font_picker(props: &FontPickerProps) -> Vec<Node> {
    let compact = props.compact();
    let customizable = props.customizable();
    if let Some(dnd) = &props.dnd {
        dnd.set_enabled(customizable);
        dnd.set_picks(top_picks(props.state.top_picks.as_deref()));
        let on_event = props.on_event.clone();
        dnd.set_listener(Some(Rc::new(move |event| {
            emit(
                &on_event,
                match event {
                    TopPicksDndEvent::PicksChange(picks) => {
                        FontPickerEvent::TopPicksChange(Some(picks))
                    }
                    TopPicksDndEvent::StateChanged => FontPickerEvent::DragChange,
                },
            );
        })));
    }
    let container = Element::new("div")
        .attr("role", "dialog")
        .attr("aria-modal", "true")
        .attr(
            "class",
            class_names([
                ("FontPicker__container", true),
                ("FontPicker__container--compact", compact),
            ]),
        )
        .child_opt((!compact).then(|| top_picks_strip(props)))
        .child_opt((!compact).then(button_separator))
        .child(trigger(props));
    let mut out = Vec::new();
    if props.state.is_open() {
        out.push(popup(props));
    }
    out.push(container.into());
    if let (true, Some(at)) = (customizable, props.top_picks_menu) {
        let emit_on = |event: FontPickerEvent| -> Rc<dyn Fn()> {
            let on_event = props.on_event.clone();
            Rc::new(move || emit(&on_event, event.clone()))
        };
        out = hide_others(out);
        out.push(context_menu(
            font_picker_text("fontList.resetTopPicks"),
            props.customized(),
            at,
            emit_on(FontPickerEvent::TopPicksChange(None)),
            emit_on(FontPickerEvent::TopPicksMenu(None)),
        ));
    }
    out
}
