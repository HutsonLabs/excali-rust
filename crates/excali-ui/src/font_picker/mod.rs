/// The picker's props: the state and what it is rendered in.
#[derive(Clone)]
pub struct FontPickerProps {
    pub state: FontPickerState,
    /// The styles panel's layout: the strip and the search only in
    /// [`StylesPanelMode::Full`] (`compactMode` otherwise).
    pub mode: StylesPanelMode,
    pub list: FontListContext,
    /// The badge's border (`DropdownMenuItem.tsx:85`).
    pub theme: Theme,
    /// `editorInterface.formFactor === "phone"`: the popup's left margin,
    /// and below the trigger.
    pub phone: bool,
    /// Cmd rather than Ctrl is the command key.
    pub is_darwin: bool,
    /// The popup's id, which the trigger's `aria-controls` names.
    pub popup_id: String,
    pub on_event: Option<OnFontPickerEvent>,
    /// The strip's context menu is open at this client point.
    pub top_picks_menu: Option<(i32, i32)>,
    /// The drag and drop ([`font_picker_dnd`]), kept by the host across
    /// renders.
    pub dnd: Option<FontPickerDnd>,
}

impl FontPickerProps {
    fn compact(&self) -> bool {
        self.mode != StylesPanelMode::Full
    }

    /// `isTopPicksCustomizable` (`FontPicker.tsx:234-235`): the strip is
    /// shown, so it can be customised.
    fn customizable(&self) -> bool {
        !self.compact()
    }

    fn customized(&self) -> bool {
        self.state.top_picks.as_ref().is_some_and(|p| !p.is_empty())
    }

    fn handler(&self, event: FontPickerEvent) -> impl Fn(&Event) + 'static {
        let on_event = self.on_event.clone();
        move |_| emit(&on_event, event.clone())
    }
}

fn emit(on_event: &Option<OnFontPickerEvent>, event: FontPickerEvent) {
    if let Some(f) = on_event {
        f(event);
    }
}

