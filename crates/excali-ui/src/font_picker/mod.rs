/// What the picker asks of its host: its callbacks (`FontPickerProps`,
/// `FontPicker.tsx:199-211`), the trigger's `setAppState`, and the search
/// the list keeps.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum FontPickerEvent {
    /// `onSelect`: a top pick, a list item or Enter.
    Select(FontFamily),
    /// `onHover`: an item under the pointer or the arrows.
    Hover(FontFamily),
    /// `onLeave`: the pointer left the popup.
    Leave,
    /// `onPopupChange`: the popup opened or closed.
    PopupChange(bool),
    /// The trigger's `setAppState`: closes `openPopup` when it is
    /// "fontFamily" (`FontPickerTrigger.tsx:44-48`).
    TriggerSelect,
    /// `onTopPicksChange`: a drop's new picks, or `None` (the strip's
    /// context menu, the tip's reset link) for the defaults.
    TopPicksChange(Option<Vec<FontFamily>>),
    /// The strip's context menu opens at this client point, or closes:
    /// the host keeps it in [`FontPickerProps::top_picks_menu`].
    TopPicksMenu(Option<(i32, i32)>),
    /// A drag's state changed: render again.
    DragChange,
    /// The search box's term, trimmed and lowercased (the list's own
    /// state, debounced by 20 ms upstream).
    Search(String),
}

/// Called with each [`FontPickerEvent`].
pub type OnFontPickerEvent = Rc<dyn Fn(FontPickerEvent)>;

/// The app state the picker reads and its host writes, and the list's
/// search.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct FontPickerState {
    /// `appState.openPopup`.
    pub open_popup: Option<String>,
    /// The selection's font family (`currentItemFontFamily` with no text
    /// selected), `None` when mixed.
    pub selected: Option<FontFamily>,
    /// `appState.currentHoveredFontFamily`.
    pub hovered: Option<FontFamily>,
    /// `appState.fontTopPicks`.
    pub top_picks: Option<Vec<FontFamily>>,
    /// The list's search term; cleared when it closes.
    pub search: String,
}

fn family_of(v: Option<&Value>) -> Option<FontFamily> {
    v.and_then(Value::as_u64)
        .and_then(|n| u32::try_from(n).ok())
        .map(FontFamily)
}

impl FontPickerState {
    /// The picker's state from the app state and the selection's font
    /// family (the panel's `getFormValue`, `actionProperties.tsx:1371-1415`).
    pub fn from_app_state(app_state: &Map<String, Value>, selected: Option<FontFamily>) -> Self {
        FontPickerState {
            open_popup: app_state
                .get("openPopup")
                .and_then(Value::as_str)
                .map(str::to_owned),
            selected,
            hovered: family_of(app_state.get("currentHoveredFontFamily")),
            top_picks: app_state
                .get("fontTopPicks")
                .and_then(Value::as_array)
                .map(|a| a.iter().filter_map(|v| family_of(Some(v))).collect()),
            search: String::new(),
        }
    }

    /// `appState.openPopup === "fontFamily"`.
    pub fn is_open(&self) -> bool {
        self.open_popup.as_deref() == Some("fontFamily")
    }

    /// What the host's update does with one callback
    /// (`actionProperties.tsx:1440-1540` batching into `perform`).
    fn apply(&mut self, event: &FontPickerEvent) {
        match event {
            FontPickerEvent::Select(f) => {
                self.open_popup = None;
                self.hovered = None;
                self.selected = Some(*f);
            }
            FontPickerEvent::Hover(f) => self.hovered = Some(*f),
            FontPickerEvent::Leave => self.hovered = None,
            FontPickerEvent::PopupChange(true) => self.open_popup = Some("fontFamily".into()),
            FontPickerEvent::PopupChange(false) => self.hovered = None,
            FontPickerEvent::TriggerSelect => {
                if self.is_open() {
                    self.open_popup = None;
                }
            }
            FontPickerEvent::TopPicksChange(p) => self.top_picks = p.clone(),
            FontPickerEvent::Search(term) => self.search = term.clone(),
            FontPickerEvent::TopPicksMenu(_) | FontPickerEvent::DragChange => {}
        }
    }

    /// The list's search hover, if any (see [`hovered_font`]).
    fn settle(&mut self, cx: &FontListContext) -> Vec<FontPickerEvent> {
        if !self.is_open() {
            return Vec::new();
        }
        let (_, effect) = hovered_font(&filtered_fonts(cx, &self.search), self);
        match effect {
            Some(e) => {
                self.apply(&e);
                vec![e]
            }
            None => Vec::new(),
        }
    }

    /// The first render: an open list calls `onOpen` as it mounts
    /// (`FontPickerList.tsx:264-271`). Returns the callbacks made.
    pub fn mount(&mut self, cx: &FontListContext) -> Vec<FontPickerEvent> {
        if !self.is_open() {
            return Vec::new();
        }
        let open = FontPickerEvent::PopupChange(true);
        self.apply(&open);
        let mut calls = vec![open];
        calls.extend(self.settle(cx));
        calls
    }

    /// Applies an event and what follows from it: the list calls `onOpen`
    /// as it mounts and `onClose` as it unmounts, and hovers on a search.
    /// Returns the host callbacks made, in order (a search, the menu's
    /// point and a drag's render are the picker's own and not among them).
    pub fn dispatch(
        &mut self,
        event: FontPickerEvent,
        cx: &FontListContext,
    ) -> Vec<FontPickerEvent> {
        let was_open = self.is_open();
        self.apply(&event);
        let mut calls = Vec::new();
        if !matches!(
            event,
            FontPickerEvent::Search(_)
                | FontPickerEvent::TopPicksMenu(_)
                | FontPickerEvent::DragChange
        ) {
            calls.push(event);
        }
        let open = self.is_open();
        if was_open && !open {
            let close = FontPickerEvent::PopupChange(false);
            self.apply(&close);
            calls.push(close);
            self.search.clear();
        } else if !was_open && open {
            calls.extend(self.mount(cx));
        } else {
            calls.extend(self.settle(cx));
        }
        calls
    }
}

