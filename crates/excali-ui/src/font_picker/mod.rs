/// `FontPicker.scss`, `QuickSearch.scss`, `ScrollableList.scss` and
/// `TopPicksDnD.scss`, compiled (generated by `tools/goldens/font-picker.mjs`).
pub const FONT_PICKER_CSS: &str = include_str!("font_picker.css");

/// The `data-excali-ui` value of the `<style>` holding [`FONT_PICKER_CSS`].
const STYLESHEET_ID: &str = "font-picker";

/// Adds [`FONT_PICKER_CSS`] to `document`'s head once, after the dropdown
/// menu's stylesheet ([`crate::main_menu::install_stylesheet`], whose
/// items the list uses, and which it installs first).
pub fn install_stylesheet(document: &web_sys::Document) -> Result<(), wasm_bindgen::JsValue> {
    crate::main_menu::install_stylesheet(document)?;
    let selector = format!("style[data-excali-ui=\"{STYLESHEET_ID}\"]");
    if document.query_selector(&selector)?.is_some() {
        return Ok(());
    }
    let style = document.create_element("style")?;
    style.set_attribute("data-excali-ui", STYLESHEET_ID)?;
    style.set_text_content(Some(FONT_PICKER_CSS));
    let head = document
        .head()
        .ok_or_else(|| wasm_bindgen::JsValue::from_str("the document has no head"))?;
    head.append_child(&style)?;
    Ok(())
}

