/// A default top pick (`DEFAULT_FONTS`, `FontPicker.tsx:42-63`).
#[derive(Clone, Copy, Debug)]
pub struct DefaultFont {
    pub value: FontFamily,
    pub icon: &'static Icon,
    /// Its label's locale key.
    pub text_key: &'static str,
    pub test_id: &'static str,
}

/// The three default top picks.
pub const DEFAULT_FONTS: [DefaultFont; FONT_TOP_PICKS_SLOTS] = [
    DefaultFont {
        value: FontFamily::EXCALIFONT,
        icon: &icons::FreedrawIcon,
        text_key: "labels.handDrawn",
        test_id: "font-family-hand-drawn",
    },
    DefaultFont {
        value: FontFamily::NUNITO,
        icon: &icons::FontFamilyNormalIcon,
        text_key: "labels.normal",
        test_id: "font-family-normal",
    },
    DefaultFont {
        value: FontFamily::COMIC_SHANNS,
        icon: &icons::FontFamilyCodeIcon,
        text_key: "labels.code",
        test_id: "font-family-code",
    },
];

fn default_font(family: FontFamily) -> Option<&'static DefaultFont> {
    DEFAULT_FONTS.iter().find(|f| f.value == family)
}

/// `isDefaultFont` (`FontPicker.tsx:82-88`).
pub fn is_default_font(family: Option<FontFamily>) -> bool {
    family.is_some_and(|f| f.0 != 0 && default_font(f).is_some())
}

/// `getFontTopPicks` (`FontPicker.tsx:67-80`): the customised picks,
/// deduplicated and capped, padded with the defaults they lack.
pub fn get_font_top_picks(top_picks: &[FontFamily]) -> Vec<FontFamily> {
    let mut picks: Vec<FontFamily> = Vec::new();
    for f in top_picks {
        if !picks.contains(f) {
            picks.push(*f);
        }
    }
    picks.truncate(FONT_TOP_PICKS_SLOTS);
    for f in DEFAULT_FONTS.iter().map(|f| f.value) {
        if picks.len() >= FONT_TOP_PICKS_SLOTS {
            break;
        }
        if !picks.contains(&f) {
            picks.push(f);
        }
    }
    picks
}

/// The strip's picks: the customised ones when there are any, else the
/// defaults (`FontPicker.tsx:239-241`).
pub fn top_picks(custom: Option<&[FontFamily]>) -> Vec<FontFamily> {
    match custom {
        Some(p) if !p.is_empty() => get_font_top_picks(p),
        _ => DEFAULT_FONTS.iter().map(|f| f.value).collect(),
    }
}

/// `getFontFamilyIcon` (`FontPickerList.tsx:76-95`).
pub fn font_family_icon(family: FontFamily) -> &'static Icon {
    match family {
        FontFamily::EXCALIFONT | FontFamily::VIRGIL => &icons::FreedrawIcon,
        FontFamily::LILITA_ONE => &icons::FontFamilyHeadingIcon,
        FontFamily::COMIC_SHANNS | FontFamily::CASCADIA => &icons::FontFamilyCodeIcon,
        _ => &icons::FontFamilyNormalIcon,
    }
}

/// `getFontFamilyLabel` (`FontPickerList.tsx:97-104`): the `FONT_FAMILY`
/// name, else the registered family's name, else "Unknown".
pub fn font_family_label(family: FontFamily) -> String {
    if FontFamily::ELEMENT_FAMILIES.contains(&family) {
        if let Some(name) = family.name() {
            return name.to_owned();
        }
    }
    registered_family(family)
        .map(|r| r.family.to_owned())
        .unwrap_or_else(|| "Unknown".to_owned())
}

/// `getFontFamilyString({fontFamily})` (`common/src/utils.ts:123-136`),
/// the CSS family list an item's label is set in.
pub fn font_family_string(family: FontFamily) -> String {
    get_font_family_string(family)
}

/// A list item (`FontDescriptor`, `FontPickerList.tsx:55-64`).
#[derive(Clone, Debug, PartialEq)]
pub struct FontDescriptor {
    pub value: FontFamily,
    pub icon: &'static Icon,
    pub text: String,
    /// Badged "old" and left out of "Available fonts" unless
    /// `showDeprecatedFonts`.
    pub deprecated: bool,
}

/// Every family of the registry but the private and fallback ones, sorted
/// by label, case-insensitively (`FontPickerList.tsx:128-156`).
pub fn all_fonts() -> Vec<FontDescriptor> {
    let mut fonts: Vec<FontDescriptor> = registered_families()
        .iter()
        .filter(|r| font_metadata(r.id).is_some_and(|m| !m.private && !m.fallback))
        .map(|r| FontDescriptor {
            value: r.id,
            icon: font_family_icon(r.id),
            text: font_family_label(r.id),
            deprecated: font_metadata(r.id).is_some_and(|m| m.deprecated),
        })
        .collect();
    fonts.sort_by_key(|f| f.text.to_lowercase());
    fonts
}

/// What the list shows besides the search: the scene's families
/// (`app.fonts.getSceneFamilies()`) and the host's `showDeprecatedFonts`.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct FontListContext {
    pub scene_families: Vec<FontFamily>,
    pub show_deprecated_fonts: bool,
}

/// The two groups after the search (`FontPickerList.tsx:158-190,
/// 263-271`).
#[derive(Clone, Debug, Default, PartialEq)]
pub struct FilteredFonts {
    /// "In this scene": every font the scene uses, deprecated or not.
    pub scene: Vec<FontDescriptor>,
    /// "Available fonts": the rest, without the deprecated ones unless
    /// shown.
    pub available: Vec<FontDescriptor>,
}

impl FilteredFonts {
    /// Both groups in order (`filteredFonts`).
    pub fn all(&self) -> impl Iterator<Item = &FontDescriptor> {
        self.scene.iter().chain(&self.available)
    }
}

/// The list's fonts whose label contains `search` (already trimmed and
/// lowercased, as QuickSearch passes it).
pub fn filtered_fonts(cx: &FontListContext, search: &str) -> FilteredFonts {
    let mut out = FilteredFonts::default();
    for font in all_fonts() {
        if !font.text.to_lowercase().contains(search) {
            continue;
        }
        if cx.scene_families.contains(&font.value) {
            out.scene.push(font);
        } else if cx.show_deprecated_fonts || !font.deprecated {
            out.available.push(font);
        }
    }
    out
}

/// `hoveredFont` (`FontPickerList.tsx:192-222`): the hovered font, else
/// the selected one, if listed. With a search leaving neither listed, the
/// list hovers its first font, or leaves when it has none: that callback
/// is returned too.
pub fn hovered_font(
    filtered: &FilteredFonts,
    state: &FontPickerState,
) -> (Option<FontFamily>, Option<FontPickerEvent>) {
    let find = |f: FontFamily| filtered.all().find(|x| x.value == f).map(|x| x.value);
    let font = match (state.hovered, state.selected) {
        (Some(h), _) => find(h),
        (None, Some(s)) => find(s),
        (None, None) => None,
    };
    let effect =
        (font.is_none() && !state.search.is_empty()).then(|| match filtered.all().next() {
            Some(first) => FontPickerEvent::Hover(first.value),
            None => FontPickerEvent::Leave,
        });
    (font, effect)
}

// -- keyboard ------------------------------------------------------------------------

/// What a key does in the list.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FontPickerKeyEffect {
    /// Shift+F: focus the search box.
    FocusSearch,
    /// Escape: `onClose`.
    Close,
    Select(FontFamily),
    Hover(FontFamily),
}

/// Whether the list handled a key (and so prevents its default and stops
/// it), and what it does.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct FontPickerKeyOutcome {
    pub handled: bool,
    pub effect: Option<FontPickerKeyEffect>,
}

/// `fontPickerKeyHandler` (`keyboardNavHandlers.ts:17-68`) over the
/// listed fonts in order (`filtered`), the arrows wrapping around.
pub fn font_picker_key_handler(
    event: &KeyInput,
    hovered: Option<FontFamily>,
    filtered: &[FontFamily],
) -> FontPickerKeyOutcome {
    let handled = |effect| FontPickerKeyOutcome {
        handled: true,
        effect,
    };
    let index = hovered.and_then(|h| filtered.iter().position(|f| *f == h));
    if !event.ctrl_or_cmd && event.shift && event.key.to_lowercase() == "f" {
        return handled(Some(FontPickerKeyEffect::FocusSearch));
    }
    match event.key.as_str() {
        "Escape" => handled(Some(FontPickerKeyEffect::Close)),
        "Enter" => handled(index.map(|i| FontPickerKeyEffect::Select(filtered[i]))),
        "ArrowDown" => {
            let next = match index {
                Some(i) => filtered.get((i + 1) % filtered.len()),
                None => filtered.first(),
            };
            handled(next.map(|f| FontPickerKeyEffect::Hover(*f)))
        }
        "ArrowUp" => {
            let prev = match index {
                Some(i) => filtered.get((i + filtered.len() - 1) % filtered.len()),
                None => filtered.last(),
            };
            handled(prev.map(|f| FontPickerKeyEffect::Hover(*f)))
        }
        _ => FontPickerKeyOutcome {
            handled: false,
            effect: None,
        },
    }
}

