//! Top-picks drag and drop (`components/TopPicksDnD/topPicksDnD.tsx`):
//! pinning a value (a colour, later a font family) to a picker's top-picks
//! strip by dragging it there from the popup or the trigger, and reordering
//! the strip by dragging a pick, with pointer events and a ghost that
//! follows the pointer. The colour picker's use is
//! `ColorPicker/colorTopPicksDnD.ts`, in [`crate::color_picker`].
//!
//! [`TopPicksDnd`] holds `useTopPicksDnD`'s controller. Its session logic
//! is pure: pointer events, time and the strip's layout come in as
//! arguments ([`TopPicksDnd::pointer_down`], [`TopPicksDnd::pointer_move`],
//! [`TopPicksDnd::pointer_up`], [`TopPicksDnd::advance`] for upstream's
//! `setTimeout`s, [`TopPicksDnd::frame`] for its `requestAnimationFrame`),
//! and what upstream writes to the DOM comes out as state: the drag state
//! the strip renders ([`TopPicksDnd::drag_state`]), the ghosts in
//! `document.body` ([`TopPicksDnd::ghosts`], [`ghost_element`]) and the
//! body's class ([`TopPicksDnd::body_active`]). In a browser,
//! [`TopPicksDnd::start_drag`] runs a session from a pointerdown: it
//! listens on the window, reads `performance.now()` and the registered
//! strip's layout ([`TopPicksDnd::set_strip`]), keeps the ghosts' elements
//! in step and tells the host ([`TopPicksDnd::set_listener`]) when to render
//! again and which picks a drop made.

