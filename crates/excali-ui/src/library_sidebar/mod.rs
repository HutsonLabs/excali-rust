/// `LibraryUnit` (`LibraryUnit.tsx`).
fn library_unit(
    props: &LibrarySidebarProps<'_>,
    unit: UnitKey,
    name: Option<&str>,
    show_name: bool,
) -> Element {
    let state = props.state;
    let pending = unit == UnitKey::Pending;
    let selected = unit
        .id()
        .is_some_and(|id| state.selected_items.iter().any(|s| s == id));
    let hovered = state.hovered.as_ref() == Some(&unit);
    let preview = props.previews.get(&unit).cloned();
    let has_name = name.is_some_and(|n| !js_trim(n).is_empty());

    let on_click = props.on_event.clone();
    let click_unit = unit.clone();
    let drag_unit = unit.clone();
    let drag_selected = state.selected_items.clone();
    let on_drag = props.on_event.clone();
    let mut dragger = Element::new("div")
        .attr(
            "class",
            class_names([
                ("library-unit__dragger", true),
                ("library-unit__pulse", pending),
            ]),
        )
        .attr("draggable", "true")
        .on("click", move |e| {
            let shift = e.dyn_ref::<MouseEvent>().is_some_and(MouseEvent::shift_key);
            emit(
                &on_click,
                LibrarySidebarEvent::UnitClick {
                    unit: click_unit.clone(),
                    shift,
                },
            );
        })
        .on("dragstart", move |e| {
            match drag_data(&drag_unit, &drag_selected) {
                DragStart::Prevent => e.prevent_default(),
                DragStart::Data { mime, data } => {
                    emit(
                        &on_drag,
                        LibrarySidebarEvent::UnitHover {
                            unit: drag_unit.clone(),
                            hovered: false,
                        },
                    );
                    if let Some(transfer) = e
                        .dyn_ref::<web_sys::DragEvent>()
                        .and_then(web_sys::DragEvent::data_transfer)
                    {
                        let _ = transfer.set_data(&mime, &data);
                    }
                }
            }
        });
    if show_name {
        dragger = dragger
            .child(
                Element::new("div")
                    .attr("class", "library-unit__preview")
                    .child_opt(preview.clone()),
            )
            .child(
                Element::new("div")
                    .attr("class", "library-unit__name")
                    .child(name.unwrap_or("")),
            );
    } else {
        dragger = dragger.child_opt(preview.clone());
    }

    let on_enter = props.on_event.clone();
    let on_leave = props.on_event.clone();
    let enter_unit = unit.clone();
    let leave_unit = unit.clone();
    let mut el = Element::new("div")
        .attr(
            "class",
            class_names([
                ("library-unit", true),
                ("library-unit__active", true),
                ("library-unit--hover", hovered),
                ("library-unit--selected", selected),
                ("library-unit--skeleton", preview.is_none()),
                ("library-unit--named", show_name),
            ]),
        )
        .on("mouseenter", move |_| {
            emit(
                &on_enter,
                LibrarySidebarEvent::UnitHover {
                    unit: enter_unit.clone(),
                    hovered: true,
                },
            )
        })
        .on("mouseleave", move |_| {
            emit(
                &on_leave,
                LibrarySidebarEvent::UnitHover {
                    unit: leave_unit.clone(),
                    hovered: false,
                },
            )
        });
    if has_name {
        let label = name.unwrap_or("").to_owned();
        el = el
            .on("pointerenter", move |e| {
                let Some(target) = e
                    .current_target()
                    .and_then(|t| t.dyn_into::<web_sys::Element>().ok())
                else {
                    return;
                };
                // a name shown below the item needs no tooltip unless cut
                if show_name {
                    if let Ok(Some(name)) = target.query_selector(".library-unit__name") {
                        if name.scroll_width() <= name.client_width() {
                            return;
                        }
                    }
                }
                crate::primitives::show_tooltip(
                    &target,
                    &label,
                    crate::primitives::TooltipOptions {
                        long: false,
                        delay: true,
                        placement: crate::primitives::TooltipPlacement::Top,
                    },
                );
            })
            .on("pointerleave", hide_tooltip_of)
            .on("pointerdown", hide_tooltip_of);
    }
    el = el.child(dragger);
    if pending {
        el = el.child(
            Element::new("div")
                .attr("class", "library-unit__adder")
                .child(icon_node(&icons::PlusIcon, props.theme)),
        );
    }
    if let Some(id) = unit.id() {
        if hovered || props.context.phone || selected {
            el = el.child(checkbox(props, id, selected));
        }
    }
    el
}

fn hide_tooltip_of(e: &Event) {
    if let Some(document) = event_document(e) {
        crate::primitives::hide_tooltip(&document);
    }
}

