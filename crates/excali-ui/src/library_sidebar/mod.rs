/// The search's matches (`LibraryMenuItems.tsx:86-98`): the items whose
/// trimmed name is not empty and whose deburred, lower-cased name holds the
/// deburred, lower-cased, trimmed query; none for a blank query.
pub fn filter_library_items<'a>(items: &'a [LibraryItem], query: &str) -> Vec<&'a LibraryItem> {
    let query = deburr(&js_trim(query).to_lowercase());
    if query.is_empty() {
        return Vec::new();
    }
    items
        .iter()
        .filter(|item| {
            let name = item.name.as_deref().unwrap_or("");
            !js_trim(name).is_empty() && deburr(&name.to_lowercase()).contains(&query)
        })
        .collect()
}

/// The header menu's entries for `selected` selected items of `items`
/// items in the library (`LibraryMenuHeaderContent.tsx:206-238`): the
/// items it acts on are the selected ones when any, else all.
pub fn library_menu_actions(selected: usize, items: usize) -> Vec<LibraryMenuAction> {
    let items_selected = selected > 0;
    let count = if items_selected { selected } else { items };
    let mut out = Vec::new();
    if !items_selected {
        out.push(LibraryMenuAction::Load);
    }
    if count > 0 {
        out.push(LibraryMenuAction::Export);
    }
    if items_selected {
        out.push(LibraryMenuAction::Publish);
    }
    if count > 0 {
        out.push(if items_selected {
            LibraryMenuAction::Remove
        } else {
            LibraryMenuAction::Reset
        });
    }
    out
}

