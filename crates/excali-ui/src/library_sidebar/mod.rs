/// `Sidebar.TabTrigger` in radix's `Tabs.Trigger`: selects on a primary
/// mousedown, Enter, Space, or focus (automatic activation).
fn tab_trigger(
    props: &LibrarySidebarProps<'_>,
    tab: &'static str,
    icon: &Icon,
    open_tab: Option<&str>,
) -> Element {
    let active = open_tab == Some(tab);
    let on_down = props.on_event.clone();
    let on_key = props.on_event.clone();
    let on_focus = props.on_event.clone();
    Element::new("button")
        .attr("type", "button")
        .attr("role", "tab")
        .attr("aria-selected", active.to_string())
        .attr(
            "aria-controls",
            format!("{}-content-{tab}", props.id_prefix),
        )
        .attr("data-state", if active { "active" } else { "inactive" })
        .attr("id", format!("{}-trigger-{tab}", props.id_prefix))
        .attr("class", "excalidraw-button sidebar-tab-trigger")
        .attr(
            "tabindex",
            if props.state.tab_stop.as_deref() == Some(tab) {
                "0"
            } else {
                "-1"
            },
        )
        .attr("data-orientation", "horizontal")
        .attr("data-radix-collection-item", "")
        .on("mousedown", move |e| {
            let Some(m) = e.dyn_ref::<MouseEvent>() else {
                return;
            };
            if m.button() == 0 && !m.ctrl_key() {
                emit(&on_down, LibrarySidebarEvent::SelectTab(tab.into()));
            } else {
                // radix keeps focus off the trigger for other presses
                e.prevent_default();
            }
        })
        .on("keydown", move |e| {
            if let Some(k) = e.dyn_ref::<KeyboardEvent>() {
                if matches!(k.key().as_str(), " " | "Enter") {
                    emit(&on_key, LibrarySidebarEvent::SelectTab(tab.into()));
                }
            }
        })
        .on("focus", move |_| {
            if !active {
                emit(&on_focus, LibrarySidebarEvent::SelectTab(tab.into()));
            }
        })
        .child(icon_node(icon, props.theme))
}

/// `Sidebar.Tab` in radix's `Tabs.Content`: empty and hidden while
/// inactive.
fn tab_panel(props: &LibrarySidebarProps<'_>, tab: &str, children: Vec<Node>) -> Element {
    let active = props.context.open_tab() == Some(tab);
    let el = Element::new("div")
        .attr("data-state", if active { "active" } else { "inactive" })
        .attr("data-orientation", "horizontal")
        .attr("role", "tabpanel")
        .attr(
            "aria-labelledby",
            format!("{}-trigger-{tab}", props.id_prefix),
        )
        .flag("hidden", !active)
        .attr("id", format!("{}-content-{tab}", props.id_prefix))
        .attr("tabindex", "0")
        .attr("data-testid", tab);
    if active {
        el.style_opt(
            "animation-duration",
            (!props.state.rerendered).then_some("0s"),
        )
        .children_from(children)
    } else {
        el
    }
}

