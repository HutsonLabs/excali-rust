/// `LibraryDropdownMenu` (`LibraryMenuHeaderContent.tsx:195-261`): the
/// header menu and the selection's count.
fn library_dropdown(props: &LibrarySidebarProps<'_>) -> Element {
    let cx = &props.context;
    let state = props.state;
    let open = state.menu_open;
    let (trigger_id, content_id) = &props.menu_ids;
    let on_toggle = props.on_event.clone();
    let trigger = Element::new("button")
        .attr("type", "button")
        .attr("id", trigger_id.clone())
        .attr("aria-haspopup", "menu")
        .attr("aria-expanded", open.to_string())
        .attr_opt("aria-controls", open.then(|| content_id.clone()))
        .attr("data-state", if open { "open" } else { "closed" })
        .attr(
            "class",
            format!(
                "dropdown-menu-button  zen-mode-transition{}",
                if cx.phone {
                    " dropdown-menu-button--mobile"
                } else {
                    ""
                }
            ),
        )
        .attr("data-testid", "dropdown-menu-button")
        // radix's trigger: a primary press keeps focus off it while closed
        .on("pointerdown", move |e| {
            let Some(m) = e.dyn_ref::<MouseEvent>() else {
                return;
            };
            if m.button() == 0 && !m.ctrl_key() && !open {
                e.prevent_default();
            }
        })
        .on("click", move |_| {
            emit(&on_toggle, LibrarySidebarEvent::MenuToggle)
        })
        .child(icon_node(&icons::DotsIcon, props.theme));
    let mut wrapper = Element::new("div")
        .attr("class", crate::main_menu::DROPDOWN_MENU_EVENT_WRAPPER)
        .style("display", "contents")
        .child(trigger);
    if open {
        wrapper = wrapper.child(dropdown_content(props, trigger_id, content_id));
    }
    let mut container = Element::new("div")
        .attr(
            "class",
            "library-menu-dropdown-container library-menu-dropdown-container--in-heading",
        )
        .child(wrapper);
    if !state.selected_items.is_empty() {
        container = container.child(
            Element::new("div")
                .attr("class", "library-actions-counter")
                .child(state.selected_items.len().to_string()),
        );
    }
    container
}

