/// `LibraryMenuItems` (`LibraryMenuItems.tsx:366-441`).
fn library_menu_items(props: &LibrarySidebarProps<'_>) -> Element {
    let cx = &props.context;
    let state = props.state;
    let empty = cx.is_library_empty();
    let searching = !empty && !js_trim(&state.search).is_empty();
    let unpublished = cx.unpublished();
    let published = cx.published();
    let any = !cx.pending.is_empty() || !unpublished.is_empty() || !published.is_empty();

    let mut header = Element::new("div").attr("class", "library-menu-items-header");
    if !empty {
        header = header.child(search_field(props));
    }
    header = header.child(library_dropdown(props));

    let mut items: Vec<Node> = Vec::new();
    if cx.status.is_loading() {
        items.push(
            Element::new("div")
                .style("position", "absolute")
                .style("top", "var(--container-padding-y)")
                .style("right", "var(--container-padding-x)")
                .style("transform", "translateY(50%)")
                .child(spinner("1em"))
                .into(),
        );
    }
    if searching {
        items.extend(when_searching(props));
    } else {
        items.extend(when_not_searching(props, &unpublished, &published));
    }
    if empty {
        items.push(
            control_buttons(
                props,
                "",
                vec![
                    ("padding".into(), "16px 0".into()),
                    ("width".into(), "100%".into()),
                ],
            )
            .into(),
        );
    }
    let list = stack_col(
        StackProps {
            gap: Some(1.0),
            align: Some(Align::Start),
            class_name: Some("library-menu-items-container__items".into()),
            style: vec![
                (
                    "flex".into(),
                    if published.is_empty() {
                        "0 1 auto"
                    } else {
                        "1"
                    }
                    .into(),
                ),
                ("margin".into(), if empty { "auto" } else { "0" }.into()),
            ],
            ..StackProps::default()
        },
        items,
    );
    let container = Element::new("div").attr("class", "library-menu-items-container");
    let container = if any {
        container.style("justify-content", "flex-start")
    } else {
        container.style("border-bottom", "0")
    };
    container.child(header).child(list)
}

/// The search field (`LibraryMenuItems.tsx:378-397`), focused once
/// mounted.
fn search_field(props: &LibrarySidebarProps<'_>) -> Element {
    let on_change = props.on_event.clone();
    let class = class_names([
        ("library-menu-items-container__search", true),
        ("hideCancelButton", !props.context.phone),
    ]);
    text_field(TextFieldProps {
        value: TextFieldValue::Controlled(props.state.search.clone()),
        on_change: Some(Rc::new(move |value| {
            emit(&on_change, LibrarySidebarEvent::SearchInput(value))
        })),
        class_name: Some(class),
        placeholder: Some(library_text("library.search.inputPlaceholder").into()),
        kind: Some(TextFieldType::Search),
        ..TextFieldProps::default()
    })
    .on_mount(|el| {
        let Ok(Some(input)) = el.query_selector("input") else {
            return;
        };
        let focused = input
            .owner_document()
            .and_then(|d| d.active_element())
            .is_some_and(|a| a.closest("input, textarea").ok().flatten().is_some());
        if !focused {
            if let Some(input) = input.dyn_ref::<web_sys::HtmlInputElement>() {
                let _ = input.focus();
                // a field built again keeps the caret at the end
                let end = input.value().encode_utf16().count() as u32;
                let _ = input.set_selection_range(end, end);
            }
        }
    })
}

/// The sections while not searching (`LibraryMenuItems.tsx:248-315`).
fn when_not_searching(
    props: &LibrarySidebarProps<'_>,
    unpublished: &[&LibraryItem],
    published: &[&LibraryItem],
) -> Vec<Node> {
    let cx = &props.context;
    let mut out: Vec<Node> = Vec::new();
    if !cx.is_library_empty() {
        out.push(section_header(library_text("labels.personalLib"), false).into());
    }
    if cx.pending.is_empty() && unpublished.is_empty() {
        let mut none = Element::new("div").attr("class", "library-menu-items__no-items");
        if published.is_empty() {
            none = none.child(
                Element::new("div")
                    .attr("class", "library-menu-items__no-items__label")
                    .child(library_text("library.noItems")),
            );
        }
        none = none.child(
            Element::new("div")
                .attr("class", "library-menu-items__no-items__hint")
                .child(library_text(if published.is_empty() {
                    "library.hint_emptyLibrary"
                } else {
                    "library.hint_emptyPrivateLibrary"
                })),
        );
        out.push(none.into());
    } else {
        let mut units: Vec<Node> = Vec::new();
        if !cx.pending.is_empty() {
            units.push(library_unit(props, UnitKey::Pending, None, false).into());
        }
        units.extend(unpublished.iter().map(|i| unit_for(props, i, false)));
        out.push(grid(units, false).into());
    }
    if !published.is_empty() {
        out.push(section_header(library_text("labels.excalidrawLib"), true).into());
        out.push(
            grid(
                published
                    .iter()
                    .map(|i| unit_for(props, i, false))
                    .collect(),
                false,
            )
            .into(),
        );
    }
    out
}

