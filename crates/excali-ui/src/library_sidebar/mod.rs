//! The library sidebar: upstream's `DefaultSidebar`
//! (`components/DefaultSidebar.tsx`) as LayerUI renders it, over the
//! Sidebar parts (`components/Sidebar/*`: the island, the header with the
//! Search and Library tab triggers and the dock and close buttons, the
//! tabs), with the `LibraryMenu` in its library tab (`LibraryMenu.tsx`,
//! `LibraryMenuItems.tsx`, `LibraryMenuSection.tsx`, `LibraryUnit.tsx`,
//! `LibraryMenuHeaderContent.tsx`, `LibraryMenuControlButtons.tsx`,
//! `LibraryMenuBrowseButton.tsx`), and LayerUI's library trigger
//! (`DefaultSidebar.Trigger`, `LayerUI.tsx:481-499`).
//!
//! Layout (research `ui-design-system.md` §3.6): the header's tab triggers
//! (Search, Library), then the dock button (while the sidebar fits and the
//! search tab does not force docking) and close; in the library tab the
//! search field and the header menu (Load, Export, Publish, Reset or
//! Remove), the "Personal Library" section (the selection waiting to be
//! added, then the unpublished items), the "Excalidraw Library" section
//! (published items), or the matches of a search, and the "Browse
//! libraries" link. The sidebar is `RIGHT_SIDEBAR_WIDTH` (302 px) less the
//! island's outer margin wide ([`LIBRARY_SIDEBAR_CSS`]).
//!
//! [`default_sidebar`] builds the DOM for the host's state
//! ([`LibrarySidebarProps`]: the app state keys it reads in a
//! [`LibraryContext`], the library, the previews the host renders and the
//! menu's own [`LibraryMenuState`]); what the user does comes back as
//! [`LibrarySidebarEvent`]s, which the host runs through [`update`]: it
//! updates the menu state and returns the [`LibraryEffect`]s upstream's
//! handlers have (app state patches, items to insert with
//! `excali_editor::edit_actions::insert_library_items`, the library to
//! store, files to load or save), then the host renders again. Dragging an
//! item puts [`drag_data`] on the drag (`MIME_TYPE_EXCALIDRAWLIB_IDS`),
//! which the canvas's drop reads back.
//!
//! The dialogs the header menu opens (the Reset and Remove confirmation,
//! the publish dialog and its success dialog) are [`library_dialogs`]
//! (`dialogs.rs`); the host mounts them with `primitives::open_modal`, and
//! does the files, storage and network their effects ask for
//! ([`LibraryEffect::LoadLibrary`], [`LibraryEffect::ExportLibrary`],
//! [`LibraryEffect::LoadPublishData`], [`LibraryEffect::SavePublishData`],
//! [`LibraryEffect::SubmitLibrary`]).
//!
//! Not here: the search tab's content (`SearchMenu`, ex-708; the host's
//! [`LibrarySidebarProps::search_menu`]), host sidebars and tab
//! triggers (`Sidebar` with another name, `DefaultSidebar.TabTriggers`),
//! radix's arrow-key roving focus among the tab triggers, and the
//! batched rendering of long sections (`LibraryMenuSection` renders 17 or
//! 64 units per transition; every unit is built here).

