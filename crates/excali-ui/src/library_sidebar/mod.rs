/// What the sidebar reads of the editor: the app state keys, the editor
/// interface, the library and the elements waiting to be added.
#[derive(Clone, Debug)]
pub struct LibraryContext<'a> {
    /// `appState.openSidebar`.
    pub open_sidebar: Option<OpenSidebar>,
    /// `appState.defaultSidebarDockedPreference`.
    pub docked_preference: bool,
    /// `editorInterface.canFitSidebar`.
    pub can_fit_sidebar: bool,
    /// `editorInterface.formFactor === "phone"`.
    pub phone: bool,
    pub status: LibraryStatus,
    /// The library's items, in order.
    pub items: &'a [LibraryItem],
    /// The pending elements ([`pending_elements`]): the selection the
    /// library offers to add.
    pub pending: &'a [SceneElement],
}

impl LibraryContext<'_> {
    fn open_tab(&self) -> Option<&str> {
        self.open_sidebar.as_ref().and_then(|o| o.tab.as_deref())
    }

    /// The default sidebar is the open one.
    fn is_open(&self) -> bool {
        self.open_sidebar
            .as_ref()
            .is_some_and(|o| o.name == DEFAULT_SIDEBAR_NAME)
    }

    /// `isForceDocked`: the search tab docks the sidebar.
    fn force_docked(&self) -> bool {
        self.open_tab() == Some(CANVAS_SEARCH_TAB)
    }

    /// DefaultSidebar's `docked`.
    fn docked(&self) -> bool {
        self.force_docked() || self.docked_preference
    }

    /// The dock button shows: the sidebar fits and LayerUI's `onDock`
    /// is not dropped for the search tab (`SidebarHeader.tsx:22-24`).
    fn can_dock(&self) -> bool {
        self.can_fit_sidebar && !self.force_docked()
    }

    /// The library tab's content is mounted.
    fn library_mounted(&self) -> bool {
        self.is_open() && self.open_tab() == Some(LIBRARY_SIDEBAR_TAB)
    }

    fn unpublished(&self) -> Vec<&LibraryItem> {
        self.items
            .iter()
            .filter(|i| i.status != LibraryItemStatus::Published)
            .collect()
    }

    fn published(&self) -> Vec<&LibraryItem> {
        self.items
            .iter()
            .filter(|i| i.status == LibraryItemStatus::Published)
            .collect()
    }

    fn is_library_empty(&self) -> bool {
        self.items.is_empty() && self.pending.is_empty()
    }
}

/// `isSidebarDockedAtom` as the default sidebar leaves it: rendered and
/// docked.
pub fn is_sidebar_docked(cx: &LibraryContext<'_>) -> bool {
    cx.is_open() && cx.docked()
}

/// LayerUI's `isSidebarDockedAndFits` (`LayerUI.tsx:462-466`): the UI gives
/// the sidebar `--right-sidebar-width` (`layer-ui__wrapper`'s width) and
/// hides the library trigger.
pub fn is_sidebar_docked_and_fits(cx: &LibraryContext<'_>) -> bool {
    cx.open_sidebar.is_some() && is_sidebar_docked(cx) && cx.can_fit_sidebar
}

