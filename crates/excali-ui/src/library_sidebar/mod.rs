/// The library menu's own state (LibraryMenu's and LibraryMenuItems'
/// `useState`s, and `isLibraryMenuOpenAtom`).
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct LibraryMenuState {
    /// `selectedItems`, in the order they were selected.
    pub selected_items: Vec<String>,
    /// `lastSelectedItem`: where a Shift range starts.
    pub last_selected_item: Option<String>,
    /// `searchInputValue`.
    pub search: String,
    /// The unit under the mouse (`isHovered`).
    pub hovered: Option<UnitKey>,
    /// `isLibraryMenuOpenAtom`: the header menu is open.
    pub menu_open: bool,
    /// The tab trigger radix's roving focus group made the tab stop (the
    /// last one pressed or focused; `tabindex="0"`), until the sidebar
    /// closes.
    pub tab_stop: Option<String>,
    /// The sidebar rendered again since it opened (the app state changed
    /// while it was open; [`update`] notes its own patches, the host any
    /// other). Until then the tab panel active at mount keeps radix's
    /// `animation-duration: 0s`, which stops its mount animation.
    pub rerendered: bool,
    /// `showRemoveLibAlert`: the Reset or Remove confirmation is open.
    pub confirm_open: bool,
    /// `showPublishLibraryDialog`, with the dialog's own state.
    pub publish: Option<PublishState>,
    /// `publishLibSuccess`: the success dialog is open.
    pub publish_success: Option<PublishSuccess>,
}

impl LibraryMenuState {
    /// The library tab's content unmounts (another tab, or the sidebar
    /// closes): LibraryMenu's and LibraryMenuItems' own state goes with it
    /// (the header menu's atom stays).
    fn unmount_library(&mut self) {
        self.selected_items.clear();
        self.last_selected_item = None;
        self.search.clear();
        self.hovered = None;
        // the header menu's dialogs are LibraryDropdownMenuButton's state
        self.confirm_open = false;
        self.publish = None;
        self.publish_success = None;
    }

    /// The sidebar closes.
    fn close(&mut self) {
        self.unmount_library();
        self.tab_stop = None;
        self.rerendered = false;
    }
}

