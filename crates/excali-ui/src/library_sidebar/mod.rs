/// `onItemSelectToggle(id, event)` (`LibraryMenuItems.tsx:129-178`): select
/// (a Shift click after a selection extends it over the range between, in
/// the order unpublished then published), or deselect.
fn toggle_item(state: &mut LibraryMenuState, cx: &LibraryContext<'_>, id: &str, shift: bool) {
    let should_select = !state.selected_items.iter().any(|s| s == id);
    if should_select {
        let ordered: Vec<&str> = cx
            .unpublished()
            .into_iter()
            .chain(cx.published())
            .map(|i| i.id.as_str())
            .collect();
        match state.last_selected_item.as_deref().filter(|_| shift) {
            Some(last) => {
                let start = ordered.iter().position(|i| *i == last);
                let end = ordered.iter().position(|i| *i == id);
                match (start, end) {
                    (Some(start), Some(end)) => {
                        let (min, max) = (start.min(end), start.max(end));
                        let next = ordered
                            .iter()
                            .enumerate()
                            .filter(|(i, item)| {
                                (*i >= min && *i <= max)
                                    || state.selected_items.iter().any(|s| s == *item)
                            })
                            .map(|(_, item)| (*item).to_owned())
                            .collect();
                        state.selected_items = next;
                    }
                    _ => {
                        state.selected_items.push(id.to_owned());
                        return;
                    }
                }
            }
            None => state.selected_items.push(id.to_owned()),
        }
        state.last_selected_item = Some(id.to_owned());
    } else {
        state.last_selected_item = None;
        state.selected_items.retain(|s| s != id);
    }
}

fn set_selected(state: &mut LibraryMenuState, selected: Vec<String>) {
    state.selected_items = selected;
    // an emptied selection forgets where a range starts
    if state.selected_items.is_empty() {
        state.last_selected_item = None;
    }
}

/// `LIBRARY_DISABLED_TYPES` (`common/src/constants.ts:542-546`), in order.
fn disabled_type(elements: &[SceneElement]) -> Option<&'static str> {
    let has = |f: fn(&ElementKind) -> bool| elements.iter().any(|e| f(&e.kind));
    if has(|k| matches!(k, ElementKind::Iframe)) {
        Some("iframe")
    } else if has(|k| matches!(k, ElementKind::Embeddable)) {
        Some("embeddable")
    } else if has(|k| matches!(k, ElementKind::Image(_))) {
        Some("image")
    } else {
        None
    }
}

/// The ids of `ids`' items, in library order.
fn in_library_order(items: &[LibraryItem], ids: &[String]) -> Vec<String> {
    items
        .iter()
        .filter(|i| ids.contains(&i.id))
        .map(|i| i.id.clone())
        .collect()
}

/// Runs an event through upstream's handlers: updates `state` and returns
/// what else they do. `env` draws a new item's id and creation time
/// (`randomId()`, `Date.now()`).
pub fn update(
    state: &mut LibraryMenuState,
    event: LibrarySidebarEvent,
    cx: &LibraryContext<'_>,
    env: &mut dyn RestoreEnv,
) -> Update {
    let mut out = Update::default();
    let was_open = cx.is_open();
    let effects = &mut out.effects;
    match event {
        LibrarySidebarEvent::SelectTab(tab) => {
            // radix's controlled value changes only to another tab
            if let Some(open) = &cx.open_sidebar {
                state.tab_stop = Some(tab.clone());
                if open.tab.as_deref() != Some(tab.as_str()) {
                    if tab != LIBRARY_SIDEBAR_TAB {
                        state.unmount_library();
                    }
                    effects.push(LibraryEffect::SetAppState(patch([(
                        "openSidebar",
                        json!({"name": open.name, "tab": tab}),
                    )])));
                }
            }
        }
        LibrarySidebarEvent::Close => effects.push(close_sidebar(state)),
        LibrarySidebarEvent::Dock(docked) => {
            // LayerUI's onDock, then DefaultSidebar's
            effects.push(LibraryEffect::TrackEvent(
                "sidebar".into(),
                format!("toggleDock ({})", if docked { "dock" } else { "undock" }),
                format!("({})", form_factor(cx)),
            ));
            effects.push(LibraryEffect::SetAppState(patch([(
                "defaultSidebarDockedPreference",
                json!(docked),
            )])));
        }
        LibrarySidebarEvent::ToggleTrigger => {
            let next_open = !cx.is_open();
            if !next_open {
                state.close();
            }
            effects.push(LibraryEffect::SetAppState(patch([
                (
                    "openSidebar",
                    if next_open {
                        json!({"name": DEFAULT_SIDEBAR_NAME, "tab": LIBRARY_SIDEBAR_TAB})
                    } else {
                        Value::Null
                    },
                ),
                ("openMenu", Value::Null),
                ("openPopup", Value::Null),
            ])));
            if next_open {
                effects.push(LibraryEffect::TrackEvent(
                    "sidebar".into(),
                    format!("{DEFAULT_SIDEBAR_NAME} (open)"),
                    format!("button ({})", form_factor(cx)),
                ));
            }
        }
        LibrarySidebarEvent::UnitClick { unit, shift } => match unit {
            UnitKey::Item(id) if shift => toggle_item(state, cx, &id, shift),
            UnitKey::Item(id) => {
                let ids = if state.selected_items.contains(&id) {
                    in_library_order(cx.items, &state.selected_items)
                } else {
                    in_library_order(cx.items, std::slice::from_ref(&id))
                };
                effects.push(LibraryEffect::Insert(ids));
                effects.push(LibraryEffect::FocusContainer);
            }
            UnitKey::Pending => add_to_library(cx, effects, env),
        },
        LibrarySidebarEvent::CheckboxToggle { id, shift } => toggle_item(state, cx, &id, shift),
        LibrarySidebarEvent::UnitHover { unit, hovered } => {
            if hovered {
                state.hovered = Some(unit);
            } else if state.hovered.as_ref() == Some(&unit) {
                state.hovered = None;
            }
        }
        LibrarySidebarEvent::SearchInput(value) => state.search = value,
        LibrarySidebarEvent::ClearSearch => state.search.clear(),
        LibrarySidebarEvent::KeyDown {
            key,
            target,
            dialog_open,
        } => {
            if key != "Escape" || !cx.is_open() {
                return out;
            }
            let outcome = escape_outcome(
                cx.library_mounted(),
                !state.selected_items.is_empty(),
                state.menu_open,
                &target,
            );
            out.prevent_default = outcome.prevent_default();
            out.stop_propagation = outcome != EscapeOutcome::PassOn;
            match outcome {
                EscapeOutcome::ClearSelection { close_menu } => {
                    set_selected(state, Vec::new());
                    state.menu_open &= !close_menu;
                }
                EscapeOutcome::CloseAndFocus { close_menu } => {
                    state.menu_open &= !close_menu;
                    out.effects.push(close_sidebar(state));
                    out.effects.push(LibraryEffect::FocusContainer);
                }
                EscapeOutcome::CloseMenu => state.menu_open = false,
                EscapeOutcome::ClearSearch => state.search.clear(),
                // Sidebar's listener: an undocked (or unfitting) sidebar
                // closes
                EscapeOutcome::PassOn => {
                    if (!cx.docked() || !cx.can_fit_sidebar) && !dialog_open {
                        out.effects.push(close_sidebar(state));
                    }
                }
            }
        }
        LibrarySidebarEvent::OutsideClick {
            on_trigger,
            dialog_open,
        } => {
            if !on_trigger && (!cx.docked() || !cx.can_fit_sidebar) && !dialog_open {
                effects.push(close_sidebar(state));
            }
        }
        LibrarySidebarEvent::MenuToggle => state.menu_open = !state.menu_open,
        LibrarySidebarEvent::MenuClose => state.menu_open = false,
        LibrarySidebarEvent::MenuSelect(action) => {
            state.menu_open = false;
            let selected = in_library_order(cx.items, &state.selected_items);
            match action {
                LibraryMenuAction::Load => effects.push(LibraryEffect::LoadLibrary),
                LibraryMenuAction::Export => {
                    let ids = if state.selected_items.is_empty() {
                        cx.items.iter().map(|i| i.id.clone()).collect()
                    } else {
                        selected
                    };
                    effects.push(LibraryEffect::ExportLibrary(ids));
                }
                LibraryMenuAction::Publish => {
                    state.publish = Some(PublishState::default());
                    effects.push(LibraryEffect::LoadPublishData);
                }
                LibraryMenuAction::Reset | LibraryMenuAction::Remove => state.confirm_open = true,
            }
        }
        LibrarySidebarEvent::ConfirmCancel => {
            confirm_button(state, effects);
            state.confirm_open = false;
            effects.push(LibraryEffect::FocusContainer);
        }
        LibrarySidebarEvent::ConfirmAccept => {
            confirm_button(state, effects);
            if state.selected_items.is_empty() {
                effects.push(LibraryEffect::ResetLibrary);
            } else {
                // LibraryDropdownMenu's removeFromLibrary
                let next = cx
                    .items
                    .iter()
                    .filter(|i| !state.selected_items.contains(&i.id))
                    .cloned()
                    .collect();
                effects.push(LibraryEffect::SetLibrary(next));
                effects.push(LibraryEffect::DeletePreviews(state.selected_items.clone()));
                set_selected(state, Vec::new());
            }
            state.confirm_open = false;
            effects.push(LibraryEffect::FocusContainer);
        }
        LibrarySidebarEvent::DialogClose(which) => {
            // Dialog's onClose, then the dialog's onCloseRequest
            effects.push(LibraryEffect::SetAppState(patch([(
                "openMenu",
                Value::Null,
            )])));
            state.menu_open = false;
            match which {
                LibraryDialog::Confirm => state.confirm_open = false,
                LibraryDialog::Publish => close_publish(state, cx, effects),
                LibraryDialog::PublishSuccess => state.publish_success = None,
            }
        }
        LibrarySidebarEvent::PublishSaveNames => close_publish(state, cx, effects),
        LibrarySidebarEvent::PublishDataLoaded(data) => {
            if let (Some(publish), Some(data)) = (state.publish.as_mut(), data) {
                publish.data = data;
            }
        }
        LibrarySidebarEvent::PublishInput { field, value } => {
            if let Some(publish) = state.publish.as_mut() {
                publish.data.set(field, value);
            }
        }
        LibrarySidebarEvent::PublishItemName { id, value } => {
            if let Some(publish) = state.publish.as_mut() {
                // the dialog's items are the library's own until a submit
                // fails validation
                if !publish.detached {
                    publish.library_names.insert(id.clone(), value.clone());
                }
                publish.dialog_names.insert(id, value);
            }
        }
        LibrarySidebarEvent::PublishRemoveItem(id) => {
            let next = state
                .selected_items
                .iter()
                .filter(|s| **s != id)
                .cloned()
                .collect();
            set_selected(state, next);
            // the items change: clonedLibItems are the library's again
            if let Some(publish) = state.publish.as_mut() {
                publish.dialog_names = publish.library_names.clone();
                publish.detached = false;
                publish.errors.clear();
            }
        }
        LibrarySidebarEvent::PublishSubmit => {
            if let Some(publish) = state.publish.as_ref() {
                let items = dialogs::publish_items(cx, state, publish);
                let errors: std::collections::HashMap<String, String> = items
                    .iter()
                    .map(|i| {
                        let error = if i.name.as_deref().unwrap_or("").is_empty() {
                            library_text("publishDialog.errors.required")
                        } else {
                            ""
                        };
                        (i.id.clone(), error.to_owned())
                    })
                    .collect();
                let publish = state.publish.as_mut().expect("the publish dialog is open");
                if errors.values().any(|e| !e.is_empty()) {
                    publish.errors = errors;
                    publish.detached = true;
                    publish.submitting = false;
                } else {
                    publish.submitting = true;
                    effects.push(LibraryEffect::SubmitLibrary {
                        items,
                        data: publish.data.clone(),
                    });
                }
            }
        }
        LibrarySidebarEvent::PublishSucceeded { url } => {
            if let Some(publish) = state.publish.take() {
                effects.push(LibraryEffect::SavePublishData(None));
                // onPublishLibSuccess: the library, its selected items
                // published
                let next = cx
                    .items
                    .iter()
                    .map(|i| {
                        let mut item = dialogs::named(i, &publish.library_names);
                        if state.selected_items.contains(&item.id) {
                            item.status = LibraryItemStatus::Published;
                        }
                        item
                    })
                    .collect();
                state.publish_success = Some(PublishSuccess {
                    url,
                    author_name: publish.data.author_name,
                });
                effects.push(LibraryEffect::SetLibrary(next));
            }
        }
        LibrarySidebarEvent::PublishFailed(message) => {
            if let Some(publish) = state.publish.as_mut() {
                effects.push(LibraryEffect::Alert(message));
                publish.submitting = false;
            }
        }
        LibrarySidebarEvent::PublishSuccessClose => state.publish_success = None,
    }
    // an app state change renders an open sidebar again (one that closes
    // has been reset, one that opens mounts)
    let patched = out
        .effects
        .iter()
        .any(|e| matches!(e, LibraryEffect::SetAppState(_)));
    let closes = out.effects.iter().any(|e| match e {
        LibraryEffect::SetAppState(p) => p.get("openSidebar") == Some(&Value::Null),
        _ => false,
    });
    if patched && was_open && !closes {
        state.rerendered = true;
    }
    out
}

/// A confirmation button's `setAppState({ openMenu: null })` and
/// `setIsLibraryMenuOpen(false)` (`ConfirmDialog.tsx:44-73`); the button
/// then focuses the container.
fn confirm_button(state: &mut LibraryMenuState, effects: &mut Vec<LibraryEffect>) {
    effects.push(LibraryEffect::SetAppState(patch([(
        "openMenu",
        Value::Null,
    )])));
    state.menu_open = false;
}

/// PublishLibrary's `onDialogClose`: the library stored with the names
/// typed (`updateItemsInStorage`, which stores the library's items), the
/// fields saved, the dialog closed.
fn close_publish(
    state: &mut LibraryMenuState,
    cx: &LibraryContext<'_>,
    effects: &mut Vec<LibraryEffect>,
) {
    let Some(publish) = state.publish.take() else {
        return;
    };
    effects.push(LibraryEffect::SetLibrary(
        cx.items
            .iter()
            .map(|i| dialogs::named(i, &publish.library_names))
            .collect(),
    ));
    effects.push(LibraryEffect::SavePublishData(Some(publish.data)));
}

/// What Escape does in the library before Sidebar's own listener sees it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum EscapeOutcome {
    /// LibraryMenu's capture listener clears the selection (stopped); an
    /// open header menu closes too.
    ClearSelection { close_menu: bool },
    /// It closes the sidebar from an empty input and focuses the canvas
    /// (stopped); an open header menu closes too.
    CloseAndFocus { close_menu: bool },
    /// The open header menu's capture listener closes it (prevented,
    /// stopped immediately).
    CloseMenu,
    /// The search field's handler clears it (prevented and stopped).
    ClearSearch,
    /// Nothing handles it: on to Sidebar's listener.
    PassOn,
}

impl EscapeOutcome {
    fn prevent_default(self) -> bool {
        matches!(
            self,
            EscapeOutcome::CloseMenu
                | EscapeOutcome::ClearSearch
                | EscapeOutcome::ClearSelection { close_menu: true }
                | EscapeOutcome::CloseAndFocus { close_menu: true }
        )
    }
}

/// LibraryMenu's capture listener on the document (`LibraryMenu.tsx:
/// 252-293`, while the library tab is mounted), then the open header
/// menu's (`DropdownMenuContent.tsx:62-85`, bound later, which stops the
/// event from going further), then the search field's handler
/// (`LibraryMenuItems.tsx:388-396`).
fn escape_outcome(
    library_mounted: bool,
    has_selection: bool,
    menu_open: bool,
    target: &KeyTarget,
) -> EscapeOutcome {
    if !library_mounted {
        return EscapeOutcome::PassOn;
    }
    let close_menu = menu_open;
    match target {
        KeyTarget::SearchInput { .. } | KeyTarget::InSidebar { .. } => {
            let empty_input = match target {
                KeyTarget::SearchInput { value } => value.is_empty(),
                KeyTarget::InSidebar { empty_input } => *empty_input,
                KeyTarget::Outside { .. } => false,
            };
            if has_selection {
                return EscapeOutcome::ClearSelection { close_menu };
            }
            if empty_input {
                return EscapeOutcome::CloseAndFocus { close_menu };
            }
        }
        KeyTarget::Outside {
            cursor_over_sidebar,
        } => {
            if has_selection && *cursor_over_sidebar {
                return EscapeOutcome::ClearSelection { close_menu };
            }
        }
    }
    if menu_open {
        return EscapeOutcome::CloseMenu;
    }
    match target {
        KeyTarget::SearchInput { value } if !value.is_empty() => EscapeOutcome::ClearSearch,
        _ => EscapeOutcome::PassOn,
    }
}

/// A click on the pending unit: `LibraryMenuContent._onAddToLibrary`
/// (`LibraryMenu.tsx:72-103`) and `LibraryMenu.deselectItems`.
fn add_to_library(
    cx: &LibraryContext<'_>,
    effects: &mut Vec<LibraryEffect>,
    env: &mut dyn RestoreEnv,
) {
    effects.push(LibraryEffect::TrackEvent(
        "element".into(),
        "addToLibrary".into(),
        "ui".into(),
    ));
    if let Some(ty) = disabled_type(cx.pending) {
        effects.push(LibraryEffect::SetAppState(patch([(
            "errorMessage",
            json!(library_text(&format!(
                "errors.libraryElementTypeError.{ty}"
            ))),
        )])));
        return;
    }
    let item = LibraryItem::new(
        env.random_id(),
        LibraryItemStatus::Unpublished,
        cx.pending.to_vec(),
        env.now(),
    );
    effects.push(LibraryEffect::SetAppState(patch([
        ("selectedElementIds", json!({})),
        ("selectedGroupIds", json!({})),
        ("activeEmbeddable", Value::Null),
    ])));
    let mut next = vec![item];
    next.extend(cx.items.iter().cloned());
    effects.push(LibraryEffect::SetLibrary(next));
}

/// What a drag of a unit puts on the drag (`LibraryMenuItems.onItemDrag`,
/// `LibraryUnit.tsx:78-85`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum DragStart {
    /// The pending unit is not dragged: the default is prevented.
    Prevent,
    /// `dataTransfer.setData(mime, data)`: the ids of the dragged items,
    /// `{"itemIds": [...]}` (the selection when the item is in it).
    Data { mime: String, data: String },
}

/// The drag data for a unit, given the selected items.
pub fn drag_data(unit: &UnitKey, selected: &[String]) -> DragStart {
    match unit {
        UnitKey::Pending => DragStart::Prevent,
        UnitKey::Item(id) => {
            let ids: Vec<&str> = if selected.contains(id) {
                selected.iter().map(String::as_str).collect()
            } else {
                vec![id]
            };
            DragStart::Data {
                mime: MIME_TYPE_EXCALIDRAWLIB_IDS.into(),
                data: json!({ "itemIds": ids }).to_string(),
            }
        }
    }
}

/// The item ids a drop's `MIME_TYPE_EXCALIDRAWLIB_IDS` data names
/// (`App.tsx:13206-13213`); `None` for data that is not such JSON.
pub fn dropped_item_ids(data: &str) -> Option<Vec<String>> {
    let value: Value = serde_json::from_str(data).ok()?;
    value["itemIds"]
        .as_array()?
        .iter()
        .map(|v| v.as_str().map(str::to_owned))
        .collect()
}

/// `getPendingElements` (`LibraryMenu.tsx:162-177`): the selected elements
