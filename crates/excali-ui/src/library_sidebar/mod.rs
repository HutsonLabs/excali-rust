fn patch<const N: usize>(entries: [(&str, Value); N]) -> Map<String, Value> {
    entries
        .into_iter()
        .map(|(k, v)| (k.to_owned(), v))
        .collect()
}

fn close_sidebar(state: &mut LibraryMenuState) -> LibraryEffect {
    state.close();
    LibraryEffect::SetAppState(patch([("openSidebar", Value::Null)]))
}

