/// `fuzzy.match(pattern, str)` of fuzzy 0.1.3: the characters of `pattern`
/// in order in `s`, ignoring case, scored by runs of consecutive matches;
/// infinite when the two are equal ignoring case. Both are read as UTF-16
/// code units, as JavaScript indexes them.
pub fn fuzzy_match(pattern: &str, s: &str) -> Option<f64> {
    let original: Vec<u16> = s.encode_utf16().collect();
    let compare: Vec<u16> = s.to_lowercase().encode_utf16().collect();
    let pattern: Vec<u16> = pattern.to_lowercase().encode_utf16().collect();
    let mut pattern_idx = 0;
    let mut total = 0.0;
    let mut current = 0.0;
    for idx in 0..original.len() {
        if pattern_idx < pattern.len() && compare.get(idx) == Some(&pattern[pattern_idx]) {
            pattern_idx += 1;
            // `currScore += 1 + currScore`
            current = 2.0 * current + 1.0;
        } else {
            current = 0.0;
        }
        total += current;
    }
    (pattern_idx == pattern.len()).then(|| {
        if compare == pattern {
            f64::INFINITY
        } else {
            total
        }
    })
}

/// `fuzzy.filter(pattern, commands, {extract: haystack})`, then upstream's
/// sort by score: the matches, best first, ties in list order.
fn fuzzy_filter(pattern: &str, commands: Vec<PaletteCommand>) -> Vec<PaletteCommand> {
    let mut scored: Vec<(f64, PaletteCommand)> = commands
        .into_iter()
        .filter_map(|c| fuzzy_match(pattern, &c.haystack).map(|score| (score, c)))
        .collect();
    // stable: equal scores (including two infinite ones) keep their order
    scored.sort_by(|a, b| b.0.partial_cmp(&a.0).unwrap_or(std::cmp::Ordering::Equal));
    scored.into_iter().map(|(_, c)| c).collect()
}

