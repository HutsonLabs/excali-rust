/// What the palette's window keydown handler did.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct PaletteKeyOutcome {
    /// The command to select, when the selection moves.
    pub current: Option<String>,
    /// Run the selected command (Enter; upstream defers it with
    /// `setTimeout`).
    pub execute: bool,
    pub prevent_default: bool,
    pub stop_propagation: bool,
    /// Focus the search input (a letter or digit typed outside it).
    pub focus_input: bool,
}

/// `handleKeyDown` (`CommandPalette.tsx:691-799`), the palette's window
/// keydown listener (capture phase): the arrows move the selection through
/// the shown commands (wrapping, through the last used one when shown and
/// available), Enter runs it, a letter or digit outside the input focuses
/// the input, and every other key outside the input is kept from the
/// editor. `writable_target` is `isWritableElement(event.target)`,
/// `toggle_shortcut` [`excali_editor::keyboard::is_command_palette_toggle_shortcut`].
pub fn palette_key_down(
    view: &PaletteView,
    key: &str,
    writable_target: bool,
    toggle_shortcut: bool,
) -> PaletteKeyOutcome {
    let mut out = PaletteKeyOutcome::default();
    let ignore_alphanumerics = writable_target || toggle_shortcut || key == "Escape";
    if ignore_alphanumerics && !matches!(key, "ArrowUp" | "ArrowDown" | "Enter") {
        return out;
    }
    let matching: Vec<&PaletteCommand> = view.matching().collect();
    let current = view.current.as_deref();
    let index = matching
        .iter()
        .position(|c| Some(c.label.as_str()) == current);
    let last_used = view.considers_last_used();
    let is_last_used = last_used.is_some_and(|l| Some(l.label.as_str()) == current);
    let label = |c: &PaletteCommand| Some(c.label.clone());
    match key {
        "ArrowUp" => {
            out.prevent_default = true;
            if let Some(last_used) = last_used {
                if index == Some(0) {
                    out.current = label(last_used);
                    return out;
                }
                if is_last_used {
                    out.current = matching.last().and_then(|c| label(c));
                    return out;
                }
            }
            let next = match index {
                None | Some(0) => matching.len().checked_sub(1),
                Some(i) => Some(i - 1),
            };
            out.current = next.and_then(|i| matching.get(i)).and_then(|c| label(c));
            return out;
        }
        "ArrowDown" => {
            out.prevent_default = true;
            if let Some(last_used) = last_used {
                if current.is_none() || index == matching.len().checked_sub(1) {
                    out.current = label(last_used);
                    return out;
                }
                if is_last_used {
                    out.current = matching.first().and_then(|c| label(c));
                    return out;
                }
            }
            let next = match index {
                None => 0,
                Some(i) => i + 1,
            };
            out.current = (!matching.is_empty())
                .then(|| matching[next % matching.len()])
                .and_then(label);
            return out;
        }
        "Enter" => out.execute = current.is_some(),
        _ => {}
    }
    if ignore_alphanumerics {
        return out;
    }
    out.stop_propagation = true;
    let mut chars = key.chars();
    if let (Some(c), None) = (chars.next(), chars.next()) {
        if c.is_ascii_alphanumeric() {
            out.focus_input = true;
            return out;
        }
    }
    out.prevent_default = true;
    out
}

