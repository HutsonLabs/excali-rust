//! The command palette (`components/CommandPalette/CommandPalette.tsx`,
//! `CommandPalette.scss`): a [`dialog`] 720 px wide with a search field,
//! the key hints and the commands by category (research
//! `ui-design-system.md` §3.14).
//!
//! [`palette_commands`] is the palette's `allCommands` as data: the
//! commands built from actions ([`commands_from_actions`]), the additional
//! ones (library, search, shape switch, the colour pickers, each tool, the
//! tool lock, text to diagram and Mermaid) and the host's own
//! (`customCommandPaletteItems`; [`hosted_app_links`] are the hosted app's
//! Links), each with the availability `isCommandAvailable` gives it;
//! [`library_commands`] are the named library items. [`palette_view`]
//! filters, searches (upstream's `fuzzy` 0.1.3, [`fuzzy_match`]) and groups
//! them by category in `getCategoryOrder`'s order (App, Export, Editor,
//! Tools, Elements, Links, then Library), [`palette_key_down`] is the
//! palette's window key handler and [`command_palette`] builds the DOM
//! upstream renders. `tests/command_palette.rs` holds all of them to
//! `tests/fixtures/command-palette.json`.
//!
//! The host opens the palette while `appState.openDialog.name` is
//! `"commandPalette"` (Ctrl/Cmd+/ or Ctrl/Cmd+Shift+P:
//! [`excali_editor::keyboard::command_palette_key_down`]) and, to run a
//! command, closes it and applies [`perform_command`]'s effects.

