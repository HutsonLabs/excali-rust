/// `shortcut.replace("++", "+$").split("+")` (`CommandShortcutHint`,
/// `CommandPalette.tsx:116-139`): the keys of a shortcut hint.
pub fn shortcut_keys(shortcut: &str) -> Vec<String> {
    shortcut
        .replacen("++", "+$", 1)
        .split('+')
        .map(|k| {
            if k == "$" {
                "+".to_owned()
            } else {
                k.to_owned()
            }
        })
        .collect()
}

/// `CommandShortcutHint`: each key in a wrapper, then the description.
fn shortcut_hint(shortcut: &str, desc: Option<&str>) -> Element {
    Element::new("div")
        .attr("class", "shortcut")
        .children_from(shortcut_keys(shortcut).into_iter().map(|key| {
            Node::Element(
                Element::new("div")
                    .attr("class", "shortcut-wrapper")
                    .child(Element::new("div").attr("class", "shortcut-key").child(key)),
            )
        }))
        .child(
            Element::new("div")
                .attr("class", "shortcut-desc")
                .children_from(desc.map(Node::text)),
        )
}

fn icon_node(name: &str, theme: Theme) -> Node {
    let icon = icons::icon(name).unwrap_or_else(|| panic!("icons.tsx has no {name}"));
    Node::Element(
        icon.element(theme)
            .unwrap_or_else(|| panic!("{name} is a path list")),
    )
}

/// `InlineIcon` (`components/InlineIcon.tsx`) with `className="icon"` and
/// `size="var(--icon-size, 1rem)"`.
fn inline_icon(icon: Node) -> Element {
    Element::new("span")
        .attr("class", "icon")
        .style("width", "var(--icon-size, 1rem)")
        .style("height", "100%")
        // React's `margin: "0 0.5ex 0 0.5ex"`, as the DOM serializes it
        .style("margin", "0px 0.5ex 0px 0.5ex")
        .style("display", "inline-flex")
        .style("line-height", "0")
        .style("vertical-align", "middle")
        .style("flex", "0 0 auto")
        .child(icon)
}

/// `Ellipsify` (`components/Ellipsify.tsx`).
fn ellipsify(text: &str) -> Element {
    Element::new("span")
        .style("text-overflow", "ellipsis")
        .style("overflow", "hidden")
        .style("white-space", "nowrap")
        .child(text)
}

/// A library item's preview by id.
pub type LibraryPreview = Rc<dyn Fn(&str) -> Option<Node>>;

/// The palette's props.
#[derive(Clone, Default)]
pub struct CommandPaletteProps {
    pub view: PaletteView,
    /// The search field's value.
    pub search: String,
    pub is_darwin: bool,
    /// The phone form factor: full screen, no key hints or shortcuts.
    pub phone: bool,
    pub theme: Theme,
    /// The editor container's id.
    pub container_id: String,
    /// The search field changed.
    pub on_search: Option<Rc<dyn Fn(String)>>,
    /// A command was clicked, by label.
    pub on_execute: Option<Rc<dyn Fn(String)>>,
    /// The pointer moved over a command, by label: it becomes the current
    /// one.
    pub on_hover: Option<Rc<dyn Fn(String)>>,
    /// `onCloseRequest`: the host sets `openDialog` to null.
    pub on_close: Option<Rc<dyn Fn()>>,
    /// A library item's preview, by id, for its icon.
    pub library_preview: Option<LibraryPreview>,
}

/// `CommandItem` (`CommandPalette.tsx:985-1043`).
fn command_item(
    props: &CommandPaletteProps,
    command: &PaletteCommand,
    disabled: bool,
    large: bool,
) -> Element {
    let selected = props.view.current.as_deref() == Some(command.label.as_str());
    let mut class = String::from("command-item");
    if selected {
        class.push_str(" item-selected");
    }
    if disabled {
        class.push_str(" item-disabled");
    }
    if large {
        class.push_str(" command-item-large");
    }
    let icon = match (&command.library_item, command.icon) {
        (Some(id), _) => Some(Node::Element(
            Element::new("div")
                .attr("class", "library-item-icon")
                .children_from(props.library_preview.as_ref().and_then(|p| p(id))),
        )),
        (None, Some(name)) => Some(icon_node(name, props.theme)),
        (None, None) => None,
    };
    let mut item = Element::new("div")
        .attr("class", class)
        .attr(
            "title",
            if disabled {
                palette_text("commandPalette.itemNotAvailable")
            } else {
                ""
            },
        )
        .child(
            Element::new("div")
                .attr("class", "name")
                .children_from(icon.map(|i| Node::Element(inline_icon(i))))
                .child(ellipsify(&command.label)),
        )
        .children_from(
            command
                .shortcut
                .as_deref()
                .filter(|_| !props.phone)
                .map(|s| Node::Element(shortcut_hint(s, None))),
        );
    if selected && !disabled {
        item = item.on_mount(|el| {
            let options = web_sys::ScrollIntoViewOptions::new();
            options.set_block(web_sys::ScrollLogicalPosition::Nearest);
            el.scroll_into_view_with_scroll_into_view_options(&options);
        });
    }
    if !disabled {
        if let Some(on_execute) = props.on_execute.clone() {
            let label = command.label.clone();
            item = item.on("click", move |e| {
                e.stop_propagation();
                e.prevent_default();
                on_execute(label.clone());
            });
        }
        if let Some(on_hover) = props.on_hover.clone() {
            let label = command.label.clone();
            item = item.on("mousemove", move |_| on_hover(label.clone()));
        }
    }
    item
}

/// The palette's `div.commands`: the last used command under "Recently
/// used", then each category, or "No matching commands..." when nothing
/// matches (`CommandPalette.tsx:884-929`).
pub fn command_list(props: &CommandPaletteProps) -> Element {
    let recents = props.view.recents.as_ref().map(|recent| {
        Node::Element(
            Element::new("div")
                .attr("class", "command-category")
                .child(
                    Element::new("div")
                        .attr("class", "command-category-title")
                        .child(palette_text("commandPalette.recents"))
                        .child(
                            Element::new("div")
                                .attr("class", "icon")
                                .style("margin-left", "6px")
                                .child(icon_node("historyCommandIcon", props.theme)),
                        ),
                )
                .child(command_item(
                    props,
                    &recent.command,
                    !recent.available,
                    false,
                )),
        )
    });
    let body: Vec<Node> = if props.view.categories.is_empty() {
        vec![Node::Element(
            Element::new("div")
                .attr("class", "no-match")
                .child(
                    Element::new("div")
                        .attr("class", "icon")
                        .child(icon_node("searchIcon", props.theme)),
                )
                .child(" ")
                .child(palette_text("commandPalette.search.noMatch")),
        )]
    } else {
        props
            .view
            .categories
            .iter()
            .map(|(title, items)| {
                let large = title == PaletteCategory::Library.as_str();
                Node::Element(
                    Element::new("div")
                        .attr("class", "command-category")
                        .child(
                            Element::new("div")
                                .attr("class", "command-category-title")
                                .child(title.clone()),
                        )
                        .children_from(
                            items
                                .iter()
                                .map(|c| Node::Element(command_item(props, c, false, large))),
                        ),
                )
            })
            .collect()
    };
    Element::new("div")
        .attr("class", "commands")
        .children_from(recents)
        .children_from(body)
}

/// `CommandPaletteInner`'s dialog (`CommandPalette.tsx:858-931`): the modal
/// container the dialog portals to the body
/// ([`crate::primitives::open_modal`] mounts it there).
pub fn command_palette(props: CommandPaletteProps) -> Element {
    let field = text_field(TextFieldProps {
        value: TextFieldValue::Controlled(props.search.clone()),
        placeholder: Some(palette_text("commandPalette.search.placeholder").to_owned()),
        on_change: props.on_search.clone(),
        select_on_render: true,
        ..TextFieldProps::default()
    });
    let hints = (!props.phone).then(|| {
        let esc = get_shortcut_key("Esc", props.is_darwin, &KeyLabels::EN);
        Node::Element(
            Element::new("div")
                .attr("class", "shortcuts-wrapper")
                .child(shortcut_hint(
                    "↑↓",
                    Some(palette_text("commandPalette.shortcuts.select")),
                ))
                .child(shortcut_hint(
                    "↵",
                    Some(palette_text("commandPalette.shortcuts.confirm")),
                ))
                .child(shortcut_hint(
                    &esc,
                    Some(palette_text("commandPalette.shortcuts.close")),
                )),
        )
    });
    let list = command_list(&props);
    dialog(
        DialogProps {
            class_name: Some("command-palette-dialog".into()),
            size: DialogSize::Px(720.0),
            title: None,
            autofocus: true,
            close_on_click_outside: true,
            container_id: props.container_id,
            theme: props.theme,
            phone: props.phone,
            on_close_request: props.on_close,
            ..DialogProps::default()
        },
        std::iter::once(Node::Element(field))
            .chain(hints)
            .chain(std::iter::once(Node::Element(list)))
            .collect(),
    )
}
