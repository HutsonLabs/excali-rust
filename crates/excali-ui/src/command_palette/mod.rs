/// What the palette shows (`CommandPalette.tsx:858-909`).
#[derive(Debug, Clone, Default, PartialEq)]
pub struct PaletteView {
    /// The last used command, shown while the search is empty.
    pub recents: Option<PaletteRecent>,
    /// `commandsByCategory`: each category in first-appearance order.
    pub categories: Vec<(String, Vec<PaletteCommand>)>,
    /// `currentCommand`'s label.
    pub current: Option<String>,
}

impl PaletteView {
    /// `Object.values(commandsByCategory).flat()`.
    fn matching(&self) -> impl Iterator<Item = &PaletteCommand> {
        self.categories.iter().flat_map(|(_, items)| items)
    }

    /// The command labelled `label`, among the shown ones.
    pub fn command(&self, label: &str) -> Option<&PaletteCommand> {
        self.recents
            .iter()
            .map(|r| &r.command)
            .chain(self.matching())
            .find(|c| c.label == label)
    }

    /// Whether the last used command takes part in the arrow keys.
    fn considers_last_used(&self) -> Option<&PaletteCommand> {
        self.recents
            .as_ref()
            .filter(|r| r.available)
            .map(|r| &r.command)
    }
}

fn by_category(commands: Vec<PaletteCommand>) -> Vec<(String, Vec<PaletteCommand>)> {
    let mut out: Vec<(String, Vec<PaletteCommand>)> = Vec::new();
    for command in commands {
        let title = command.category.as_str();
        match out.iter_mut().find(|(t, _)| t == title) {
            Some((_, items)) => items.push(command),
            None => out.push((title.to_owned(), vec![command])),
        }
    }
    out
}

/// The palette's list for `search` (`CommandPalette.tsx:771-834`): the
/// available commands by category order, the library items too once the
/// search has two characters, fuzzy-matched and best first while
/// searching; with an empty search the last used command (`last_used`,
/// found by label among `commands` and `library`) under "Recently used"
/// and selected when available, else the first command.
pub fn palette_view(
    commands: &[PaletteCommand],
    library: &[PaletteCommand],
    search: &str,
    last_used: Option<&str>,
) -> PaletteView {
    let last_used = last_used.and_then(|label| {
        commands
            .iter()
            .chain(library)
            .find(|c| c.label == label)
            .cloned()
    });
    let mut matching: Vec<PaletteCommand> =
        commands.iter().filter(|c| c.available).cloned().collect();
    matching.sort_by_key(|c| c.order);
    if search.encode_utf16().count() > 1 {
        matching.extend(library.iter().cloned());
    }
    if search.is_empty() {
        let recents = last_used.map(|command| PaletteRecent {
            available: command.available,
            command,
        });
        let shown = recents.as_ref().filter(|r| r.available);
        if let Some(shown) = shown {
            matching.retain(|c| c.label != shown.command.label);
        }
        let current = shown
            .map(|r| r.command.label.clone())
            .or_else(|| matching.first().map(|c| c.label.clone()));
        return PaletteView {
            recents,
            categories: by_category(matching),
            current,
        };
    }
    let query: String = search
        .to_lowercase()
        .chars()
        .filter(|c| !matches!(c, '<' | '>' | '_' | '|' | ' ' | '-'))
        .collect();
    let matching = fuzzy_filter(&deburr(&query), matching);
    let current = matching.first().map(|c| c.label.clone());
    PaletteView {
        recents: None,
        categories: by_category(matching),
        current,
    }
}

