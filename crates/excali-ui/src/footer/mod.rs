//! The footer: the desktop `Footer` (`components/footer/Footer.tsx`) with
//! `ZoomActions`, `UndoRedoActions` and `ExitZenModeButton`
//! (`components/Actions.tsx:877-929`), the `HelpButton`
//! (`components/HelpButton.tsx`), and the panels the zoom and history
//! actions render there (`actions/actionCanvas.tsx` `actionZoomIn`,
//! `actionZoomOut`, `actionResetZoom`; `actions/actionHistory.tsx`
//! `createUndoAction`, `createRedoAction`).
//!
//! Layout (`Footer.tsx:37-91`, research `ui-design-system.md` §3.4): on
//! the left, in the "Canvas actions" section, zoom out, the zoom level
//! (reset zoom) and zoom in, then undo and redo; the host's centre content
//! (`FooterCenterTunnel`); on the right the welcome screen's help hint and
//! the help button; last the exit-zen-mode button, shown by the host's
//! `showExitZenModeBtn` (`disable-zen-mode--visible`). Zen mode fades the
//! left, undo/redo and right groups out in place (the transition classes);
//! view mode drops undo/redo; the zoom actions need navigation enabled.
//!
//! [`footer`] builds the DOM upstream leaves (`tests/footer.rs` holds every
//! case of `tests/fixtures/footer.json` to it); a click on a control
//! reports its [`FooterControl`], whose [`FooterControl::action`] the host
//! runs: the zoom actions with `excali_editor::viewport::perform_zoom_action`
//! ([`FooterControl::zoom_action`]), undo and redo with the history, help
//! with [`toggle_shortcuts`] and exit zen with [`toggle_zen_mode`]. The
//! styles are the footer's rules of upstream's stylesheets ([`FOOTER_CSS`]);
//! zen mode's own look needs the container's `excalidraw--zen-mode` class,
//! which is the host's.
//!
//! Not ported here: the phone layout's footer (`MobileMenu.tsx`), where the
//! history buttons take `MOBILE_ACTION_BUTTON_BG`, and the actions'
//! analytics.

