/// `ColorPickerTrigger` (`ColorPicker.tsx:267-351`), a radix
/// `Popover.Trigger`.
fn trigger(props: &ColorPickerProps) -> Node {
    let color = props.color.as_deref().filter(|c| !c.is_empty());
    let display = color.map(|c| props.display_color(c));
    let class = class_names([
        ("color-picker__button active-color properties-trigger", true),
        ("is-transparent", color.is_none_or(|c| c == "transparent")),
        (
            "has-outline",
            color.is_none_or(|c| !is_color_dark(c, Some(COLOR_OUTLINE_CONTRAST_THRESHOLD))),
        ),
        ("compact-sizing", props.compact()),
        ("mobile-border", props.mode == StylesPanelMode::Mobile),
    ]);
    let title = color_picker_text(match props.ty {
        ColorPickerType::ElementStroke => "labels.showStroke",
        _ => "labels.showBackground",
    });
    let on_event = props.on_event.clone();
    let mut button = Element::new("button")
        .attr("type", "button")
        .attr("aria-haspopup", "dialog")
        .attr("aria-expanded", props.open.to_string())
        .attr("aria-controls", props.popup_id.as_str())
        .attr("data-state", if props.open { "open" } else { "closed" })
        .attr("class", class)
        .attr("aria-label", props.label.as_str())
        .style_opt("--swatch-color", display.clone())
        .attr("title", title)
        .attr("data-openpopup", props.ty.as_str())
        .on("click", move |e: &Event| {
            e.prevent_default();
            e.stop_propagation();
            if let Some(f) = &on_event {
                f(ColorPickerEvent::Trigger);
            }
        })
        .child(
            Element::new("div")
                .attr("class", "color-picker__button-outline")
                .child_opt(color.is_none().then(|| icon("slashIcon"))),
        );
    if let (true, Some(display), ColorPickerType::ElementStroke) =
        (props.compact(), &display, props.ty)
    {
        let text = if is_color_dark(display, Some(COLOR_OUTLINE_CONTRAST_THRESHOLD)) {
            "#fff"
        } else {
            "#111"
        };
        button = button.child(
            Element::new("div")
                .attr("class", "color-picker__button-background")
                .child(
                    Element::new("span")
                        .style("color", text)
                        .child(icon("strokeIcon")),
                ),
        );
    }
    // the active colour can be dragged onto the strip to pin it
    draggable(button, props, props.color.as_deref(), DragOrigin::Source).into()
}

