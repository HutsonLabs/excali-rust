/// `appState.openPopup` after the trigger is pressed
/// (`ColorPicker.tsx:462-474`): closed when this picker's popup is open,
/// else this picker's (switching from any other popup).
pub fn toggle_popup(open_popup: Option<&str>, ty: ColorPickerType) -> Option<String> {
    if open_popup == Some(ty.as_str()) {
        None
    } else {
        Some(ty.as_str().to_owned())
    }
}

/// `appState.openPopup` after the popup closes (`onClose`,
/// `ColorPicker.tsx:151-156`): cleared only while it is still this
/// picker's. The active section is cleared too.
pub fn close_popup(open_popup: Option<&str>, ty: ColorPickerType) -> Option<String> {
    if open_popup == Some(ty.as_str()) {
        None
    } else {
        open_popup.map(str::to_owned)
    }
}

/// Whether a top pick moves `openPopup` to its own picker
/// (`ColorPicker.tsx:431-443`): another colour picker's popup is open.
/// Upstream defers that update a tick so it does not overwrite the colour
/// change.
pub fn top_pick_follows_focus(open_popup: Option<&str>, ty: ColorPickerType) -> bool {
    open_popup
        .and_then(ColorPickerType::from_popup)
        .is_some_and(|open| open != ty)
}

/// `activeEyeDropperAtom`'s value (`EyeDropper.tsx:39-51`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct EyeDropperState {
    /// Opened with Alt held: it stays while Alt is.
    pub keep_open_on_alt: bool,
    /// The picker whose colour it picks.
    pub picker: ColorPickerType,
}

/// `onEyeDropperToggle(force)` (`ColorPicker.tsx:181-203`): `Some(true)`
/// (Alt) opens it, or keeps it, open while Alt is held; otherwise it
/// toggles, and `Some(false)` (Alt released) closes it.
pub fn toggle_eye_dropper(
    state: Option<EyeDropperState>,
    force: Option<bool>,
    ty: ColorPickerType,
) -> Option<EyeDropperState> {
    if force == Some(true) {
        let state = state.unwrap_or(EyeDropperState {
            keep_open_on_alt: true,
            picker: ty,
        });
        return Some(EyeDropperState {
            keep_open_on_alt: true,
            ..state
        });
    }
    if force == Some(false) || state.is_some() {
        None
    } else {
        Some(EyeDropperState {
            keep_open_on_alt: false,
            picker: ty,
        })
    }
}

