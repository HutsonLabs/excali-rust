/// `ColorInput` (`ColorInput.tsx:98-153`) under its heading
/// (`ColorPicker.tsx:106-120`).
fn color_input(props: &ColorPickerProps) -> Node {
    let error = props.hex.error;
    let on_event = props.on_event.clone();
    let emit = move |event: ColorPickerEvent| {
        if let Some(f) = &on_event {
            f(event);
        }
    };
    let input = {
        let (on_input, on_blur, on_focus) = (emit.clone(), emit.clone(), emit.clone());
        let el = Element::new("input")
            .style("border", "0")
            .style("padding", "0")
            .attr("spellcheck", "false")
            .attr("class", "color-picker-input")
            .attr("aria-label", props.label.as_str())
            .attr("aria-invalid", error.is_some().to_string())
            .attr("value", hex_input_value(&props.hex.inner_value))
            .attr("tabindex", "-1")
            .attr("placeholder", color_picker_text("colorPicker.color"))
            .on("input", move |e: &Event| {
                if let Some(input) = e
                    .target()
                    .and_then(|t| t.dyn_into::<HtmlInputElement>().ok())
                {
                    on_input(ColorPickerEvent::HexInput(input.value()));
                }
            })
            .on("blur", move |_| on_blur(ColorPickerEvent::HexBlur))
            .on("focus", move |_| on_focus(ColorPickerEvent::HexFocus))
            .on("keydown", |e: &Event| {
                let Some(e) = e.dyn_ref::<KeyboardEvent>() else {
                    return;
                };
                match e.key().as_str() {
                    "Tab" => return,
                    "Escape" => {
                        // the eye-dropper trigger takes the focus
                        let trigger = e
                            .target()
                            .and_then(|t| t.dyn_into::<web_sys::Element>().ok())
                            .and_then(|t| t.parent_element())
                            .and_then(|p| {
                                p.query_selector(".excalidraw-eye-dropper-trigger")
                                    .ok()
                                    .flatten()
                            })
                            .and_then(|t| t.dyn_into::<HtmlElement>().ok());
                        if let Some(t) = trigger {
                            let _ = t.focus();
                        }
                    }
                    _ => {}
                }
                e.stop_propagation();
            });
        focus_on_mount(el, props.section == Some(Section::Hex))
    };
    let mut label = Element::new("div")
        .attr(
            "class",
            class_names([
                ("color-picker__input-label", true),
                ("has-error", error.is_some()),
            ]),
        )
        .child(
            Element::new("div")
                .attr("class", "color-picker__input-hash")
                .child(Node::text("#")),
        )
        .child(input);
    if !props.phone {
        let alt = get_shortcut_key("Alt", props.is_darwin, &KeyLabels::EN);
        let title = format!("{} — I or {alt} ", color_picker_text("labels.eyeDropper"));
        label = label
            .child(
                Element::new("div")
                    .style("width", "1px")
                    .style("height", "1.25rem")
                    .style("background-color", "var(--default-border-color)"),
            )
            .child(
                Element::new("div")
                    .attr(
                        "class",
                        class_names([
                            ("excalidraw-eye-dropper-trigger", true),
                            ("selected", props.eye_dropper_active),
                        ]),
                    )
                    .on("click", move |_| emit(ColorPickerEvent::EyeDropperTrigger))
                    .attr("title", title)
                    .child(icon("eyeDropperIcon")),
            );
    }
    Element::new("div")
        .child(heading("colorPicker.hexCode"))
        .child(
            Element::new("div")
                .attr("class", "color-picker__input-label-container")
                .child(label)
                .child_opt(error.map(|key| {
                    Element::new("div")
                        .attr("class", "color-picker__error-message")
                        .attr("role", "alert")
                        .child(Node::text(color_picker_text(key)))
                })),
        )
        .into()
}

