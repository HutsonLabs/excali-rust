/// A change of the hex input: the colour it picks (`onChange`), if any,
/// and the input's state.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct HexChange {
    pub color: Option<String>,
    pub state: HexInputState,
}

/// `changeColor` (`ColorInput.tsx:41-60`): the typed value lowercased and
/// trimmed picks its colour ([`normalize_input_color`]) when it is one;
/// otherwise empty is no error, hex digits of the wrong length are
/// `invalidHexLength`, anything else `invalidColor`.
pub fn change_hex_input(value: &str) -> HexChange {
    let value = js_trim(&value.to_lowercase()).to_owned();
    let color = normalize_input_color(&value);
    let error = if color.is_some() || value.is_empty() {
        None
    } else {
        let digits = value.strip_prefix('#').unwrap_or(&value);
        if !digits.is_empty()
            && digits
                .bytes()
                .all(|b| b.is_ascii_hexdigit() && !b.is_ascii_uppercase())
        {
            Some("colorPicker.invalidHexLength")
        } else {
            Some("colorPicker.invalidColor")
        }
    };
    HexChange {
        color,
        state: HexInputState {
            inner_value: value,
            error,
        },
    }
}

/// What the input shows for its state (`value`, `ColorInput.tsx:92`):
/// the value without one leading `#`.
pub fn hex_input_value(inner_value: &str) -> String {
    inner_value
        .strip_prefix('#')
        .unwrap_or(inner_value)
        .to_owned()
}

