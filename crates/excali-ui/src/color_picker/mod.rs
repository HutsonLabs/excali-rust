//! The colour picker (`components/ColorPicker/*`): the top-picks strip
//! (`TopPicks.tsx`), the trigger swatch that shows the active colour, and
//! the popup (`ColorPicker.tsx`, `Picker.tsx`) with the most-used custom
//! colours (`CustomColorList.tsx`), the 5×3 palette with its q…b hotkeys
//! (`PickerColorList.tsx`), the shades of the picked hue (`ShadeList.tsx`),
//! the hex input with the eye-dropper trigger (`ColorInput.tsx`), and the
//! keyboard map ([`keyboard`], `keyboardNavHandlers.ts`); the eye dropper
//! itself is [`eye_dropper`] (`EyeDropper.tsx`).
//!
//! [`color_picker`] builds the DOM for the host's state
//! ([`ColorPickerProps`]); what the user does comes back as
//! [`ColorPickerEvent`]s, which the host applies with the state functions
//! here ([`toggle_popup`], [`close_popup`], [`toggle_eye_dropper`],
//! [`escape`], [`change_hex_input`]) and renders again. The palettes and
//! colour helpers are `packages/common/src/colors.ts`'s, in
//! [`excali_core::color`]. With `customizableTopPicks`
//! ([`ColorPickerProps::customizable_top_picks`], `colorTopPicksDnD.ts`)
//! a swatch or the trigger dragged onto the strip pins its colour, a pick
//! dragged along the strip reorders it (both through
//! [`crate::top_picks_dnd`]), the strip's context menu resets it and the
//! popup shows the tip; the host keeps the picks in
//! `appState.colorTopPicks` ([`color_top_picks_update`]).
//!
//! See `site/content/research/ui-design-system.md` sections 2 and 3.12.

