/// `PickerColorList` (`PickerColorList.tsx`): the palette in its 5×3 grid.
fn picker_color_list(
    props: &ColorPickerProps,
    palette: &[PaletteEntry],
    active_shade: usize,
    focus: bool,
) -> Node {
    let obj = get_color_name_and_shade(palette, props.color.as_deref());
    let show_hotkey = props.mode != StylesPanelMode::Mobile;
    let buttons = palette.iter().enumerate().map(|(index, (key, value))| {
        let color = match value {
            PaletteColor::Shades(shades) => shades.get(active_shade).copied(),
            PaletteColor::Single(c) => Some(*c),
        }
        .filter(|c| !c.is_empty())
        .unwrap_or("transparent");
        if props.excluded_colors.iter().any(|c| c == color) {
            // an invisible placeholder keeps the grid positions and hotkeys
            return Element::new("div")
                .attr("class", "color-picker__button color-picker__button--large")
                .style("visibility", "hidden")
                .attr("aria-hidden", "true")
                .into();
        }
        let keybinding = COLOR_PICKER_HOTKEY_BINDINGS
            .get(index)
            .copied()
            .unwrap_or("undefined");
        let display = props.display_color(color);
        // t(`colors.${key.replace(/\d+/, "")}`, null, "")
        let name: String = {
            let start = key.find(|c: char| c.is_ascii_digit());
            match start {
                Some(s) => {
                    let end = key[s..]
                        .find(|c: char| !c.is_ascii_digit())
                        .map_or(key.len(), |e| s + e);
                    format!("{}{}", &key[..s], &key[end..])
                }
                None => (*key).to_owned(),
            }
        };
        let locale_key = format!("colors.{name}");
        let label = match color_picker_text(&locale_key) {
            l if l == locale_key => "",
            l => l,
        };
        let hex = if color.starts_with('#') {
            format!(" {color}")
        } else {
            String::new()
        };
        let active = obj.is_some_and(|o| o.color_name == *key);
        let el = Element::new("button")
            .attr("tabindex", "-1")
            .attr("type", "button")
            .attr(
                "class",
                class_names([
                    ("color-picker__button color-picker__button--large", true),
                    ("has-outline", !is_color_dark(color, Some(255.0))),
                    ("active", active),
                    ("is-transparent", color == "transparent"),
                ]),
            )
            .on(
                "click",
                props.handler(ColorPickerEvent::Pick {
                    color: color.to_owned(),
                    section: Section::BaseColors,
                }),
            )
            .attr("title", format!("{label}{hex} — {keybinding}"))
            .attr("aria-label", format!("{label} — {keybinding}"))
            .style("--swatch-color", display.as_str())
            .attr("data-testid", format!("color-{key}"))
            .child(outline())
            .child_opt(show_hotkey.then(|| hotkey_label(&display, keybinding, false)));
        let el = draggable(el, props, Some(color), DragOrigin::Source);
        focus_on_mount(el, focus && active).into()
    });
    Element::new("div")
        .attr("class", "color-picker-content--default")
        .children_from(buttons)
        .into()
}

