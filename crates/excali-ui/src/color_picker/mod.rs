/// A colour's palette entry and shade.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ColorObj {
    pub color_name: &'static str,
    /// `None` for a single colour (transparent, white, black).
    pub shade: Option<usize>,
}

/// `getColorNameAndShadeFromColor` (`colorPickerUtils.ts:12-36`): the
/// first palette entry holding `color`; `None` for no colour or one the
/// palette does not have.
pub fn get_color_name_and_shade(palette: &[PaletteEntry], color: Option<&str>) -> Option<ColorObj> {
    let color = color.filter(|c| !c.is_empty())?;
    palette.iter().find_map(|(name, value)| match value {
        PaletteColor::Shades(shades) => shades.iter().position(|s| *s == color).map(|i| ColorObj {
            color_name: name,
            shade: Some(i),
        }),
        PaletteColor::Single(c) => (*c == color).then_some(ColorObj {
            color_name: name,
            shade: None,
        }),
    })
}

/// `isCustomColor` (`colorPickerUtils.ts:44-53`): the palette does not
/// hold `color`.
pub fn is_custom_color(color: &str, palette: &[PaletteEntry]) -> bool {
    !palette.iter().any(|(_, value)| match value {
        PaletteColor::Shades(shades) => shades.contains(&color),
        PaletteColor::Single(c) => *c == color,
    })
}

/// `getMostUsedCustomColors` (`colorPickerUtils.ts:55-93`): the custom
/// (non-palette, not fully transparent) stroke or background colours of
/// the live elements, most used first (ties in first-use order), at most
/// [`MAX_CUSTOM_COLORS_USED_IN_CANVAS`]. The canvas background picker
/// reads the background colours.
pub fn get_most_used_custom_colors(
    elements: &[SceneElement],
    ty: ColorPickerType,
    palette: &[PaletteEntry],
) -> Vec<String> {
    let mut counts: Vec<(&str, usize)> = Vec::new();
    for element in elements.iter().filter(|e| !e.base.is_deleted) {
        let color = match ty {
            ColorPickerType::ElementStroke => element.base.stroke_color.as_str(),
            _ => element.base.background_color.as_str(),
        };
        if is_transparent(color) || !is_custom_color(color, palette) {
            continue;
        }
        match counts.iter_mut().find(|(c, _)| *c == color) {
            Some(entry) => entry.1 += 1,
            None => counts.push((color, 1)),
        }
    }
    // Array.prototype.sort is stable
    counts.sort_by_key(|c| std::cmp::Reverse(c.1));
    counts
        .into_iter()
        .take(MAX_CUSTOM_COLORS_USED_IN_CANVAS)
        .map(|(c, _)| c.to_owned())
        .collect()
}

/// The custom colours a picker opens with (`Picker.tsx:84-89`): none for
/// the canvas background, else [`get_most_used_custom_colors`]. Upstream
/// samples them once, when the popup opens.
pub fn picker_custom_colors(
    ty: ColorPickerType,
    elements: &[SceneElement],
    palette: &[PaletteEntry],
) -> Vec<String> {
    match ty {
        ColorPickerType::CanvasBackground => Vec::new(),
        _ => get_most_used_custom_colors(elements, ty, palette),
    }
}

/// The section the popup starts in (`Picker.tsx:103-122`, run while no
/// section is active): none for a custom colour missing from the custom
/// list, the custom list for one in it, the shades for a hue, else the
/// palette.
pub fn initial_section(
    color: Option<&str>,
    palette: &[PaletteEntry],
    custom_colors: &[String],
) -> Option<Section> {
    let is_custom = color.is_some_and(|c| !c.is_empty() && is_custom_color(c, palette));
    let listed = color.is_some_and(|c| custom_colors.iter().any(|x| x == c));
    if is_custom && !listed {
        None
    } else if is_custom {
        Some(Section::Custom)
    } else if get_color_name_and_shade(palette, color).is_some_and(|o| o.shade.is_some()) {
        Some(Section::Shades)
    } else {
        Some(Section::BaseColors)
    }
}

/// The shade the palette's hues show (`Picker.tsx:124-130`): the picked
/// colour's, else the element default's for the picker.
pub fn initial_active_shade(ty: ColorPickerType, obj: Option<&ColorObj>) -> usize {
    obj.and_then(|o| o.shade).unwrap_or(match ty {
        ColorPickerType::ElementBackground => DEFAULT_ELEMENT_BACKGROUND_COLOR_INDEX,
        _ => DEFAULT_ELEMENT_STROKE_COLOR_INDEX,
    })
}

