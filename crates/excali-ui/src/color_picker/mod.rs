impl ColorPickerProps {
    fn compact(&self) -> bool {
        self.mode != StylesPanelMode::Full
    }

    fn emit(&self, event: ColorPickerEvent) {
        if let Some(f) = &self.on_event {
            f(event);
        }
    }

    fn handler(&self, event: ColorPickerEvent) -> impl Fn(&Event) + 'static {
        let on_event = self.on_event.clone();
        move |_| {
            if let Some(f) = &on_event {
                f(event.clone());
            }
        }
    }

    fn display_color(&self, color: &str) -> String {
        apply_dark_mode_filter(color, self.theme == Theme::Dark)
    }
}

