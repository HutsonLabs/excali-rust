/// The browser facts the dialog reads when upstream's modules load
/// (`common/src/editorInterface.ts:37-43`, `clipboard.ts:68-72`).
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct Platform {
    /// `isDarwin`: Cmd for CtrlOrCmd, Option for Alt.
    pub darwin: bool,
    /// `isWindows`: redo also reads Ctrl+Y.
    pub windows: bool,
    /// `isFirefox`: one command palette shortcut; copy as PNG always shown.
    pub firefox: bool,
    /// `probablySupportsClipboardBlob`.
    pub clipboard_blob: bool,
}

/// One `Shortcut` row: its label and shortcuts, each a `+`-joined string
/// as upstream passes it (split by [`shortcut_keys`]).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ShortcutRow {
    pub label: String,
    pub shortcuts: Vec<String>,
    /// `isOr`: "or" between the shortcuts; otherwise they are one sequence.
    pub is_or: bool,
}

/// One `ShortcutIsland`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ShortcutIsland {
    /// `HelpDialog__island--tools`, `--view` or `--editor`.
    pub class_name: &'static str,
    pub caption: String,
    pub rows: Vec<ShortcutRow>,
}

/// `upperCaseSingleChars` (`HelpDialog.tsx:91-93`): the first lone
/// lowercase ASCII letter (`/\b[a-z]\b/`, not global) upper-cased.
fn upper_case_single_chars(key: &str) -> String {
    let word = |c: Option<char>| c.is_some_and(|c| c.is_ascii_alphanumeric() || c == '_');
    let chars: Vec<char> = key.chars().collect();
    for i in 0..chars.len() {
        let before = i.checked_sub(1).map(|j| chars[j]);
        if chars[i].is_ascii_lowercase() && !word(before) && !word(chars.get(i + 1).copied()) {
            let mut out = chars.clone();
            out[i] = chars[i].to_ascii_uppercase();
            return out.into_iter().collect();
        }
    }
    key.to_owned()
}

/// The keys of one shortcut as `Shortcut` shows them
/// (`HelpDialog.tsx:104-111`): split on `+`, a trailing `++` ending in the
/// `+` key, each key through `upperCaseSingleChars`.
pub fn shortcut_keys(shortcut: &str) -> Vec<String> {
    let keys: Vec<&str> = match shortcut.strip_suffix("++") {
        Some(head) => head.split('+').chain(["+"]).collect(),
        None => shortcut.split('+').collect(),
    };
    keys.into_iter().map(upper_case_single_chars).collect()
}

