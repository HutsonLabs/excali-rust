//! The help dialog (`components/HelpDialog.tsx`, `HelpDialog.scss`): a
//! [`dialog`] titled "Help" with the header links (documentation, blog,
//! GitHub issues, YouTube) and, under "Keyboard shortcuts", the Tools,
//! View and Editor islands (research `ui-design-system.md` §3.5).
//!
//! [`shortcut_islands`] is the dialog's content as data, per [`Platform`]
//! (`isDarwin` picks Cmd and Option, `isWindows` adds Ctrl+Y to redo,
//! `isFirefox` drops the second command palette shortcut, and copy as PNG
//! needs `probablySupportsClipboardBlob` or Firefox) and whether the host
//! enables the theme action (`UIOptions.canvasActions.toggleTheme`,
//! `actionToggleTheme.predicate`); [`help_dialog`] builds the DOM upstream
//! leaves from it (`tests/help_dialog.rs` holds every case of
//! `tests/fixtures/help-dialog.json` to it), and
//! [`shortcuts_page_section`] the section of the shortcuts page
//! (`site/content/design-system/shortcuts.md`) that lists it.
//!
//! The host opens the dialog while `appState.openDialog.name` is `"help"`
//! (`LayerUI.tsx:577-583`, [`crate::footer::toggle_shortcuts`]) and on
//! close applies [`close_help_dialog`].

